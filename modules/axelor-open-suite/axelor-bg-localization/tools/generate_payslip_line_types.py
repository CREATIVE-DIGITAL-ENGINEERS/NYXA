def render(r):
    return ";".join(('"%s"' % v) if ";" in v else v for v in r)

def check(rows, head):
    for r in rows:
        assert len(r) == len(head.split(";")), r[1]
        for v in r:
            assert ";" not in v and '"' not in v and "\n" not in v, (r[1], v[:40])

