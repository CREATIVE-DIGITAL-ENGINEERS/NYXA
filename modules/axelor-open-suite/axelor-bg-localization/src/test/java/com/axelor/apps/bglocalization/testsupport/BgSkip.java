package com.axelor.apps.bglocalization.testsupport;

import org.junit.jupiter.api.Assumptions;

/**
 * Пропускане на тест с ПРОЧЕТИМА причина.
 *
 * <p><b>Защо съществува.</b> {@code Assumptions.assumeTrue(false, "причина")} хвърля изключение,
 * чието съобщение Gradle НЕ записва в XML отчета: там остава празният елемент {@code <skipped/>}.
 * Тоест причината съществува в кода и не съществува за никого, който чете отчета — а пропуснат тест
 * без причина е неразличим от тест, който някой е изключил, за да мине билдът.
 *
 * <p>Проверено върху двата пропуснати теста за банковите извлечения: и двата подават текст на
 * {@code assumeTrue}, и в двата случая отчетът показва {@code <skipped/>}.
 *
 * <p>Оттам този помощник: причината се ПЕЧАТА (Gradle я хваща в {@code <system-out>} на теста) и
 * чак тогава тестът се прекъсва. Съобщението остава и в изключението — за средите, които го четат.
 */
public final class BgSkip {

  /** Префиксът прави причините намираеми с едно търсене в лога и в отчета. */
  public static final String PREFIX = "⏭ ПРОПУСНАТ — ";

  private BgSkip() {}

  /**
   * Прекъсва текущия тест и оставя причината видима в отчета.
   *
   * @param reason защо това твърдение не е проверено — пълно изречение, не код за грешка
   */
  public static void because(String reason) {
    System.out.println(PREFIX + reason);
    Assumptions.abort(reason);
  }
}
