  /**
   * РОДЕНИЯТ ПРЕДИ 1960 НЯМА УПФ, роденият след 1959 има — двете кохорти, поотделно.
   *
   * <p>Свидетелят е поискан изрично: 1958 → без ДЗПО, 1970 → с ДЗПО. На ниво seed това е точно
   * „няма ред UPF за WITHOUT_UPF“ и „има ред UPF за WITH_UPF“, а петте пункта стоят във фонд
   * „Пенсии“ (11,02 срещу 8,22 при осигурителя).
   */
  @Test
  @DisplayName("97 · роден 1958 → без ДЗПО (11,02/8,78); роден 1970 → с ДЗПО (8,22/6,58 + 2,8/2,2)")
  void code97SplitsTheTwoCohorts() {
    assertEquals(
        "11.0200/8.7800",
        rateOf("97", "PENSION", "WITHOUT_UPF"),
        "роден 1958 · целите 19,8 стоят във фонд „Пенсии“, разпределени по чл. 6 ал. 3");
    assertEquals(
        null,
        rateOf("97", "UPF", "WITHOUT_UPF"),
        "роден 1958 · НЕ подлежи на ДЗПО — ред за УПФ при WITHOUT_UPF би му удържал 2,2 без основание");
    assertEquals(
        "8.2200/6.5800",
        rateOf("97", "PENSION", "WITH_UPF"),
        "роден 1970 · фонд „Пенсии“ 14,8 след като 5-те пункта са излезли към УПФ");
    assertEquals(
        "2.8000/2.2000",
        rateOf("97", "UPF", "WITH_UPF"),
        "роден 1970 · УПФ 5 със сплит по чл. 6 ал. 3");
  }

