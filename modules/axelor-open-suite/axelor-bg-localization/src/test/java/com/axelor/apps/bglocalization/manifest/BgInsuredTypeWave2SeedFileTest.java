  /**
   * <b>⚠️ ТУК ТАБЛИЦАТА ОПРОВЕРГА ОТГОВОРА, И ПЕЧЕЛИ ТАБЛИЦАТА.</b>
   *
   * <p>Заданието и попълненият въпросник казваха „платец: ЛИЦЕТО“. Забележка 9 под таблицата казва
   * обратното и го казва дословно: <i>„Дължимите социални и здравноосигурителни вноски за
   * учениците, включени в обучение чрез работа (дуална система на обучение), са изцяло за сметка на
   * държавния бюджет.“</i> Съответно разд. 19.1 оставя колоната „за сметка на осигуреното лице“
   * ПРАЗНА и слага звездичка на всяко число в колоната на осигурителя.
   *
   * <p>Разликата не е козметична: ученик на минимална заплата би получил удръжка от порядъка на
   * 13,78 на сто от брутното, която не му се полага.
   */
  @Test
  @DisplayName("42 · нула лична вноска — вноските са изцяло за сметка на държавния бюджет (заб. 9)")
  void code42IsPaidEntirelyByTheStateBudget() {
    List<String> offenders = new ArrayList<>();
    for (String[] r : rowsOf("42")) {
      if (dec(cell(r, "employeeRate")).signum() != 0) {
        offenders.add(
            cell(r, "importId") + " · " + cell(r, "fundCode") + " = " + cell(r, "employeeRate"));
      }
    }
    if (!offenders.isEmpty()) {
      fail(
          "НАП Приложение 1 заб. 9: вноските за учениците в дуална система са ИЗЦЯЛО за сметка на"
              + " държавния бюджет. Тези редове удържат от ученика:\n    "
              + String.join("\n    ", offenders)
              + "\n\n  ⚠️ Ако някой източник твърди „платец: лицето“ — той е по-стар от заб. 9 или"
              + " бърка платеца с работодателя, който подава декларацията.");
    }
    assertTrue(rowsOf("42").size() >= 5, "код 42 · очакван пълен набор фондове по разд. 19");
  }

  // ═══ 82 · ИЗБОРНИ ДЛЪЖНОСТИ И ДУХОВНИ ЗВАНИЯ ═════════════════════════════

  /**
   * Код 82 върви по ставките на код 01 — защото шапката на разд. 1 го изброява ПОИМЕННО.
   *
   * <p>„…лица, упражняващи трудова дейност на изборни длъжности и служителите с духовно звание на
   * Българската православна църква и регистрирани вероизповедания“ стои в самото заглавие на разд.
   * 1, тоест таблицата не му дава собствен ред, а го слага при общия случай. Затова тестът иска
   * РАВЕНСТВО с 01, а не заковани числа: смени ли се 01 по ЗБДОО 2027, 82 трябва да се смени с
   * него.
   *
   * <p><b>⚠️ БЕЗ ГВРС.</b> Изборната длъжност и духовното звание НЕ са трудово правоотношение, а
   * ЗГВРС чл. 2 покрива само работници и служители в трудово правоотношение — както при ДУК (10).
   */
  @Test
  @DisplayName("82 · дословно ставките на 01, но без ГВРС (не е трудово правоотношение)")
  void code82ReplicatesCode01WithoutGvrs() {
    for (String fund : Arrays.asList("PENSION", "UPF", "OZM", "UNEMPLOYMENT", "HEALTH")) {
      for (String regime : Arrays.asList("WITH_UPF", "WITHOUT_UPF", "ANY")) {
        String template = rateOf("01", fund, regime);
        if (template == null) {
          continue;
        }
        assertEquals(
            template,
            rateOf("82", fund, regime),
            "вид осигурен 82 · " + fund + " · " + regime + " трябва да е дословно като код 01");
      }
    }
    assertTrue(
        !fundsOf("82").contains("GVRS"),
        "код 82 не е трудово правоотношение — ГВРС по ЗГВРС чл. 2 не се дължи");
  }

  // ═══ 95 · БАЛЕТ ══════════════════════════════════════════════════════════

  /**
   * <b>⚠️ И ТУК ТАБЛИЦАТА ОПРОВЕРГА ЗАДАНИЕТО.</b> Заданието казваше „БЕЗ +3пп (не е I/II)“.
   *
   * <p>Двете твърдения са РАЗЛИЧНИ и само едното е вярно. Категорията НАИСТИНА е трета — това е
   * сверено и оттам код 95 няма професионален пенсионен фонд (ППФ). Но +3-те пункта НЕ идват от
   * категорията: те са надбавката за ранното пенсиониране по чл. 69а КСО и разд. 8 на таблицата ги
   * показва черно на бяло — за сметка на ОСИГУРИТЕЛЯ и при двете кохорти:
   *
   * <ul>
   *   <li>разд. 8.1 (роден преди 1960): за осигурителя „За ДОО 16,72“ срещу 13,72 при код 01
   *   <li>разд. 8.2 (роден след 1959): за осигурителя „13,92“ срещу 10,92 при код 01
   * </ul>
   *
   * <p>И в двата случая личната вноска е НЕПРОМЕНЕНА (10,58 и 8,38) — тоест надбавката пада изцяло
   * върху работодателя. Разликата 16,72 − 13,72 = 3,00 се вижда след изваждането на ОЗМ (2,1) и
   * безработицата (0,6): 14,02 срещу 11,02 във фонд „Пенсии“.
   */
  @Test
  @DisplayName(
      "95 · фонд Пенсии носи +3пп САМО при осигурителя (чл. 69а), личната вноска е като 01")
  void code95CarriesTheArt69aSurcharge() {
    assertEquals(
        "14.0200/8.7800",
        rateOf("95", "PENSION", "WITHOUT_UPF"),
        "НАП Приложение 1 разд. 8.1 — 11,02 + 3,00 при осигурителя, лицето остава на 8,78");
    assertEquals(
        "11.2200/6.5800",
        rateOf("95", "PENSION", "WITH_UPF"),
        "НАП Приложение 1 разд. 8.2 — 8,22 + 3,00 при осигурителя, лицето остава на 6,58");

    BigDecimal art69a =
        dec(rateOf("95", "PENSION", "WITH_UPF").split("/")[0])
            .subtract(dec(rateOf("01", "PENSION", "WITH_UPF").split("/")[0]));
    assertEquals(
        0,
        art69a.compareTo(dec("3.00")),
        "надбавката по чл. 69а е точно 3 процентни пункта, а излезе " + art69a);
  }

