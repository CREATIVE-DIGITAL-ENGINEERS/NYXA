  /**
   * Сборът на ставките при ЛИЦЕТО за една кохорта — позволителното {@code ANY} влиза и в двете.
   *
   * <p>⚠️ Точно затова редът на ОЗМ при код 96 е {@code ANY}, а не два реда: рискът не зависи от
   * ДЗПО кохортата и разцепен на два, щеше да иска две поправки при всяка промяна на ставката.
   */
  private static String totalFor(String code, String regime) {
    BigDecimal total = BigDecimal.ZERO;
    for (String[] r : rowsOf(code)) {
      String rowRegime = cell(r, "bgUpfRegime");
      if ("ANY".equals(rowRegime) || regime.equals(rowRegime)) {
        total = total.add(dec(cell(r, "employeeRate")));
      }
    }
    return total.toPlainString();
  }
