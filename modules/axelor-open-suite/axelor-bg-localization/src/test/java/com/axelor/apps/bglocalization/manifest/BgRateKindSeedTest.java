  /** Видовете, които ТВЪРДЯТ, че стойност няма — тоест ставката задължително е нула. */
  private static final Set<String> MUST_BE_ZERO =
      new HashSet<>(Arrays.asList("LEGAL_ZERO", "STRUCTURAL_ZERO", "MISSING"));

  private static final String[][] RATES = {
    {"employerRate", "bgEmployerRateKind", "работодател"},
    {"employeeRate", "bgEmployeeRateKind", "лице"},
  };

  @Test
  @DisplayName("ФАЙЛ · ⚠️ ИНВАРИАНТ: всяка ставка носи обявен вид и не си противоречи с него")
  void everyRateDeclaresAKindThatMatchesIt() {
    List<String> head = BgSeed.header(FILE);
    List<String[]> rows = BgSeed.rows(FILE);
    List<String> problems = new ArrayList<>();

    for (String[] row : rows) {
      String id = BgSeed.col(head, row, "importId");
      for (String[] rate : RATES) {
        String raw = BgSeed.col(head, row, rate[0]);
        String kind = BgSeed.col(head, row, rate[1]);
        String where = id + " (" + rate[2] + ", " + rate[0] + "=" + raw + ")";

        // ⚠️ ред без обявен вид
        if (kind.trim().isEmpty()) {
          problems.add(where + ": вид не е обявен — мълчаливо подразбиране няма");
          continue;
        }
        // ⚠️ вид, който не е сред разрешените
        if (!ALLOWED.contains(kind)) {
          problems.add(
              where + ": вид „" + kind + "“ не е сред " + new java.util.TreeSet<>(ALLOWED));
          continue;
        }

        boolean zero = new BigDecimal(raw).signum() == 0;
        // ⚠️ ставка 0,0000 с вид VALUE
        if (zero && "VALUE".equals(kind)) {
          problems.add(
              where
                  + ": нула, обявена за VALUE — ако ставката наистина е нула, кажи КОЯ нула"
                  + " (LEGAL_ZERO, STRUCTURAL_ZERO или MISSING)");
        }
        // ⚠️ ставка различна от нула с вид MISSING или STRUCTURAL_ZERO (и LEGAL_ZERO)
        if (!zero && MUST_BE_ZERO.contains(kind)) {
          problems.add(
              where + ": вид „" + kind + "“ твърди, че стойност няма, а ставката не е нула");
        }
      }
    }

    if (!problems.isEmpty()) {
      fail(
          "противоречия между ставка и обявен вид ("
              + problems.size()
              + "):\n  "
              + String.join("\n  ", problems));
    }
  }

