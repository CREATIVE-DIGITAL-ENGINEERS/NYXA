package com.axelor.apps.bglocalization.service.vat;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertNotNull;
import static org.junit.jupiter.api.Assertions.assertSame;
import static org.junit.jupiter.api.Assertions.assertTrue;

import com.axelor.apps.bglocalization.service.vat.adapter.BgVatDeclarationAdapter;
import com.axelor.apps.bglocalization.service.vat.adapter.BgVatPurchaseAdapter;
import com.axelor.apps.bglocalization.service.vat.adapter.BgVatSalesAdapter;
import com.axelor.apps.bglocalization.service.vat.adapter.BgVatViesAdapter;
import com.axelor.apps.bglocalization.service.vat.dto.BgVatExportRequestDto;
import com.axelor.apps.bglocalization.service.vat.dto.BgVatExportResultDto;
import com.axelor.apps.bglocalization.service.vat.dto.BgVatGeneratedFileDto;
import com.axelor.apps.bglocalization.service.vat.dto.BgVatPreparedFile;
import com.axelor.apps.bglocalization.service.vat.dto.BgVatPreparedPackage;
import com.axelor.apps.bglocalization.service.vat.dto.BgVatSalesRowDto;
import com.axelor.apps.bglocalization.service.vat.dto.BgVatValidationErrorDto;
import java.io.IOException;
import java.math.BigDecimal;
import java.nio.charset.Charset;
import java.util.Collections;
import java.util.List;
import org.junit.jupiter.api.Test;

/**
 * Pure (no DB / no Guice) tests for {@link BgVatPackageBuilder}: a normal four-file package, an
 * explicit zero declaration built from the real adapters, per-file hashes/sizes/record counts, and
 * the byte-identity guarantee (preview uses the exact generated bytes).
 */
class BgVatPackageBuilderTest {

  private static final Charset CP1251 = Charset.forName("windows-1251");

  private BgVatGeneratedFileDto file(String scope, String name, byte[] content) {
    return new BgVatGeneratedFileDto(scope, name, null, null, content);
  }

  private BgVatExportResultDto result(int documentsFound, BgVatGeneratedFileDto... files) {
    BgVatExportResultDto r = new BgVatExportResultDto();
    r.setReportType("all");
    r.setCompanyName("Test ООД");
    r.setPeriodLabel("2026-06");
    r.setDocumentsFound(documentsFound);
    r.setTotalBase(new BigDecimal("1000.00"));
    r.setTotalVat(new BigDecimal("200.00"));
    r.setTotalGross(new BigDecimal("1200.00"));
    Collections.addAll(r.getGeneratedFiles(), files);
    return r;
  }

  // --- Normal four-file package ---------------------------------------------

  @Test
  void normalPackage_fourFiles_hashesAndSizes() {
    byte[] sales = "PRODAGBI-ROW\r\n".getBytes(CP1251);
    byte[] purch = "POKUPKI-ROW\r\n".getBytes(CP1251);
    byte[] decl = ("D".repeat(590) + "\r\n").getBytes(CP1251);
    byte[] vies = "VHR...\r\nVIR...\r\n".getBytes(CP1251);

    BgVatExportResultDto r =
        result(
            3,
            file("sales", "PRODAGBI.TXT", sales),
            file("purchases", "POKUPKI.TXT", purch),
            file("declaration", "DEKLAR.TXT", decl),
            file("vies", "VIES.TXT", vies));
    r.getSalesRows().add(new BgVatSalesRowDto());
    r.getSalesRows().add(new BgVatSalesRowDto());

    BgVatPreparedPackage pkg = BgVatPackageBuilder.build(r);

    assertEquals(4, pkg.getFiles().size());
    assertTrue(!pkg.isZeroDeclaration(), "3 documents ⇒ not a zero declaration");
    assertEquals(BgVatPreparedPackage.READINESS_READY, pkg.getReadiness());

    for (BgVatPreparedFile f : pkg.getFiles()) {
      // Size and SHA-256 must match the exact bytes.
      byte[] content = f.getContent();
      assertEquals(content.length, f.getByteSize(), f.getFileName() + " size");
      assertEquals(BgVatHashUtil.sha256Hex(content), f.getSha256(), f.getFileName() + " sha256");
      assertEquals(BgVatPreparedFile.STATUS_OK, f.getStatus(), f.getFileName() + " status");
    }
    assertEquals(2, byScope(pkg, "sales").getRecordCount(), "sales record count = salesRows");
    assertEquals(1, byScope(pkg, "declaration").getRecordCount(), "DEKLAR = 1 record");
    assertEquals(1, byScope(pkg, "vies").getRecordCount(), "one VIR line");
  }

  // --- Explicit zero declaration (built from the REAL adapters) -------------

  @Test
  void zeroDeclaration_allFourFilesPresent_diariesEmpty() throws IOException {
    BgVatExportRequestDto request = new BgVatExportRequestDto();
    request.setCompanyVatNumber("BG100000065");
    request.setCompanyName("Test ООД");
    request.setEncoding("cp1251");

    BgVatFileWriter writer = new BgVatFileWriter();
    BgVatSalesAdapter salesAdapter = new BgVatSalesAdapter();

    byte[] salesBytes =
        writer.toBytes(salesAdapter.buildLines(Collections.emptyList(), request), "cp1251");
    byte[] purchaseBytes =
        writer.toBytes(new BgVatPurchaseAdapter().buildLines(Collections.emptyList()), "cp1251");
    byte[] declBytes =
        writer.toBytes(
            new BgVatDeclarationAdapter(salesAdapter)
                .buildLines(
                    Collections.emptyList(),
                    Collections.emptyList(),
                    new BgVatDeclarationAdapter.Header("BG100000065", "Test ООД", "202606", ""),
                    new BgVatDeclarationAdapter.ManualCells(
                        BigDecimal.ZERO,
                        BigDecimal.ZERO,
                        BigDecimal.ZERO,
                        BigDecimal.ZERO,
                        BigDecimal.ZERO,
                        BigDecimal.ZERO)),
            "cp1251");
    byte[] viesBytes =
        writer.toBytes(
            new BgVatViesAdapter(salesAdapter)
                .buildLines(
                    Collections.emptyList(),
                    new BgVatViesAdapter.RegisteredPerson("BG100000065", "Test ООД", "София"),
                    new BgVatViesAdapter.Declarant(
                        "6803030040", "Иван", "София", "1000", "ул.1", "A"),
                    "06/2026"),
            "cp1251");

    BgVatExportResultDto r =
        result(
            0,
            file("sales", "PRODAGBI.TXT", salesBytes),
            file("purchases", "POKUPKI.TXT", purchaseBytes),
            file("declaration", "DEKLAR.TXT", declBytes),
            file("vies", "VIES.TXT", viesBytes));

    BgVatPreparedPackage pkg = BgVatPackageBuilder.build(r);

    assertTrue(pkg.isZeroDeclaration(), "0 documents ⇒ zero declaration");
    assertEquals(4, pkg.getFiles().size(), "all four files present");

    BgVatPreparedFile salesFile = byScope(pkg, "sales");
    BgVatPreparedFile purchaseFile = byScope(pkg, "purchases");
    BgVatPreparedFile declFile = byScope(pkg, "declaration");
    BgVatPreparedFile viesFile = byScope(pkg, "vies");

    // Empty diaries: 0 bytes, 0 records, status empty.
    assertEquals(0, salesFile.getByteSize(), "empty PRODAGBI");
    assertEquals(BgVatPreparedFile.STATUS_EMPTY, salesFile.getStatus());
    assertEquals(0, purchaseFile.getByteSize(), "empty POKUPKI");
    assertEquals(BgVatPreparedFile.STATUS_EMPTY, purchaseFile.getStatus());

    // Valid zero DEKLAR: one real record.
    assertTrue(declFile.getByteSize() > 0, "DEKLAR is a real zero record");
    assertEquals(BgVatPreparedFile.STATUS_OK, declFile.getStatus());
    assertEquals(1, declFile.getRecordCount());

    // VIES header-only: present but zero ВОД rows.
    assertTrue(viesFile.getByteSize() > 0, "VIES header sections present");
    assertEquals(0, viesFile.getRecordCount(), "no VIR rows");

    // Hashes/sizes still consistent for every file.
    for (BgVatPreparedFile f : pkg.getFiles()) {
      assertEquals(f.getContent().length, f.getByteSize());
      assertEquals(BgVatHashUtil.sha256Hex(f.getContent()), f.getSha256());
    }
  }

  // --- Byte identity: preview == package == submission ----------------------

  @Test
  void preparedFile_reusesExactBytes_andIsDeterministic() {
    byte[] decl = ("X".repeat(590) + "\r\n").getBytes(CP1251);
    BgVatGeneratedFileDto generated = file("declaration", "DEKLAR.TXT", decl);
    BgVatExportResultDto r = result(1, generated);

    BgVatPreparedPackage first = BgVatPackageBuilder.build(r);
    BgVatPreparedPackage second = BgVatPackageBuilder.build(result(1, generated));

    BgVatPreparedFile f1 = byScope(first, "declaration");
    // The prepared file carries the SAME byte array (no copy/regeneration).
    assertSame(decl, f1.getContent(), "prepared file must reuse the generated bytes");
    // Deterministic: same bytes ⇒ same hash across builds.
    assertEquals(f1.getSha256(), byScope(second, "declaration").getSha256());
    assertEquals(BgVatHashUtil.sha256Hex(decl), f1.getSha256());
  }

  // --- Readiness reflects validation ----------------------------------------

  @Test
  void readiness_errorsAndWarnings() {
    BgVatExportResultDto withError = result(1, file("declaration", "DEKLAR.TXT", new byte[] {1}));
    withError
        .getValidationErrors()
        .add(new BgVatValidationErrorDto("X", BgVatValidationErrorDto.SEVERITY_ERROR, "bad"));
    assertEquals(
        BgVatPreparedPackage.READINESS_ERRORS, BgVatPackageBuilder.build(withError).getReadiness());

    BgVatExportResultDto withWarning = result(1, file("declaration", "DEKLAR.TXT", new byte[] {1}));
    withWarning.getWarnings().add("provisional layout");
    assertEquals(
        BgVatPreparedPackage.READINESS_WARNINGS,
        BgVatPackageBuilder.build(withWarning).getReadiness());
  }

  private BgVatPreparedFile byScope(BgVatPreparedPackage pkg, String scope) {
    List<BgVatPreparedFile> files = pkg.getFiles();
    for (BgVatPreparedFile f : files) {
      if (scope.equals(f.getScope())) {
        return f;
      }
    }
    assertNotNull(null, "missing file scope " + scope);
    return null;
  }
}
