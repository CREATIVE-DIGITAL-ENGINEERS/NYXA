      IF v_par_id IS NULL THEN
        blockers := blockers || format(
          E'\n  · [%s] REPARENT %s: новият родител %s липсва.', c.ccode, x.code, x.new_parent);
        CONTINUE;
      END IF;
      UPDATE account_account SET parent_account = v_par_id, updated_on = now() WHERE id = v_acc_id;
      n_reparented := n_reparented + 1;
    END LOOP;

    -- ── 1.4 · ШЕСТТЕ КОНВЕРСИИ КЪМ view ───────────────────────────────────────────────────────
    FOR x IN SELECT * FROM bg_n2_retype ORDER BY code LOOP
      SELECT acc.id, t.technical_type_select INTO v_acc_id, v_tech
        FROM account_account acc
        LEFT JOIN account_account_type t ON t.id = acc.account_type
       WHERE acc.company = c.cid AND acc.code = x.code;
      IF NOT FOUND THEN
        blockers := blockers || format(E'\n  · [%s] RETYPE %s: сметката липсва изобщо.',
                                       c.ccode, x.code);
        CONTINUE;
      END IF;
      IF v_tech = x.to_tech THEN
        n_skipped := n_skipped + 1;
        CONTINUE;
      END IF;
      IF v_tech IS DISTINCT FROM x.from_tech THEN
        blockers := blockers || format(
          E'\n  · [%s] RETYPE %s: тип %L, а се очакваше %L или вече %L.',
          c.ccode, x.code, v_tech, x.from_tech, x.to_tech);
        CONTINUE;
      END IF;

      -- ⚠️ ГЕЙТ. Репортен възел със собствено салдо е дефект: view сметка не се избира в
      -- интерфейса, тъй че салдото ѝ спира да се движи и тихо застива в баланса.
      SELECT count(*), coalesce(sum(ml.debit), 0) - coalesce(sum(ml.credit), 0)
        INTO v_posted, v_balance
        FROM account_move_line ml JOIN account_move m ON m.id = ml.move
       WHERE ml.account = v_acc_id AND m.status_select IN (2, 3);
      IF v_posted > 0 THEN
        blockers := blockers || format(
          E'\n  · [%s] RETYPE %s → view, но сметката НОСИ %s осчетоводени реда, салдо %s.' ||
          E'\n      Репортен възел не бива да има собствено салдо: първо реклас към листо (напр.' ||
          E' %s)\n      с РЕДОВНА счетоводна статия, чак после този файл.',
          c.ccode, x.code, v_posted, to_char(v_balance, 'FM999999999990.00'), x.reclass);
        CONTINUE;
      END IF;

      SELECT count(*) INTO v_cnt
        FROM account_account kid JOIN account_account par ON par.id = kid.parent_account
       WHERE kid.company = c.cid AND par.code = x.code AND kid.code = ANY(x.kids);
      IF v_cnt <> array_length(x.kids, 1) THEN
        blockers := blockers || format(
          E'\n  · [%s] RETYPE %s: под нея висят %s от очакваните %s деца.' ||
          E'\n      Възел без децата си е празна позиция в отчета.',
          c.ccode, x.code, v_cnt, array_length(x.kids, 1));
        CONTINUE;
      END IF;

      UPDATE account_account
         SET account_type = (SELECT id FROM account_account_type
                              WHERE technical_type_select = x.to_tech LIMIT 1),
             bg_ap_select = NULL,          -- възелът няма собствено салдо, тъй че няма и А/П ос
             updated_on = now()
       WHERE id = v_acc_id;
      n_retyped := n_retyped + 1;
      RAISE NOTICE 'BG_COA/N2   RETYPED [%] %: % → view (деца: %)',
        c.ccode, x.code, x.from_tech, array_to_string(x.kids, ', ');
    END LOOP;

    -- ── 1.5 · СТАТУС И А/П ОС ─────────────────────────────────────────────────────────────────
    -- ⚠️ Пипат се САМО редовете, чиято стойност се различава — инак `updated_on` на целия план
    -- скача при всяко пускане и идемпотентността става невидима в одита.
    UPDATE account_account acc
       SET status_select = tgt.status, updated_on = now()
      FROM bg_n2_acc tgt
     WHERE acc.company = c.cid AND acc.code = tgt.code
       AND acc.status_select IS DISTINCT FROM tgt.status;
    GET DIAGNOSTICS v_cnt = ROW_COUNT;
    n_status := n_status + v_cnt;

    UPDATE account_account acc
       SET bg_ap_select = tgt.ap, updated_on = now()
      FROM bg_n2_acc tgt
     WHERE acc.company = c.cid AND acc.code = tgt.code
       AND acc.bg_ap_select IS DISTINCT FROM tgt.ap;
    GET DIAGNOSTICS v_cnt = ROW_COUNT;
    n_ap := n_ap + v_cnt;

    -- ── 1.6 · Z124: ПАРКИНГ-КОДЪТ ОТ КРЪГ 1 ───────────────────────────────────────────────────
    -- ⚠️ МАХА СЕ САМО АКО Е ПРАЗНА. Z124 е пенсионираната „Текущ корпоративен данък“; кръг 1 ѝ
    -- смени кода, за да освободи 124 за НАП „Резултат при несъстоятелност и ликвидация“. Носи ли
    -- тя осчетоводени редове, изтриването или би паднало на чуждия ключ, или би отнесло история.
    -- Тогава решението е РЕКЛАС със счетоводна статия — на човек, не на този файл.
    SELECT acc.id INTO v_acc_id
      FROM account_account acc WHERE acc.company = c.cid AND acc.code = 'Z124';
    IF FOUND THEN
      SELECT count(*) INTO v_posted FROM account_move_line ml WHERE ml.account = v_acc_id;
      IF v_posted > 0 THEN
        blockers := blockers || format(
          E'\n  · [%s] Z124: носи %s реда в account_move_line и НЕ може да се махне.' ||
          E'\n      Пенсионираната 124 пази историята си. Реклас към 123 с РЕДОВНА статия, после' ||
          E' пак този файл.', c.ccode, v_posted);
      ELSE
        SELECT count(*) INTO v_cnt FROM account_accounting_report_config_line_account_set s
         WHERE s.account_set = v_acc_id;
        DELETE FROM account_accounting_report_config_line_account_set WHERE account_set = v_acc_id;
        DELETE FROM account_account_compatible_account_set
         WHERE account_account = v_acc_id OR compatible_account_set = v_acc_id;
        UPDATE account_account SET parent_account = NULL WHERE parent_account = v_acc_id;
        DELETE FROM account_account WHERE id = v_acc_id;
        n_removed := n_removed + 1;
        RAISE NOTICE 'BG_COA/N2   Z124 премахната [%] (празна; %s набора изчистени)', c.ccode, v_cnt;
      END IF;
    ELSE
      n_skipped := n_skipped + 1;
    END IF;

    -- ── 1.7 · ТВЪРДИТЕ ВРЪЗКИ ─────────────────────────────────────────────────────────────────
    -- ⚠️ ЗАЩО ВЪОБЩЕ. 609 и 601/602 стават репортни възли, а полетата сочат тях по many-to-one.
    -- Оставени така, отписването на актив и покупката на продукт биха се опитали да осчетоводят
    -- по view сметка — Move-ът хвърля при запис, в чужда транзакция, без ясно съобщение.
    FOR x IN SELECT * FROM bg_n2_fac LOOP
      SELECT acc.id INTO v_acc_id
        FROM account_account acc WHERE acc.company = c.cid AND acc.code = x.new_code;
      IF v_acc_id IS NULL THEN
        blockers := blockers || format(E'\n  · [%s] ДМА-връзка: сметка %s липсва.',
                                       c.ccode, x.new_code);
        CONTINUE;
      END IF;
      UPDATE account_fixed_asset_category fac
         SET realised_assets_value_account = v_acc_id, updated_on = now()
       WHERE fac.company = c.cid AND fac.import_id = c.ccode || '-' || x.import_suffix
         AND fac.realised_assets_value_account IS DISTINCT FROM v_acc_id;
      GET DIAGNOSTICS v_cnt = ROW_COUNT;
      n_binding := n_binding + v_cnt;
    END LOOP;

    FOR x IN SELECT * FROM bg_n2_am LOOP
      SELECT acc.id INTO v_acc_id
        FROM account_account acc WHERE acc.company = c.cid AND acc.code = x.new_code;
      IF v_acc_id IS NULL THEN
        blockers := blockers || format(E'\n  · [%s] Покупки-връзка: сметка %s липсва.',
                                       c.ccode, x.new_code);
        CONTINUE;
      END IF;
      UPDATE account_account_management am
         SET purchase_account = v_acc_id, updated_on = now()
       WHERE am.import_id = c.ccode || '-' || x.import_suffix
         AND am.purchase_account IS DISTINCT FROM v_acc_id;
      GET DIAGNOSTICS v_cnt = ROW_COUNT;
      n_binding := n_binding + v_cnt;
    END LOOP;

    -- ── 1.8 · СПРАВКИТЕ: ПРЕНАСОЧЕНИТЕ РЕДОВЕ ─────────────────────────────────────────────────
    FOR x IN SELECT * FROM bg_n2_remap LOOP
      SELECT cl.id, cl.account_code INTO v_acc_id, v_tech
        FROM account_accounting_report_config_line cl
       WHERE cl.import_id = c.ccode || '-' || x.import_suffix;
      IF NOT FOUND THEN
        blockers := blockers || format(
          E'\n  · [%s] REMAP %s: редът %s-%s липсва в базата.',
          c.ccode, x.line_code, c.ccode, x.import_suffix);
        CONTINUE;
      END IF;
      IF v_tech = x.new_acct THEN
        n_skipped := n_skipped + 1;
        CONTINUE;
      END IF;
      IF v_tech IS DISTINCT FROM x.old_acct THEN
        blockers := blockers || format(
          E'\n  · [%s] REMAP %s: accountCode е %L, а се очакваше %L или вече %L.',
          c.ccode, x.line_code, v_tech, x.old_acct, x.new_acct);
        CONTINUE;
      END IF;
      UPDATE account_accounting_report_config_line
         SET account_code = x.new_acct, updated_on = now() WHERE id = v_acc_id;
      -- ⚠️ СТАРИЯТ НАБОР СЕ ЧИСТИ ЗАДЪЛЖИТЕЛНО. Смятането прави accountSet ∪ LIKE(accountCode):
      -- остане ли там старата 452, тя се връща в отчета въпреки пренасочването, и то мълчаливо.
      DELETE FROM account_accounting_report_config_line_account_set
       WHERE account_accounting_report_config_line = v_acc_id;
      -- Пълни се само за ГОЛ ЕДИНИЧЕН код — точно каквото би направил пресен внос.
      IF x.new_acct !~ '[%,]' THEN
        INSERT INTO account_accounting_report_config_line_account_set
          (account_accounting_report_config_line, account_set)
        SELECT v_acc_id, acc.id FROM account_account acc
         WHERE acc.company = c.cid AND acc.code = x.new_acct;
      END IF;
      n_remap := n_remap + 1;
    END LOOP;

    -- ── 1.9 · СПРАВКИТЕ: НОВИТЕ РЕДОВЕ ────────────────────────────────────────────────────────
    -- Всичко освен code/accountCode/sequence/importId се КОПИРА от живия template ред, а не се
    -- предполага: така клонингът носи точно тези styleSelect/resultSelect/hidden, които тази база
    -- вече ползва за съседната сметка.
    FOR x IN SELECT * FROM bg_n2_newline ORDER BY import_suffix LOOP
      PERFORM 1 FROM account_accounting_report_config_line
        WHERE import_id = c.ccode || '-' || x.import_suffix;
      IF FOUND THEN
        n_skipped := n_skipped + 1;
        CONTINUE;
      END IF;
      SELECT rt.id INTO v_rt_id FROM account_accounting_report_type rt
       WHERE rt.import_id = c.ccode || '-' || x.rt;
      IF v_rt_id IS NULL THEN
        blockers := blockers || format(E'\n  · [%s] NEWLINE %s: справка %s липсва.',
                                       c.ccode, x.line_code, x.rt);
        CONTINUE;
      END IF;
      SELECT * INTO v_tpl FROM account_accounting_report_config_line cl
       WHERE cl.report_type = v_rt_id AND cl.code = x.tpl_code;
      IF NOT FOUND THEN
        blockers := blockers || format(
          E'\n  · [%s] NEWLINE %s: образецът %s липсва в справка %s.',
          c.ccode, x.line_code, x.tpl_code, x.rt);
        CONTINUE;
      END IF;
      v_new_id := nextval('public.account_accounting_report_config_line_seq');
      INSERT INTO account_accounting_report_config_line (
        id, version, archived, created_on, updated_on, created_by, updated_by,
        import_id, import_origin, process_instance_id, attrs,
        report_type, report_type_column, sequence, code, label,
        type_select, rule_type_select, style_select, detail_by_select, result_select,
        negate_value, rule, account_code, analytic_account_code,
        hidden, not_computed_if_intersect, balance_before_period,
        compute_other_period, compute_previous_year, hide_detailed_lines_without_moves,
        percentage_base_column, percentage_total_line, priority, style_priority,
        groups_without_column
      ) VALUES (
        v_new_id, 0, false, now(), NULL, NULL, NULL,
        c.ccode || '-' || x.import_suffix, v_tpl.import_origin, NULL, NULL,
        v_rt_id, v_tpl.report_type_column, x.seq, x.line_code, v_tpl.label,
        v_tpl.type_select, v_tpl.rule_type_select, v_tpl.style_select, v_tpl.detail_by_select,
        v_tpl.result_select, v_tpl.negate_value, NULL, x.acct, NULL,
        v_tpl.hidden, v_tpl.not_computed_if_intersect, v_tpl.balance_before_period,
        v_tpl.compute_other_period, v_tpl.compute_previous_year,
        v_tpl.hide_detailed_lines_without_moves, v_tpl.percentage_base_column,
        v_tpl.percentage_total_line, v_tpl.priority, v_tpl.style_priority,
        v_tpl.groups_without_column
      );
      IF x.acct !~ '[%,]' THEN
        INSERT INTO account_accounting_report_config_line_account_set
          (account_accounting_report_config_line, account_set)
        SELECT v_new_id, acc.id FROM account_account acc
         WHERE acc.company = c.cid AND acc.code = x.acct;
      END IF;
      n_lines := n_lines + 1;
    END LOOP;

    -- ── 1.10 · СПРАВКИТЕ: ДОПЪЛНЕНИТЕ ПРАВИЛА ─────────────────────────────────────────────────
    -- ⚠️ БЕЗ ТОВА НОВИТЕ РЕДОВЕ НЕ СЕ СУМИРАТ НИКЪДЕ. Детайлните редове са hidden=true и
    -- съществуват САМО за да влязат в правило: забравен там, редът се смята и се изхвърля.
    -- ⚠️ ПО ТОКЕН, не по подниз: `A_2_2_441` е префикс на `A_2_2_4412`, ако такава някога влезе.
    FOR x IN SELECT * FROM bg_n2_rule ORDER BY import_suffix LOOP
      SELECT cl.id, cl.rule INTO v_acc_id, v_rule
        FROM account_accounting_report_config_line cl
       WHERE cl.import_id = c.ccode || '-' || x.import_suffix;
      IF NOT FOUND THEN
        blockers := blockers || format(E'\n  · [%s] RULE %s: сборът %s-%s липсва.',
                                       c.ccode, x.subtotal_code, c.ccode, x.import_suffix);
        CONTINUE;
      END IF;
      IF x.token = ANY (string_to_array(regexp_replace(coalesce(v_rule, ''), '\s*\+\s*', ',', 'g'),
                                        ',')) THEN
        n_skipped := n_skipped + 1;
        CONTINUE;
      END IF;
      UPDATE account_accounting_report_config_line
         SET rule = coalesce(v_rule, '') ||
                    CASE WHEN coalesce(v_rule, '') = '' THEN '' ELSE ' + ' END || x.token,
             updated_on = now()
       WHERE id = v_acc_id;
      n_rules := n_rules + 1;
    END LOOP;

  END LOOP;

  IF v_companies = 0 THEN
    RAISE EXCEPTION
      E'BG_COA/N2: нито една фирма с BG сметкоплан (опори 4551 и 4552). Нищо не е пипано.';
  END IF;

  IF blockers <> '' THEN
    RAISE EXCEPTION E'BG_COA/N2 ОТКАЗ — нищо не е записано.\n%', blockers;
  END IF;

  RAISE NOTICE 'BG_COA/N2 ═══ готово ═══ фирми=% · сметки +% · view % · препородени % ·'
               ' статус % · А/П % · връзки % · пренасочени редове % · нови редове % ·'
               ' правила % · Z124 премахната % · пропуснати %',
    v_companies, n_added, n_retyped, n_reparented, n_status, n_ap, n_binding,
    n_remap, n_lines, n_rules, n_removed, n_skipped;
END
$mig$;

COMMIT;
