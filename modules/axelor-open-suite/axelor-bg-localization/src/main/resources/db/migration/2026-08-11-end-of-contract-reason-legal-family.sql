-- ЗАЩО. Основанието за прекратяване стана две части — акт и член — защото номерата на членовете се
-- повтарят между актовете (КТ чл. 71 и ЗДСл чл. 71 са различни основания със същата цифра).
-- Съпоставянето срещу BgCompensationType сега иска И двете да съвпаднат.
--
-- Подразбирането KT важи само за НОВИ записи: то е инициализатор на java полето, не DEFAULT на
-- колоната. Заварен ред остава с NULL, NULL не съвпада с нито един legalFamily, и обезщетенията по
-- него спират да се предлагат — мълчаливо, защото липсващото предложение не се обажда никъде.
--
-- Същият капан е и при bgIsPrimaryContract. Разликата е, че там NULL значи „никой не е попълнил“
-- и иска решение; тук няма двусмислие: без ЗДСл и ЗВО основанията в селекцията всеки заварен
-- запис е по КТ и нищо друго не може да бъде.
--
-- Пуска се ВЕДНЪЖ, върху всяка среда, чиято база е създадена преди този комит.

BEGIN;

UPDATE hr_end_of_contract_reason
    SET bg_legal_family = 'KT'
    WHERE bg_legal_family IS NULL;

COMMIT;
