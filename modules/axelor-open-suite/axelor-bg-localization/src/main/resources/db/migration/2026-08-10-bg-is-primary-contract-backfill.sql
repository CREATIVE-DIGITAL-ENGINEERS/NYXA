-- bgIsPrimaryContract: попълване на заварените договори, останали с NULL.
--
-- ЗАЩО. Подразбирането на полето стана true, защото по допълнителен трудов договор обезщетение при
-- прекратяване изобщо не се поражда, а цената на грешката е
-- несиметрична: непопълнен флаг при подразбиране false СКРИВА дължимо обезщетение, а при true
-- предлага излишен ред, който се вижда и се изключва с причина.
--
-- Но подразбирането важи само за НОВИ записи: то е инициализатор на java полето, не DEFAULT на
-- колоната. Заварен договор с NULL остава NULL, а генерираният getter връща FALSE при NULL — тоест
-- пазачът в BgTerminationCompensationService го прескача МЪЛЧАЛИВО и обезщетенията по него никога
-- не се предлагат. Точно посоката, която не се обажда.
--
-- ⚠️ ПУСКА СЕ САМО ВЪРХУ СРЕДИ, В КОИТО ДОГОВОРИТЕ СА ВЪВЕЖДАНИ ПРЕДИ ТАЗИ ПРОМЯНА и никой не е
-- отбелязвал допълнителните договори. Ако средата вече различава основен от допълнителен, НЕ я
-- пускай — ще заличиш това различаване. Условието WHERE ... IS NULL пази изричното false, но не
-- може да познае дали NULL значи „основен“ или „никой не е попълнил“. Пуска се след преглед, не
-- по навик.

BEGIN;

UPDATE hr_employment_contract
    SET bg_is_primary_contract = true
    WHERE bg_is_primary_contract IS NULL;

COMMIT;
