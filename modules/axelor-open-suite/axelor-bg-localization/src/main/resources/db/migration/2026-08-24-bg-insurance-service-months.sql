--
-- bg_insurance_service_months   — признатият осигурителен стаж в МЕСЕЦИ, деклариран вход.
-- bg_insurance_service_declared — попълван ли е изобщо.
--
-- ⚠️ ЗАЩО ДВЕ КОЛОНИ. Генерираният getter за Integer връща 0 и за NULL колона, тоест „нула месеца
-- стаж“ и „никой не е попълвал“ са НЕРАЗЛИЧИМИ в стойността. Разликата има цена: по чл. 40 ал. 1
-- КСО правото на парично обезщетение иска 6 месеца осигурителен стаж, тоест нулата е ВЕРЕН отговор
-- за новопостъпилия и ГРЕШЕН отговор за непопълненото. Флагът носи разликата, а
-- BgPayrollInputBuilder чете стойността САМО когато флагът я обявява за декларирана — инак полето
-- остава null („не знам“), не 0.
--
-- ⚠️ НИЩО НЕ СЕ ПОПЪЛВА, по същия довод като 2026-08-18-bg-insured-type-home.sql. Изкушението е
-- да се изведе стажът от bg_prior_experience_months на договора — и точно затова не се прави: там
-- стои ТРУДОВИЯТ стаж за ТОЗИ договор, а двата стажа се разминават (неплатеният отпуск над 30 дни
-- не е нито трудов, нито осигурителен; платеният е трудов). Пренесено мълчаливо, разминаването би
-- дало обезщетение на човек без право или би отнело право на човек, който го има — и в двата
-- случая без нито един признак, че е сгрешено.
--
-- Заварените редове получават NULL за флага, а генерираният getter за Boolean връща FALSE за NULL
-- — тоест те се четат като „не е декларирано“, което е верният прочит: никой още не ги е питал.
--
-- Пуска се ВЕДНЪЖ, върху всяка среда, чиято база е създадена преди този комит.

