-- Категория труд срещу вид осигурен: лицето по договор с код 01, останало с ПЪРВА категория.
--
-- ЗАЩО. Ставките се намират по ДВОЙКА, не по код: BgInsuranceCalculationService пита
-- `self.bgInsuredTypeCode = :code AND self.laborCategory = :cat`. Вид осигурен 01 е общият случай
-- по чл. 4 ал. 1 т. 1 КСО — „без обхванатите от следващите кодове“ — и редовете му със ставки
-- съществуват САМО за трета категория (измерено: 7 реда за (01, 3), НУЛА за (01, 1); първата
-- категория си има свой код, 02 „Работещи при условията на първа категория труд“). Тоест двойката
-- (01, 1) е ПРАЗЕН набор ставки: резолверът не намира нито един ред, фишът излиза без вноски и
-- това не се обажда никъде — грешно число, не гърмеж. Точно затова BgInsuredTypeHomeDbTest пита
-- базата, а не само файловете.
--
-- ⚠️ КОЯ ОТ ДВЕТЕ СТОЙНОСТИ Е СГРЕШЕНАТА — това е въпрос за ЗАМИСЪЛА, не за данните. Двойката е
-- невалидна и от двете страни; кое да се поправи се чете от сценария, който записът обслужва:
--
--   * Записът е „Половин“ — вторият ред на таблицата на ръчния тестов сценарий
--     („Половин · 4 ч/ден, всички работни дни · МОД × 0,50“). Осите му са ЧАСОВЕТЕ: договорът носи
--     bgHoursPerDay = 4 при bgLegalHoursPerDay = 8.
--   * Близнакът му е първият ред на същата таблица („Пълен месец“) — договор с код 01,
--     ТРЕТА категория, база 2000, 8/8 часа. Двата записа се различават по ЕДНА променлива — часа —
--     и точно това ги прави сверка. Категорията е единствената втора разлика и тя чупи сверката.
--   * Сценарият за ПЪРВА категория съществува ОТДЕЛНО и се сдвоява с ДРУГ код. Записано е в самия
--     пазач: BgInsuredTypeHomeFileTest#aLaborCategoryWithoutRowsForTheCodeIsRed държи контролата
--     disagreements("ред 10", "02", "1", …) → празен списък, с думите „код 02 е първа категория
--     труд по самото си наименование — съгласуван запис“. Същото сдвояване има и ръчният сценарий
--     на блок Ф: bgLaborCategory = '1' ЗАЕДНО с bgInsuredTypeCode = '02'
--     (I категория, редови, ППФ 12% = 240,00 за сметка на работодателя). Тоест категория 1 върви с
--     код 02, а не с 01 — този запис не е онзи сценарий.
--
-- Оттам и посоката: поправя се КАТЕГОРИЯТА, кодът остава 01. Обратната поправка (код → 02) би
-- вкарала ППФ 12% = 240,00 във фиша, тоест ВТОРА разлика спрямо близнака, и би измислила
-- първокатегориен сценарий, какъвто никой не е искал от този запис.
--
-- ЗАЩО '3', а не друга категория. Не е избор: редовете на код 01 допускат точно една категория и
-- тя е третата. Щом страната, която поправяме, е категорията, стойността ѝ е определена еднозначно
-- от самите данни.
--
-- ⚠️ ВЪРХУ КОЯ СРЕДА. Това е поправка на ТЕСТОВИТЕ данни на Nyxa (ръчно въведени
-- през приложението — hr_employee и hr_employment_contract НЕ идват от никой seed, затова App
-- Install не ги пипа и поправката трябва да живее тук, за да е повторяема). Върху среда с
-- ДЕЙСТВИТЕЛНИ лица НЕ се пуска по навик: там всяко попадение иска отделно решение коя от двете
-- стойности лъже — категорията на лицето или кодът на договора. Заявката, която ги изважда:
--
--     SELECT e.id, e.name, e.bg_labor_category, ct.id, ct.bg_insured_type_code
--       FROM hr_employee e
--       JOIN hr_employment_contract ct ON ct.employee = e.id
--      WHERE btrim(coalesce(ct.bg_insured_type_code, '')) <> ''
--        AND coalesce(e.bg_labor_category, '') <> ''
--        AND NOT EXISTS (SELECT 1 FROM bglocalization_bg_insurance_contribution c
--                         WHERE c.bg_insured_type_code = btrim(ct.bg_insured_type_code)
--                           AND c.labor_category = e.bg_labor_category);
--
--   ⚠️ Двете празни проверки не са украса: празният вид осигурен е ОТКАЗ на сглобителя, а не
--   разминаване (така го чете и disagreements(...)), а непопълнената категория без тях би обявила
--   за дефектен всеки запис, който още никой не е попълнил.
--
-- Пуска се веднъж и е ПОВТОРЯЕМА: след нея условието bg_labor_category = '1' вече не хваща реда,
-- тоест второто пускане не мени нищо. Условието NOT EXISTS пък я прави мълчалива, ако seed-ът
-- някога получи редове за (01, 1) — тогава двойката е валидна и няма какво да се поправя.

BEGIN;

UPDATE hr_employee e
    SET bg_labor_category = '3'
    WHERE e.bg_labor_category = '1'
      AND EXISTS (SELECT 1
                    FROM hr_employment_contract ct
                   WHERE ct.employee = e.id
                     AND btrim(coalesce(ct.bg_insured_type_code, '')) = '01')
      AND NOT EXISTS (SELECT 1
                        FROM bglocalization_bg_insurance_contribution c
                       WHERE c.bg_insured_type_code = '01'
                         AND c.labor_category = e.bg_labor_category);

COMMIT;
