package com.axelor.apps.bglocalization.service.payroll;

import java.math.BigDecimal;

/**
 * ЗАПЛАЩАНЕТО НА ПЛАТЕНИЯ ОТПУСК — КТ чл. 177, НСОРЗ чл. 17, 18 и 19. Чиста аритметика: без база,
 * без Guice, без Hibernate.
 *
 * <p><b>ДОСЛОВНИТЕ ТЕКСТОВЕ, ЧЕТЕНИ ОТ ПЪРВИЧЕН ИЗТОЧНИК.</b>
 *
 * <ul>
 *   <li><b>КТ чл. 177 ал. 1</b> — „За времето на платения годишен отпуск работодателят заплаща на
 *       работника или служителя възнаграждение, което се изчислява от начисленото при същия
 *       работодател СРЕДНОДНЕВНО брутно трудово възнаграждение за ПОСЛЕДНИЯ КАЛЕНДАРЕН МЕСЕЦ,
 *       предхождащ ползуването на отпуска, през който работникът или служителят е отработил
 *       НАЙ-МАЛКО 10 РАБОТНИ ДНИ.“
 *   <li><b>КТ чл. 177 ал. 2</b> — „Когато НЯМА месец, през който работникът или служителят е
 *       отработил най-малко 10 работни дни при същия работодател, възнаграждението по ал. 1 се
 *       определя от УГОВОРЕНИТЕ В ТРУДОВИЯ ДОГОВОР основно и допълнителни трудови възнаграждения с
 *       постоянен характер.“
 *   <li><b>НСОРЗ чл. 18 ал. 1 изр. 1</b> — среднодневното по чл. 177 ал. 1 „се установява, като
 *       начисленото … брутно трудово възнаграждение за последния календарен месец … се РАЗДЕЛИ НА
 *       БРОЯ НА ОТРАБОТЕНИТЕ ДНИ през този месец“.
 *   <li><b>НСОРЗ чл. 18 ал. 1 изр. 2</b> — среднодневното по чл. 177 ал. 2 „се установява, като
 *       уговореното в трудовия договор основно и допълнителни трудови възнаграждения с постоянен
 *       характер се раздели на СРЕДНОМЕСЕЧНИЯ БРОЙ РАБОТНИ ДНИ през съответната календарна година“.
 *   <li><b>НСОРЗ чл. 18 ал. 2</b> — „При определен месечен размер на трудовото възнаграждение
 *       установеното по ал. 1, ИЗРЕЧЕНИЕ ПЪРВО среднодневно брутно трудово възнаграждение се
 *       коригира с коефициент, получен от ОТНОШЕНИЕТО НА БРОЯ НА РАБОТНИТЕ ДНИ НА МЕСЕЦА, ПРИЕТ ЗА
 *       БАЗА, И БРОЯ НА РАБОТНИТЕ ДНИ НА СЪОТВЕТНИЯ МЕСЕЦ, ПРЕЗ КОЙТО СЕ ПОЛЗВА ОТПУСКЪТ.“
 *   <li><b>НСОРЗ чл. 19 ал. 2</b> — „Размерът на среднодневното брутно трудово възнаграждение при
 *       изчисляване на платения годишен отпуск и обезщетенията по Кодекса на труда ПРИ ПЪЛЕН
 *       РАБОТЕН ДЕН не може да бъде ПО-МАЛЪК от този, който се изчислява при възникване на
 *       съответното основание от размера на установената за страната минимална работна заплата.“
 * </ul>
 *
 * <p><b>⚠️ ЧЕТИРИ ЧЕТЕНИЯ, КОИТО ПРЕРАЗКАЗЪТ ГУБИ.</b>
 *
 * <ol>
 *   <li><b>Коефициентът е САМО за изречение първо.</b> Ал. 2 казва дословно „установеното по ал. 1,
 *       ИЗРЕЧЕНИЕ ПЪРВО“ — тоест резервният ред по чл. 177 ал. 2 НЕ се коригира. И не би имало с
 *       какво: знаменателят му вече е ГОДИШНА средна, а не броят дни на конкретен месец, тоест
 *       коефициент „дни на базовия месец / дни на месеца на ползване“ би нямал числител.
 *   <li><b>Дробта е база/ползване, а не обратното.</b> Базов месец с ПО-МАЛКО работни дни дава
 *       ПО-ВИСОКО среднодневно и коефициент под единица — двете се компенсират. Обърната, дробта
 *       усилва изкривяването вместо да го маха, и то точно в месеците, в които тя изобщо се
 *       появява.
 *   <li><b>Подът по чл. 19 ал. 2 е СЛЕД коефициента.</b> Нормата мери „размерът на среднодневното …
 *       ПРИ ИЗЧИСЛЯВАНЕ на платения годишен отпуск“, а чл. 18 ал. 2 казва, че коригираното пак Е
 *       среднодневното. Размерността потвърждава същото: сравняваното е МРЗ ÷ работните дни на
 *       месеца „при възникване на съответното основание“, тоест на месеца на ползване. Приложен
 *       ПРЕДИ коефициента, подът щеше да се умножи по „дни(база)/дни(ползване)“ и да се превърне в
 *       МРЗ × дни(база) ÷ дни(ползване)², число без норма зад себе си.
 *   <li><b>„Отработени дни“ не е „дни в осигуряване“.</b> Знаменателят на изр. 1 са ОТРАБОТЕНИТЕ
 *       дни на базовия месец — платеният отпуск през него НЕ е отработен ден и не влиза. Симетрично
 *       и числителят го няма: чл. 17 ал. 1 изброява седем съставки на базата и възнаграждението за
 *       платен отпуск НЕ е сред тях (то е в чл. 16 ал. 2 т. 7, друга база). Тоест отпускът от
 *       миналия месец не се самохрани в тазмесечния.
 * </ol>
 *
 * <p><b>⚠️ СРЕДНОДНЕВНОТО СЕ НОСИ КАТО ДРОБ, А НЕ КАТО ЧИСЛО.</b> § 5.3 иска ЕДНО деление, накрая.
 * Закръглено на два знака и чак после умножено по дните и по коефициента, среднодневното дава
 * различна сума от същата сметка, направена наведнъж — при 1060,00 ÷ 21 разликата е 0,000476 на
 * ден, тоест цяла стотинка вече при 21 дни отпуск. Затова {@link DailyRate} пази ЧИСЛИТЕЛ и
 * ЗНАМЕНАТЕЛ, а делението става веднъж, в {@link #upliftAmount}.
 */
public final class BgArt177Resolver {

  /** Прагът по КТ чл. 177 ал. 1: „отработил НАЙ-МАЛКО 10 работни дни“. */
  public static final BigDecimal QUALIFYING_WORKED_DAYS = BigDecimal.TEN;

  /** Месеците в годината — знаменателят на „средномесечния брой работни дни“ по чл. 18 ал. 1. */
  private static final BigDecimal MONTHS_IN_YEAR = BigDecimal.valueOf(12);

  private BgArt177Resolver() {}

  /**
   * СРЕДНОДНЕВНОТО БТВ КАТО ТОЧНА ДРОБ — числител и знаменател, без нито едно деление.
   *
   * <p>Виж класовия javadoc защо не е {@code BigDecimal}.
   */
  public static final class DailyRate {

    /** Числителят на дробта. */
    public final BigDecimal numerator;

    /** Знаменателят. ВИНАГИ положителен — фабриките отказват иначе. */
    public final BigDecimal denominator;

    /** Коя норма е дала числото — влиза в бележката на перото. */
    public final String basis;

    private DailyRate(BigDecimal numerator, BigDecimal denominator, String basis) {
      this.numerator = numerator;
      this.denominator = denominator;
      this.basis = basis;
    }

    /** Сравнение на две дроби без деление: {@code a/b ⋛ c/d} ⟺ {@code a·d ⋛ c·b}. */
    boolean isBelow(DailyRate other) {
      return numerator.multiply(other.denominator).compareTo(other.numerator.multiply(denominator))
          < 0;
    }
  }

  /**
   * СРЕДНОДНЕВНОТО ПО ЧЛ. 18 АЛ. 1 ИЗР. 1, ВЕЧЕ КОРИГИРАНО С КОЕФИЦИЕНТА ПО АЛ. 2.
   *
   * <p>Дробта е {@code (начислено × дни на базовия месец) / (отработени × дни на месеца на
   * ползване)} — тоест среднодневното и коефициентът, слети в едно, точно както § 5.3 иска.
   *
   * @param accruedArt17Base начисленото по чл. 17 БТВ на базовия месец. Единица: ЕВРО
   * @param workedDaysInBaseMonth ОТРАБОТЕНИТЕ дни на базовия месец — не дните в осигуряване
   * @param workingDaysInBaseMonth работните дни по календар на базовия месец (числителят на коеф.)
   * @param workingDaysInUsageMonth работните дни на месеца, през който се ползва отпускът
   * @return дробта, или {@code null} при неизползваем вход
   */
  public static DailyRate accruedDailyRate(
      BigDecimal accruedArt17Base,
      BigDecimal workedDaysInBaseMonth,
      Integer workingDaysInBaseMonth,
      Integer workingDaysInUsageMonth) {
    if (accruedArt17Base == null
        || accruedArt17Base.signum() <= 0
        || workedDaysInBaseMonth == null
        || workedDaysInBaseMonth.signum() <= 0
        || workingDaysInBaseMonth == null
        || workingDaysInBaseMonth <= 0
        || workingDaysInUsageMonth == null
        || workingDaysInUsageMonth <= 0) {
      return null;
    }
    return new DailyRate(
        accruedArt17Base.multiply(BigDecimal.valueOf(workingDaysInBaseMonth)),
        workedDaysInBaseMonth.multiply(BigDecimal.valueOf(workingDaysInUsageMonth)),
        "КТ чл. 177 ал. 1; НСОРЗ чл. 18 ал. 1 изр. 1 и ал. 2");
  }

  /**
   * СРЕДНОДНЕВНОТО ПО ЧЛ. 177 АЛ. 2 — уговореното по договор ÷ средномесечните работни дни.
   *
   * <p><b>⚠️ БЕЗ КОЕФИЦИЕНТ, И ТОВА НЕ Е ПРОПУСК.</b> Чл. 18 ал. 2 коригира изрично „установеното
   * по ал. 1, ИЗРЕЧЕНИЕ ПЪРВО“. Тук знаменателят вече е годишна средна и няма „месец, приет за
   * база“, чиито дни да застанат в числителя на коефициента.
   *
   * <p>⚠️ Средномесечният брой е {@code работни дни на ГОДИНАТА ÷ 12}, тоест дробта се записва като
   * {@code (уговорено × 12) / работни дни на годината} — пак без междинно деление.
   *
   * @param contractualPermanentPay уговорените по договор основно + ДТВ с постоянен характер
   * @param workingDaysInYear работните дни на календарната година на ползването
   */
  public static DailyRate contractualDailyRate(
      BigDecimal contractualPermanentPay, Integer workingDaysInYear) {
    if (contractualPermanentPay == null
        || contractualPermanentPay.signum() <= 0
        || workingDaysInYear == null
        || workingDaysInYear <= 0) {
      return null;
    }
    return new DailyRate(
        contractualPermanentPay.multiply(MONTHS_IN_YEAR),
        BigDecimal.valueOf(workingDaysInYear),
        "КТ чл. 177 ал. 2; НСОРЗ чл. 18 ал. 1 изр. 2 (БЕЗ коефициент)");
  }

  /**
   * ПОДЪТ ПО ЧЛ. 19 АЛ. 2 — МРЗ ÷ работните дни на месеца на ползване.
   *
   * <p>⚠️ „при възникване на съответното основание“ = месецът, през който се ползва отпускът.
   *
   * @param minWage минималната работна заплата за страната ({@code MIN_WAGE})
   */
  public static DailyRate statutoryMinimumDailyRate(
      BigDecimal minWage, Integer workingDaysInUsageMonth) {
    if (minWage == null
        || minWage.signum() <= 0
        || workingDaysInUsageMonth == null
        || workingDaysInUsageMonth <= 0) {
      return null;
    }
    return new DailyRate(
        minWage, BigDecimal.valueOf(workingDaysInUsageMonth), "НСОРЗ чл. 19 ал. 2 (под от МРЗ)");
  }

  /**
   * ПО-ВИСОКАТА ОТ ДВЕТЕ ДРОБИ — прилага пода по чл. 19 ал. 2, ако той хапе.
   *
   * <p><b>⚠️ САМО ПРИ ПЪЛЕН РАБОТЕН ДЕН.</b> Нормата го казва дословно. При непълно работно време
   * подът НЕ се прилага изобщо: МРЗ е за пълен ден, а лице на половин щат законно получава
   * половината — наложен и там, подът би удвоил отпуска му.
   *
   * @param floor резултатът на {@link #statutoryMinimumDailyRate}, или {@code null}, ако не се
   *     прилага (непълен работен ден, липсваща МРЗ)
   */
  public static DailyRate withStatutoryFloor(DailyRate rate, DailyRate floor) {
    if (rate == null) {
      return null;
    }
    if (floor == null || !rate.isBelow(floor)) {
      return rate;
    }
    return floor;
  }

  /**
   * НАДБАВКАТА — РАЗЛИКАТА между дължимото по чл. 177 и онова, което фишът ВЕЧЕ плаща за същите
   * дни. Закръглена ВЕДНЪЖ, § 5.3.
   *
   * <p><b>⚠️ ТОВА Е СЪРЦЕТО НА „БЕЗ ДВОЙНО ПЛАЩАНЕ“ И ТРЯБВА ДА СЕ ПРОЧЕТЕ БАВНО.</b> Перата с
   * постоянен характер за ТЕКУЩИЯ месец плащат всеки календарно-работен ден по {@code M / норма},
   * където {@code M} е непроратираният им месечен сбор. Дните платен отпуск са сред тези дни, тоест
   * фишът вече им е платил {@code M × дни / норма}. Дължимото по чл. 177 е {@code среднодневно ×
   * дни}. Разликата между двете е ЕДИНСТВЕНОТО, което чл. 177 добавя.
   *
   * <p>Оттам следва и инвариантът: при НЕПРОМЕНЕН състав на възнаграждението и напълно отработен
   * базов месец среднодневното × коефициента е точно {@code M / норма}, тоест надбавката е ТОЧНО
   * НУЛА — не „закръглено до нула“. Перото тогава връща само карва и фишът излиза бит по бит както
   * преди.
   *
   * <p><b>⚠️ ЗАЩО НЕ СЕ СМЯТА КАТО „ДЪЛЖИМО − ВЕЧЕ ПЛАТЕНО“ С ДВЕ ЗАКРЪГЛЯНИЯ.</b> Две закръглени
   * числа, извадени едно от друго, дават нула само когато и двете попаднат в една стотинка;
   * инвариантът щеше да важи в около две трети от случаите и да се чупи с една стотинка в
   * останалите — тоест щеше да изглежда като заоблена грешка вместо като правило.
   *
   * @param rate коригираното среднодневно като точна дроб
   * @param currentMonthPermanentPay {@code M} — непроратираният месечен сбор на перата с постоянен
   *     характер за ТЕКУЩИЯ месец (резултатът на {@code BgEarningsResolver#permanentPayBase})
   * @param workingDaysInUsageMonth нормата на месеца на ползване
   * @param art177Days дните платен отпуск по чл. 177
   * @return надбавката, която може да е и ОТРИЦАТЕЛНА (базовият месец е по-беден от текущия)
   */
  public static BigDecimal upliftAmount(
      DailyRate rate,
      BigDecimal currentMonthPermanentPay,
      int workingDaysInUsageMonth,
      BigDecimal art177Days) {
    BigDecimal norm = BigDecimal.valueOf(workingDaysInUsageMonth);
    // (числител/знаменател − M/норма) × дни, записано с ЕДНО деление:
    //   (числител × норма − M × знаменател) × дни / (знаменател × норма)
    return rate.numerator
        .multiply(norm)
        .subtract(currentMonthPermanentPay.multiply(rate.denominator))
        .multiply(art177Days)
        .divide(
            rate.denominator.multiply(norm), BgEarningsResolver.SCALE, BgEarningsResolver.ROUNDING);
  }

  /**
   * ДЪЛЖИМОТО ПО ЧЛ. 177 ЗА ДНИТЕ — само за ПОКАЗВАНЕ и сверяване, НЕ е сумата на перото.
   *
   * <p>⚠️ Сумата на перото е {@code карв + надбавка} (виж {@link #upliftAmount}), а това число е
   * пълното право по чл. 177. Двете съвпадат само когато всички пера с постоянен характер са
   * карвирани; при ръчно въведено постоянно перо перото носи по-малко, защото остатъкът се плаща
   * през самото ръчно перо. Числото служи на бележката и на свидетелите.
   *
   * <p><b>⚠️ И ЕДНА СТОТИНКА, КОЯТО Е ИЗБОР, А НЕ ГРЕШКА.</b> Дори когато всичко е карвирано,
   * {@code карв + надбавка} може да се разминe с това число с 0,01 — карвът е сбор от вече
   * закръглени пера, а надбавката се закръгля веднъж отделно. Разминаването е предпочетено
   * СЪЗНАТЕЛНО: алтернативата е перото да носи точно пълното право, но тогава „нето нула“ при
   * непроменено възнаграждение се чупи с една стотинка в около една трета от случаите (измерено
   * върху 779 040 комбинации основна × клас × степен × норма × дни). Инвариантът пази ОБЩИЯ случай
   * — всеки фиш без отпуск и всеки фиш с непроменено възнаграждение; разминаването се появява само
   * когато базовият месец така или иначе мести парите.
   */
  public static BigDecimal entitlementAmount(DailyRate rate, BigDecimal art177Days) {
    return rate.numerator
        .multiply(art177Days)
        .divide(rate.denominator, BgEarningsResolver.SCALE, BgEarningsResolver.ROUNDING);
  }

  /** Квалифицира ли базовият месец по чл. 177 ал. 1 — „най-малко 10 работни дни“. */
  public static boolean qualifiesAsBaseMonth(BigDecimal workedDays) {
    return workedDays != null && workedDays.compareTo(QUALIFYING_WORKED_DAYS) >= 0;
  }
}
