package com.axelor.apps.bglocalization.service.fixedasset;

import com.axelor.apps.bglocalization.service.fixedasset.BgArt79CorrectionRules.AssetKind;
import java.util.Collection;
import java.util.Collections;
import java.util.HashSet;
import java.util.Set;

/**
 * Прозорецът на годишната корекция — <b>чл. 79а ал. 8</b> и <b>чл. 79б ал. 7 ЗДДС</b>, като чиста
 * функция.
 *
 * <p><b>Защо е ОТДЕЛЕН от калкулатора.</b> Формулата на ал. 3 е аритметика върху една година;
 * прозорецът е СЪСТОЯНИЕ ПРЕЗ ГОДИНИТЕ. Дословно ал. 8: „5-годишният срок, съответно 20-годишният
 * срок <b>спира да тече</b> за всяка календарна година, през която стоката, съответно недвижимият
 * имот не се използва за дейностите, посочени в чл. 69 и 70. Срокът се <b>възобновява</b> за всяка
 * календарна година, през която стоката, съответно недвижимият имот започне отново да се използва
 * за дейностите, посочени в чл. 69 и 70.“ Тоест срокът брои ГОДИНИ НА ПОЛЗВАНЕ, а не календарни
 * години — една спряла година мести края с една напред. Сметнат с изваждане на години, прозорецът
 * би се затворил рано и корекция, която се дължи, просто нямаше да се предложи.
 *
 * <p>⚠️ <b>ТУК НЯМА МНОЖИТЕЛ „БРОЙ ГОДИНИ“.</b> При чл. 79 ал. 3 дължимият данък е {@code НДДС ×
 * 1/n × БГ} — наведнъж за всички останали години. При 79а/79б корекцията е {@code 1/n} за ЕДНА
 * година и се повтаря всяка година, докато прозорецът е отворен. Пренесен наум БГ оттам, годишната
 * корекция би се умножила по броя на оставащите години.
 *
 * <p>⚠️ <b>ГОДИНАТА НА КРЕДИТА НЕ Е КОРЕКЦИОННА ГОДИНА.</b> Ал. 1 казва „за всяка от годините,
 * <b>СЛЕДВАЩИ</b> годината на упражняване на право на данъчен кредит“. Тя е началото на срока (и
 * носителят на К₀), но за нея корекция не се прави — тогава кредитът е бил упражнен, няма спрямо
 * какво да се мери изменение.
 */
public final class BgArt79aCorrectionWindow {

  private BgArt79aCorrectionWindow() {}

  /**
   * Началото на n-годишния срок — <b>две отделни начала</b>, според това дали кредитът е упражнен.
   *
   * <p>Дословно чл. 79а ал. 3 т. 1 (и огледално т. 2 и чл. 79б ал. 3) срокът се брои „считано от:
   *
   * <ul>
   *   <li>началото на годината на упражняване правото на данъчен кредит, съответно от началото на
   *       годината на фактическото използване, в случай че имотът не е използван повече от една
   *       година след годината на упражняване правото на данъчен кредит, или
   *   <li>началото на годината, през която изтича срокът по чл. 72, ал. 1, <b>когато при
   *       придобиване или изграждане на имота не е упражнено право на данъчен кредит</b> …“
   * </ul>
   *
   * <p>⚠️ <b>ВТОРОТО НАЧАЛО Е СЪЩЕСТВЕНО ИМЕННО ТУК.</b> При чл. 79 ал. 3 то е без значение: без
   * упражнен кредит няма какво да се връща. При 79а буква „а“ е ТОЧНО случаят „не е приспаднат
   * данъчен кредит на основание чл. 70“ и корекцията е в посока УВЕЛИЧЕНИЕ — тъй че ако срокът се
   * закотви за несъществуваща година на кредит, правото се губи мълчаливо.
   *
   * <p>⚠️ <b>ГОДИНАТА НА ФАКТИЧЕСКО ИЗПОЛЗВАНЕ мести срока САМО при недвижим имот.</b> Т. 2
   * (останалите стоки) и чл. 79б (услуги) нямат това изречение в текста си — там едно поле,
   * попълнено по навик, не бива да мести нищо.
   *
   * @param kind класификацията — решава дали годината на фактическо използване изобщо се чете
   * @param creditYear годината на упражняване на кредита, или {@code 0}, когато не е упражнен
   * @param art72DeadlineYear годината, през която изтича срокът по чл. 72 ал. 1 — чете се само
   *     когато кредит не е упражняван
   * @param firstUseYear годината на фактическото използване, или {@code null}
   */
  public static int periodStartYear(
      AssetKind kind, int creditYear, int art72DeadlineYear, Integer firstUseYear) {
    int anchor = creditYear > 0 ? creditYear : art72DeadlineYear;
    if (kind == AssetKind.IMMOVABLE_PROPERTY && firstUseYear != null && firstUseYear > anchor + 1) {
      return firstUseYear;
    }
    return anchor;
  }

  /**
   * Поредният номер на годината ВЪТРЕ В СРОКА, като спрените години не се броят.
   *
   * <p>Началната година е № 1. Година, в която активът не се използва за дейностите по чл. 69 и 70,
   * не получава номер и не изразходва срока — оттам „срокът спира да тече“.
   *
   * @return номерът (≥ 1), или {@code 0}, когато годината е преди началото или е спряна
   */
  public static int countedIndex(int startYear, Set<Integer> suspendedYears, int year) {
    if (year < startYear || suspendedYears.contains(year)) {
      return 0;
    }
    int index = 0;
    for (int y = startYear; y <= year; y++) {
      if (!suspendedYears.contains(y)) {
        index++;
      }
    }
    return index;
  }

  /**
   * Дължи ли се изобщо годишна корекция за тази година.
   *
   * <p>Три отказа, всеки от различна разпоредба:
   *
   * <ul>
   *   <li>годината е началната или по-ранна — ал. 1 иска „годините, СЛЕДВАЩИ“;
   *   <li>годината е спряна — ал. 8: активът не се използва за чл. 69/70, няма изменение в
   *       използването, което да се мери;
   *   <li>срокът е изчерпан — чл. 80 ал. 1 т. 3 (20 г. за имоти) и т. 4 (5 г. за останалите).
   * </ul>
   */
  public static boolean contains(
      int startYear, int periodYears, Set<Integer> suspendedYears, int year) {
    int index = countedIndex(startYear, suspendedYears, year);
    return index > 1 && index <= periodYears;
  }

  /**
   * Основанието по чл. 80 ал. 1 при изтекъл срок, или {@code null}, докато прозорецът е отворен.
   *
   * <p>Ползва се за да се обясни ЗАЩО няма ред, вместо редът просто да липсва.
   */
  public static String timeBarGround(
      AssetKind kind, int startYear, Set<Integer> suspendedYears, int year) {
    int index = countedIndex(startYear, suspendedYears, year);
    return index > kind.periodYears() ? kind.timeBarGround() : null;
  }

  /**
   * Прозорецът на ВТОРИЯ носител по <b>ППЗДДС чл. 67 ал. 4</b> — язди остатъка от срока на
   * ЗАВАРЕНИЯ актив, а не свой собствен.
   *
   * <p>Дословно ал. 4: „…за който <b>не възниква нов</b> 20-годишен срок, съответно 5-годишен срок
   * съгласно чл. 79, ал. 10, чл. 79а, ал. 10 и чл. 79б, ал. 8 от закона, корекциите по чл. 79, 79а
   * и 79б от закона се извършват пропорционално <b>за остатъка от годините</b> на 20-годишния,
   * съответно 5-годишния, срок.“
   *
   * <p>Тоест годината се коригира само когато е вярно И ДВЕТО:
   *
   * <ul>
   *   <li>тя следва годината на кредита ЗА ПОДОБРЕНИЕТО (ал. 1 иска „годините, СЛЕДВАЩИ“ — за този
   *       носител това е неговата си кредитна година, не тази на актива);
   *   <li>тя още е вътре в срока на ЗАВАРЕНИЯ актив (ал. 10: нов срок не възниква).
   * </ul>
   *
   * <p>⚠️ Спрените години по ал. 8 са на АКТИВА и местят края му напред, тоест остатъкът РАСТЕ, а
   * не се топи. Затова и двете проверки минават през {@link #countedIndex}, а не през изваждане на
   * календарни години.
   */
  public static boolean containsWithinIncumbentTerm(
      int carrierStartYear,
      int assetStartYear,
      int assetPeriodYears,
      Set<Integer> suspendedYears,
      int year) {
    if (countedIndex(carrierStartYear, suspendedYears, year) <= 1) {
      return false;
    }
    int assetIndex = countedIndex(assetStartYear, suspendedYears, year);
    return assetIndex >= 1 && assetIndex <= assetPeriodYears;
  }

  /**
   * R — остатъкът от годините на срока на ЗАВАРЕНИЯ актив, броен от {@code fromYear} ВКЛЮЧИТЕЛНО.
   *
   * <p>Това е параметърът, който ППЗДДС чл. 67 ал. 4 нарича „остатъка от годините“. Държи се явно
   * върху реда, защото е ЕДИНСТВЕНОТО, което разпоредбата казва сигурно — знаменателят тя не го
   * казва (виж {@code BgArt79aAnnualCorrectionRules#correction}).
   *
   * <p>⚠️ <b>R НЕ Е броят на коригиращите години.</b> R брои и самата {@code fromYear}, докато
   * корекция за нея не се прави (ал. 1: „годините, СЛЕДВАЩИ“). Тоест коригиращите години са R − 1.
   * Двете числа се разминават точно с едно и това е нарочно: R е мярката на разпоредбата, а
   * коригиращите години са следствие от конвенцията за началната година.
   *
   * <p>Пример: имот с кредит 2020 г. (срок 2020–2039), подобрение с кредит 2030 г. → R = 10
   * (2030…2039), а коригиращите години са девет (2031…2039).
   *
   * @return броят на тикащите години от {@code fromYear} до края на срока, или {@code 0}, когато
   *     срокът вече е изчерпан
   */
  public static int remainingYears(
      int assetStartYear, int assetPeriodYears, Set<Integer> suspendedYears, int fromYear) {
    if (fromYear <= assetStartYear) {
      return assetPeriodYears;
    }
    // Спряната година не носи номер — остатъкът се мери от първата следваща тикаща.
    int probe = fromYear;
    int index = countedIndex(assetStartYear, suspendedYears, probe);
    int guard = 0;
    while (index == 0 && guard++ < MAX_SUSPENSION_LOOKAHEAD) {
      index = countedIndex(assetStartYear, suspendedYears, ++probe);
    }
    if (index == 0 || index > assetPeriodYears) {
      return 0;
    }
    return assetPeriodYears - index + 1;
  }

  /**
   * Таван на търсенето при поредица от спрени години — пази от безкраен цикъл, ако летописът е
   * повреден. Двайсет години подред без ползване по чл. 69/70 вече не са „спиране на срок“, а
   * различен факт, който иска човек.
   */
  private static final int MAX_SUSPENSION_LOOKAHEAD = 100;

  /** Незадължителна помощ: спрените години като модифицируемо множество от нищо. */
  public static Set<Integer> suspended(Collection<Integer> years) {
    return years == null ? Collections.emptySet() : new HashSet<>(years);
  }
}
