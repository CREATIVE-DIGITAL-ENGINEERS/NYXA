/**
 * ЧЕТЕЦЪТ НА ШЕСТТЕ ФЛАГА на {@link BgInsuredType} — и единственият.
 *
 * <p><b>Защо изобщо съществува.</b> Шестте флага стоят в речника, сверени срещу изброените в
 * Приложение № 1 кодове, и без този клас никой производствен код не ги чете. Данни, които никой не
 * пита, не са данни — те са мнение, което остарява мълчаливо. Тук е мястото, където мнението става
 * поведение.
 *
 * <p><b>⚠️ ФЛАГЪТ СЕ ПИТА, СПИСЪКЪТ НЕ СЕ ПРЕПИСВА.</b> Изкушението е да се напише {@code if
 * (NO_NET_PAY.contains(code))} с двайсетте кода от наредбата. То би било второ копие на едно и също
 * правило — а номенклатурата е ТЕМПОРАЛНА (ДВ бр. 15/2024 премахна кодове 07, 21, 23 и 93) и се
 * сменя с редакция на наредбата, не с комит. Копието би оцеляло след редакцията и би било вярно на
 * вид. Затова тук се чете САМО стойността на реда, а дали редът е верен, се проверява на друго
 * място и срещу друг източник: {@code BgD1FlagsAgainstNaredbaTest} сверява seed-а машинно срещу
 * дословно изброените в Приложение № 1 кодове.
 *
 * <p><b>⚠️ ЛИПСВАЩ ВИД ОСИГУРЕН НЕ СЕ ЧЕТЕ КАТО „НИЩО ОТ ГОРНОТО“.</b> Всеки метод тук приема, че
 * редът е намерен. Ненамерен код е ОТКАЗ ({@link #refusalReason}), не набор от подразбирания:
 * подразбиранията биха дали правдоподобен запис за лице, чийто режим не познаваме.
 */
public final class BgD1InsuredTypeRules {

  /**
   * Кодовете, чиито данни подава НОИ, а не работодателят — чл. 4 ал. 10 т. 1.
   *
   * <p>⚠️ ЕДИНСТВЕНИЯТ СПИСЪК, КОЙТО НАИСТИНА Е СПИСЪК, и затова е тук, а не флаг в речника. Той не
   * описва КАК се попълва декларацията — той казва, че тя изобщо НЕ Е НАША. Разграничението минава
   * по подател, не по поведение на поле, тоест няма ред в речника, на който да седне.
   *
   * <p>Кодовете: <b>15</b> — парично обезщетение за безработица (б. „б“); <b>88</b> и <b>89</b> —
   * обезщетения по чл. 230 ал. 1 и чл. 231 ал. 1 от Закона за отбраната и въоръжените сили (б.
   * „а“).
   *
   * <p>⚠️ Речникът ни ги носи, и това е ВЯРНО, не пропуск: коригираща Д1 за минал период може да ги
   * срещне, а лицето с такъв код има вид осигурен независимо кой го декларира.
   */
  public static final Set<String> NOI_SUBMITTED_CODES =
      Collections.unmodifiableSet(new LinkedHashSet<>(Arrays.asList("15", "88", "89")));

  /**
   * Кодът, при който т. 12.1/12.2/12.3 зависят от УСЛОВИЕ, а не от самия код — заб. 2 към т. 12.
   *
   * <p>Условието е „когато осигурителният доход на лицето се определя по реда на чл. 6, ал. 3 от
   * КСО“. Днес този факт НЯМА носител в модела — виж {@link #modIsUndecidable}.
   */
  public static final String CONDITIONAL_MOD_CODE = "94";

  /**
   * Полетата, които се попълват при <b>код 28</b> — дословно от Приложение № 1: „Когато в т. 12
   * „Вид осигурен“ е попълнен код 28, се попълват т. 2, 3, 4, 5, 5.1, 6, 7, 14, 15, 27 и 28.“
   *
   * <p>⚠️ Единайсет точки, и т. 21/22 ГИ НЯМА СРЕД ТЯХ. Код 28 е лице само със здравни вноски върху
   * особена база (т. 27/28) — осигурителен доход по т. 21 и вноски за ДОО то не носи. Емитер, който
   * подаде т. 21 със сметнато число, не греши в аритметиката: той твърди нещо за режима на лицето,
   * което не е вярно.
   *
   * <p>⚠️ Т. 1 не е в списъка на наредбата — тя е кодът за корекция и стои извън набора „данни“.
   */
  public static final Set<String> CODE_28_FIELDS =
      Collections.unmodifiableSet(
          new LinkedHashSet<>(
              Arrays.asList("2", "3", "4", "5", "5.1", "6", "7", "14", "15", "27", "28")));

  /** Код 28 — само здравни вноски върху особена база. */
  public static final String HEALTH_ONLY_CODE = "28";

  /**
   * Код <b>16</b> — „лица, работещи при сумирано изчисляване на работното време за <b>повече от
   * един месец</b>“, и ЕДИНСТВЕНИЯТ, за който се попълва т. 13.
   *
   * <p><b>⚠️ КОД, А НЕ ФЛАГ, и това е разлика от останалите пет правила тук.</b> Указанието на т.
   * 13 казва дословно „когато в т. 12 е попълнен код за вид осигурен 16“ — тоест условието е самият
   * код, а не свойство на режима. Флаг в речника би бил второ копие на едно име.
   *
   * <p><b>⚠️ И НЕ Е {@code EmploymentContract.bgWorkTimeMode}.</b> Той описва СЪЩИЯ факт (режимът е
   * СИРВ), но лице на СИРВ може да е декларирано с ДРУГ код — например 04 по допълнителен трудов
   * договор. Попълнена по режима, т. 13 твърди нещо за КОДА, което не е вярно.
   */
  public static final String SIRV_CODE = "16";

  /**
   * Код <b>90</b> — попълват се само т. 31 и 31а, а <b>т. 16 не се попълва</b> (заб. 3 към т. 16).
   *
   * <p>Заб. 3 дословно: „Когато в т. 12 Вид осигурен е попълнен код 90, т. 16 не се попълва.“ А т.
   * 31 изброява 90 сред кодовете си, докато 90 е и в списъците на т. 16.7/16.8 и т. 34 — тоест
   * лицето с код 90 носи данък и облагаем доход, но не и дни, часове и нето.
   */
  public static final String TAX_ONLY_CODE = "90";

  /**
   * Код <b>14</b> — т. 31 и 31а зависят от УСЛОВИЕ ЗА ЛИЦЕТО, а не от самия код.
   *
   * <p>Указанието към т. 31, ДОСЛОВНО: „Полето на т. 31 за лицата с код за вид осигурен 14 се
   * попълва САМО от акционери, притежаващи повече от 5 на сто от капитала на акционерното
   * дружество, за доходи по § 1, т. 26, букви „и“ и „л“.“
   *
   * <p><b>⚠️ И ЗАТОВА {@code bgFillsT31} ОСТАВА {@code true} В РЕЧНИКА — това не е
   * противоречие.</b> Флагът преписва ИЗБРОЯВАНЕТО на указанието, трийсетте кода, сред които 14
   * наистина стои, и се сверява машинно срещу дословния списък ({@code
   * BgD1FlagsAgainstNaredbaTest}). Свален, той би направил преписа НЕВЯРЕН спрямо наредбата и щеше
   * да отнеме единствената машинна проверка на самия списък — а тя пази ТЕМПОРАЛНА номенклатура (ДВ
   * бр. 15/2024 премахна четири кода). Условието ОТГОРЕ на изброяването е второ правило и живее
   * ТУК, по същия довод, по който т. 13 се решава от {@link #SIRV_CODE}, а не от флаг: наредбата го
   * изрича през самия код.
   *
   * <p>⚠️ Признакът „над 5 на сто от капитала“ НЯМА носител в модела — виж {@link
   * #taxPointsUndecidable}. Същата липса държи акционера по код 14 на ред 101 вместо 102 в
   * справката по чл. 73 ал. 1 ({@code BgArt73Para6Aggregator}); поправката на двете е ЕДНА и е
   * липсващият признак, не втори филтър.
   */
  public static final String CONDITIONAL_T31_CODE = "14";

  private BgD1InsuredTypeRules() {}

  /**
   * Причината този вид осигурен да НЕ бъде емитиран от нас, или {@code null}, ако е наш.
   *
   * <p>Две различни причини, и двете назовани — защото мълчаливо прескочен фиш прави декларацията
   * непълна по начин, който се открива от НАП, а не от нас.
   */
  public static String refusalReason(String code, BgInsuredType type) {
    if (code == null || code.trim().isEmpty()) {
      return "фишът няма вид осигурен (т. 12) — без него записът не може да се построи:"
          + " видът осигурен решава кои точки изобщо се попълват";
    }
    String c = code.trim();
    if (NOI_SUBMITTED_CODES.contains(c)) {
      return "вид осигурен "
          + c
          + " се подава от Националния осигурителен институт по чл. 4 ал. 10 т. 1, не от"
          + " работодателя — данните за него тръгват по друг ред и до 20-о число";
    }
    if (type == null) {
      return "вид осигурен "
          + c
          + " не е намерен в речника (BgInsuredType) за този период — режимът му е неизвестен, а"
          + " подразбирания биха дали правдоподобен запис за лице, което не познаваме";
    }
    return null;
  }

  /** Прилага ли се МОД, тоест попълват ли се т. 12.1, 12.2 и 12.3 (18-те кода). */
  public static boolean appliesMod(BgInsuredType type) {
    return type != null && Boolean.TRUE.equals(type.getBgAppliesMod());
  }

  /**
   * Условният случай: код 94 при доход по чл. 6 ал. 3 КСО.
   *
   * <p>⚠️ ОБЯВЕНА ГРАНИЦА, НЕ ТИХО РЕШЕНИЕ. Признакът „доходът се определя по реда на чл. 6 ал. 3
   * КСО“ НЯМА носител в модела днес — нито на договора, нито на фиша. Тоест за код 94 не можем да
   * отговорим нито „да“, нито „не“.
   *
   * <p>Изборът е между три погрешни неща и едно вярно. Да попълним т. 12.1/12.3 значи да твърдим
   * условие, което не сме установили. Да откажем целия запис значи да загубим т. 21, 22 и всичко
   * останало, което е напълно определимо. Да оставим полетата празни МЪЛЧАЛИВО значи да представим
   * решение като данни. Остава вярното: полетата остават празни — по подразбирането на самата
   * наредба, която ги пълни само за изброените кодове — и валидаторът ОБЯВЯВА, че условието не е
   * проверено. Празното е и консервативният прочит: изключението се установява, не се предполага.
   */
  public static boolean modIsUndecidable(String code, BgInsuredType type) {
    return type != null
        && CONDITIONAL_MOD_CODE.equals(code == null ? null : code.trim())
        && Boolean.TRUE.equals(type.getBgAppliesModConditional());
  }

  /** Попълва ли се т. 31 (начислен месечен облагаем доход) — 30-те кода. */
  public static boolean fillsT31(BgInsuredType type) {
    return type != null && Boolean.TRUE.equals(type.getBgFillsT31());
  }

  /** Попълва ли се 0 в позиции 3 и 4 на т. 16 (законоустановено и договорено РВ) — 17-те кода. */
  public static boolean zeroWorkTime(BgInsuredType type) {
    return type != null && Boolean.TRUE.equals(type.getBgZeroWorkTime());
  }

  /** Остават ли празни т. 16.7 и 16.8 (часове) — 23-те кода. */
  public static boolean noHours(BgInsuredType type) {
    return type != null && Boolean.TRUE.equals(type.getBgNoHours());
  }

  /**
   * Остава ли празна т. 34 (нетно възнаграждение по НПОПДОО) — 20-те кода.
   *
   * <p>⚠️ Флагът трябва да е верен и без читател: код 92 („Морски лица“) е сред кодовете на т. 34
   * по наредбата; с {@code bgNoNetPay = false} морското лице би получило т. 34, която не му се
   * полага, в мига, в който този метод влезе в употреба.
   */
  public static boolean noNetPay(BgInsuredType type) {
    return type != null && Boolean.TRUE.equals(type.getBgNoNetPay());
  }

  /** Лице само със здравни вноски (код 28) — попълват се единствено {@link #CODE_28_FIELDS}. */
  public static boolean healthOnly(String code) {
    return HEALTH_ONLY_CODE.equals(code == null ? null : code.trim());
  }

  /** Лице само с данък (код 90) — попълват се т. 31 и 31а, т. 16 остава празна. */
  public static boolean taxOnly(String code) {
    return TAX_ONLY_CODE.equals(code == null ? null : code.trim());
  }

  /**
   * Условният случай на т. 31 и 31а: код 14 БЕЗ установен признак „акционер над 5 на сто“.
   *
   * <p><b>⚠️ ОБЯВЕНА ГРАНИЦА, НЕ ТИХО РЕШЕНИЕ</b> — по образеца на {@link #modIsUndecidable}.
   * Изборът е между три погрешни неща и едно вярно. Да попълним т. 31 значи да твърдим, че лицето Е
   * акционер с над 5 на сто от капитала — обстоятелство, което никой не е установил. Да откажем
   * целия запис значи да загубим т. 21, 22, 22.1 и 26, които са напълно определими и които НАП
   * чака. Да оставим точките празни МЪЛЧАЛИВО значи да представим решение като данни. Остава
   * вярното: точките остават празни — както указанието ги оставя за всекиго, който не е акционерът,
   * — а валидаторът ОБЯВЯВА, че условието не е проверено. Празното е и консервативният прочит:
   * изключението се установява, не се предполага.
   *
   * <p><b>⚠️ И ДВЕТЕ ТОЧКИ, НЕ САМО Т. 31.</b> Указанието дава на акционера по б. „и“ и „л“ т. 31 И
   * 31а заедно; извън него ЗДДФЛ страната на дохода по граждански договор изобщо не минава през Д1.
   * Данъкът му е АВАНСОВ по чл. 43 (облагаемият доход по чл. 29 МИНУС удържаните задължителни
   * вноски), удържа се тримесечно и се декларира по чл. 55 и в справката по чл. 73 ал. 1 — докато
   * т. 31а е „начислен месечен данък“ по чл. 42 ал. 4, който осигурителят удържа МЕСЕЧНО. Копиран в
   * т. 31а, авансовият данък по чл. 43 се декларира ДВА ПЪТИ и по два несъвместими реда.
   *
   * <p><b>⚠️ САМО КОД 14.</b> Наетият (01), ДУК-ът (10), самоосигуряващият се и всички останали
   * пълнят двете точки както преди — това е гейт за ЕДИН код, а не смяна на генератора на Д1. И
   * осигурителните точки на самия код 14 (т. 12, 21, 22, 22.1, 26) не се докосват: празни остават
   * само данъчните.
   *
   * <p>⚠️ Появи ли се признакът в модела, гейтът става истинско условие на СЪЩИЯ шев: акционерът
   * над 5 на сто минава по общия път и пълни т. 31 и 31а от фиша си.
   */
  public static boolean taxPointsUndecidable(String code) {
    return CONDITIONAL_T31_CODE.equals(code == null ? null : code.trim());
  }
}
