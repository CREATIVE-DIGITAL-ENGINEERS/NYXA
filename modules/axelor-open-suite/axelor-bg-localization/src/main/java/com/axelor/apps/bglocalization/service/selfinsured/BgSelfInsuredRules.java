  /** Фишът е на самоосигуряващо се лице, тоест носи регистрация. */
  public static boolean isSelfInsured(BgPaySlip slip) {
    return slip != null && slip.getBgSelfInsuredRegistration() != null;
  }

  /**
   * ПРИЧИНАТА ТОЗИ ФИШ ДА НЯМА ВАЛИДЕН НОСИТЕЛ, или {@code null}, когато има точно един.
   *
   * <p><b>⚠️ XOR, А НЕ „ПОНЕ ЕДНО“.</b> Изискване в колоната ({@code employmentContract
   * required="true"}) хваща само единия грешен случай. Разхлабена, колоната не хваща нито един —
   * затова правилото е тук И Е ПО-СИЛНО:
   *
   * <ul>
   *   <li><b>И двете</b> значи фиш, който твърди ДВЕ различни правоотношения наведнъж. Той е
   *       по-опасният от двата: всяко от тях е валидно само за себе си, тоест числата излизат, а
   *       вноските се смятат по единия и се декларират по другия. {@code required} никога не би го
   *       хванал.
   *   <li><b>Нито едно</b> значи фиш без лице — днешното поведение на {@code required}, запазено.
   * </ul>
   *
   * <p>⚠️ ДВЕТЕ ПРИЧИНИ СА РАЗЛИЧНИ ТЕКСТОВЕ, а не един общ. Първата се поправя с изтриване на
   * едната препратка, втората — с попълване на едната. Общ текст би пратил и двамата на грешното
   * място.
   */
  public static String refuseCarrier(BgPaySlip slip) {
    if (slip == null) {
      return "фиш няма — носител не може да се определи";
    }
    boolean hasContract = slip.getEmploymentContract() != null;
    boolean hasRegistration = slip.getBgSelfInsuredRegistration() != null;
    if (hasContract && hasRegistration) {
      return "фишът сочи И трудов договор, И регистрация на самоосигуряващо се лице. ⚠️ Двете се"
          + " изключват: самоосигуряващият се НЯМА работодател (КСО чл. 6 ал. 8 — вноските са за"
          + " сметка на осигурените лица), а наетият по трудово правоотношение НЕ се самоосигурява"
          + " за същия доход. Фиш с двата носителя дава ДВА валидни всеки сам за себе си набора"
          + " ставки и нито един контрол по обща сума не го хваща. Поправка: изчистете едната"
          + " препратка.";
    }
    if (!hasContract && !hasRegistration) {
      return "фишът няма нито трудов договор, нито регистрация на самоосигуряващо се лице — тоест"
          + " няма чий да е. Без носител видът осигурен няма източник, а без него каталогът със"
          + " ставки не може да бъде питан.";
    }
    return null;
  }

  /**
   * ПРИЧИНАТА ФИШЪТ ДА НОСИ ДВА НОСИТЕЛЯ НАВЕДНЪЖ, или {@code null} във всеки друг случай.
   *
   * <p><b>⚠️ ПО-ТЕСЕН ВЪПРОС ОТ {@link #refuseCarrier}, И РАЗЛИКАТА Е ИЗМЕРИМА.</b> Двата грешни
   * случая се хващат на РАЗЛИЧНИ места, защото единият вече има кой да го хване:
   *
   * <ul>
   *   <li><b>„Нито едно“</b> стига до {@code BgPaySlipService#contributions} и се връща като {@code
   *       INPUT_NOT_ASSEMBLED} с пълния текст на {@link #refuseCarrier} — а {@code
   *       contributionRefusal} го превръща в отказ при потвърждаване. Тоест той Е покрит.
   *   <li><b>„И двете“</b> НЕ стига дотам при всеки повикващ: услуга, чиито осигуровки са подменени
   *       или вече сметнати, ще види RESOLVED и ще пусне фиша нататък. Този случай няма друг пазач
   *       и затова се пита ИЗРИЧНО.
   * </ul>
   *
   * <p><b>⚠️ И ЗАТОВА {@code confirm()} НЕ ПИТА ШИРОКИЯ ВЪПРОС.</b> Питан широко, той дублира
   * отказ, който вече идва по друг път — а дублираният отказ не е безобиден: той ИЗПРЕВАРВА
   * заварените пазачи и сменя съобщението, което операторът вижда, за фиш, чийто дефект е съвсем
   * друг. Заварените тестове на потвърждаването строят фиш без договор, за да проверят нещо трето
   * (празни пера, заключен период, незаредена година), и широкият въпрос би ги повалил всичките,
   * преди да са стигнали до собственото си твърдение.
   */
  public static String refuseAmbiguousCarrier(BgPaySlip slip) {
    if (slip == null
        || slip.getEmploymentContract() == null
        || slip.getBgSelfInsuredRegistration() == null) {
      return null;
    }
    return refuseCarrier(slip);
  }

