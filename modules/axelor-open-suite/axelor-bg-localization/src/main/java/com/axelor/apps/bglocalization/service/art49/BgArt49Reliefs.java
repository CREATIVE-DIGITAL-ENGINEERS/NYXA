package com.axelor.apps.bglocalization.service.art49;

import java.math.BigDecimal;

/**
 * ДАНЪЧНИТЕ ОБЛЕКЧЕНИЯ ПО ЧЛ. 49 АЛ. 3 — колони от 8 до 16 на ред 8.3, едно поле на колона.
 *
 * <p>Един и същ обект носи ДВЕ различни неща на два различни етапа: ПОИСКАНОТО (входът) и
 * ПРИЛОЖЕНОТО (изходът след таваните). {@link BgArt49Recalculation#applyCaps} превръща първото във
 * второто, а справката показва второто — указание т. 7 иска в колоните това, което е било ползвано
 * при определянето на годишния данък, не това, на което лицето би имало право.
 *
 * <p><b>═══ ⚠️ ЧЛ. 49 АЛ. 3 ДАВА ДВЕ РАЗЛИЧНИ ГРУПИ, А НЕ ЕДИН СПИСЪК ═══</b>
 *
 * <ul>
 *   <li><b>т. 1 — чл. 19 и чл. 22</b>, но САМО „когато сумите са удържани от работодателя при
 *       изплащане на дохода от трудово правоотношение“. Указание т. 7 го повтаря за колони 9, 10,
 *       12, 13 и 14. Тоест вноска, която лицето е направило само̀ по банков път, НЕ влиза тук — тя
 *       се ползва с годишна данъчна декларация по чл. 50.
 *   <li><b>т. 2 — чл. 18, чл. 20, чл. 22в и чл. 22г</b>, без такова условие: те се ползват срещу
 *       ДОКУМЕНТ, не срещу удържане.
 * </ul>
 *
 * <p><b>═══ ⚠️ И ВСИЧКИ ТЕ МИНАВАТ ПРЕЗ ЕДНА ОБЩА ВРАТА — ЧЛ. 49 АЛ. 4 ═══</b>
 *
 * <p>Дословно: „Алинея 3 СЕ ПРИЛАГА, когато работникът/служителят предостави на работодателя в срок
 * от 30 НОЕМВРИ до 31 ДЕКЕМВРИ на данъчната година следните документи“ — и следва списък от седем
 * точки, по една на облекчение, плюс т. 8: писмена декларация, че лицето няма подлежащи на
 * принудително изпълнение публични задължения ИЛИ че за годината ще подава годишна данъчна
 * декларация.
 *
 * <p><b>⚠️ ТОВА Е ВРАТА ЗА ОБЛЕКЧЕНИЯТА, А НЕ ЗА ПРЕИЗЧИСЛЯВАНЕТО.</b> Разликата е цялата разлика
 * между „не намалявам основата“ и „не смятам годишен данък“. Работодателят по основното ТПО е
 * ЗАДЪЛЖЕН да преизчисли по ал. 1 независимо дали лицето му е дало каквото и да било; без
 * документите той просто не прилага ал. 3. Слети в едно условие, лице без документи щеше да остане
 * съвсем без колони 6 и 17–22 — тоест справката щеше да мълчи там, където законът иска число.
 *
 * <p><b>⚠️ И ЧЛ. 49 НЯМА АЛИНЕЯ, С КОЯТО ЛИЦЕТО ДА ОТКАЖЕ ПРЕИЗЧИСЛЯВАНЕ.</b> Сверено дословно
 * върху ал. 1–8 на официалния текст (ЗДДФЛ, консолидиран 2026 г.). Онова, което лицето подава или
 * не подава, е по ал. 4 и управлява САМО намаленията. Ако някой очаква „лицето поиска да не се
 * прави“ — такова правило в чл. 49 не се намери; най-близкото е т. 8 на ал. 4, която пита за
 * публични задължения и за намерение да се подава декларация по чл. 50, и която пак е условие за
 * ал. 3.
 *
 * <p><b>═══ ⚠️ ЧЛ. 22а (МЛАДИ СЕМЕЙСТВА) ГО НЯМА ТУК, И ТОВА НЕ Е ПРОПУСК НА ТАЗИ ФАЗА ═══</b>
 *
 * <p>Работодателят НЕ може да го приложи. Две независими доказателства: чл. 49 ал. 3 изброява
 * поименно чл. 19, 22, 18, 20, 22в и 22г и чл. 22а НЕ е сред тях; и образецът на справката няма
 * колона за него — колоните вървят чл. 18, чл. 19 (две), чл. 20, чл. 22 (три), чл. 22в, чл. 22г и
 * свършват. Същото важи за чл. 22д (безкасови плащания) и чл. 22е (ремонт на жилище): те се ползват
 * САМО с годишна данъчна декларация по чл. 50. Записано, за да не бъде добавено „за пълнота“.
 */
public final class BgArt49Reliefs {

  /**
   * ДОКУМЕНТИТЕ ПО ЧЛ. 49 АЛ. 4 — предоставени ли са в срок от 30 ноември до 31 декември.
   *
   * <p>⚠️ Без тях ал. 3 НЕ се прилага и всяка колона от 8 до 16 излиза нула — но колони 6 и 17–22
   * пак се смятат. Виж описанието на класа.
   */
  public boolean documentsProvided;

  /** Колона 8 — чл. 18: лица с 50 и над 50 на сто намалена работоспособност. */
  public BigDecimal disability = BigDecimal.ZERO;

  /** Колона 9 — чл. 19: лични вноски за допълнително ДОБРОВОЛНО ОСИГУРЯВАНЕ (пенсионно). */
  public BigDecimal voluntaryPension = BigDecimal.ZERO;

  /** Колона 10 — чл. 19: лични вноски за доброволно ЗДРАВНО осигуряване и застраховки „Живот“. */
  public BigDecimal voluntaryHealthLife = BigDecimal.ZERO;

  /** Колона 11 — чл. 20: вноски по чл. 9а КСО за осигурителен стаж при пенсиониране. */
  public BigDecimal serviceYears = BigDecimal.ZERO;

  /** Колона 12 — чл. 22 ал. 1 т. 1: дарения в полза на лица с код 01 (до 5 на сто). */
  public BigDecimal donationsCode01 = BigDecimal.ZERO;

  /** Колона 13 — чл. 22 ал. 1 т. 2: дарения за култура, код 02 (до 15 на сто). */
  public BigDecimal donationsCode02 = BigDecimal.ZERO;

  /** Колона 14 — чл. 22 ал. 1 т. 3: дарения в полза на лица с код 03 (до 50 на сто). */
  public BigDecimal donationsCode03 = BigDecimal.ZERO;

  /** Колона 15 — чл. 22в: облекчение за деца. */
  public BigDecimal children = BigDecimal.ZERO;

  /** Колона 16 — чл. 22г: облекчение за деца с увреждания. */
  public BigDecimal disabledChildren = BigDecimal.ZERO;

  /** Сборът от колони 8 до 16 — умалителят на колона 17. */
  public BigDecimal total() {
    return nz(disability)
        .add(nz(voluntaryPension))
        .add(nz(voluntaryHealthLife))
        .add(nz(serviceYears))
        .add(nz(donationsCode01))
        .add(nz(donationsCode02))
        .add(nz(donationsCode03))
        .add(nz(children))
        .add(nz(disabledChildren));
  }

  /** Сборът от колони 12, 13 и 14 — този, който указание т. 7 ограничава до 65 на сто. */
  public BigDecimal donationsTotal() {
    return nz(donationsCode01).add(nz(donationsCode02)).add(nz(donationsCode03));
  }

  @Override
  public String toString() {
    return "к.8="
        + disability
        + " к.9="
        + voluntaryPension
        + " к.10="
        + voluntaryHealthLife
        + " к.11="
        + serviceYears
        + " к.12="
        + donationsCode01
        + " к.13="
        + donationsCode02
        + " к.14="
        + donationsCode03
        + " к.15="
        + children
        + " к.16="
        + disabledChildren
        + " (документи по ал. 4: "
        + (documentsProvided ? "да" : "НЕ")
        + ")";
  }

  private static BigDecimal nz(BigDecimal value) {
    return value == null ? BigDecimal.ZERO : value;
  }
}
