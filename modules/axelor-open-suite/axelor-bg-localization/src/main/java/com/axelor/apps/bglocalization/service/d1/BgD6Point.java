/**
 * НОМЕРАТА НА ТОЧКИТЕ от Приложение № 4 към чл. 2 ал. 2 — Декларация обр. № 6 — и връзката „фонд →
 * точка“.
 *
 * <p><b>⚠️ ГРУПИРАНЕТО НЕ Е ОГЛЕДАЛНО НА Д1, И ТОВА Е ЦЯЛАТА ПРИЧИНА ТОЗИ КЛАС ДА СЪЩЕСТВУВА.</b>
 * Изкушението е Д6 да се получи като сбор по точките на Д1. Двете декларации групират по РАЗЛИЧЕН
 * начин, и разликите са три:
 *
 * <ul>
 *   <li><b>ТЗПБ.</b> Д1 т. 22 е „за фондовете на ДОО <b>БЕЗ</b> ТЗПБ“ и дава на ТЗПБ своя точка
 *       (22.2). Д6 т. 10 иска „сумата на дължимите осигурителни вноски за фондовете на ДОО за
 *       всички осигурени лица“ — БЕЗ изключение. Тоест ТЗПБ е ВЪТРЕ в т. 10. Пренесено едно към
 *       едно, т. 10 щеше да е по-малка точно с ТЗПБ — правдоподобна разлика от порядъка на половин
 *       процент, заради която равенството по чл. 2 ал. 4 не се затваря.
 *   <li><b>Здравното.</b> Д1 го разцепва на ТРИ точки по база (22.1, 18, 28); Д6 т. 14 ги СЛИВА —
 *       „за всички осигурени лица“, без разграничение. Това е и независимото потвърждение, че
 *       разграничителят е БАЗА на перото, а не фонд: като база той просто не участва тук.
 *   <li><b>ДЗПО.</b> Д1 дава на УПФ т. 26 и на ППФ т. 25 — тоест по-малкият номер е ППФ. Д6 ги
 *       подрежда обратно: т. 12 е УПФ, т. 13 е ППФ. Пренесен по номер вместо по фонд, редът се
 *       разменя, а двете суми са от един и същи порядък.
 * </ul>
 *
 * <p>Затова връзката тук е „КОД НА ФОНД → точка от Д6“, а НЕ „точка от Д1 → точка от Д6“. Фондът е
 * едно и също нещо в двете декларации; точката — не.
 */
