  /** Фонд „Гарантирани вземания на работниците и служителите“. Поле 17. */
  public static final String T15_GVRS = "15";

  /**
   * Удържан данък по чл. 41а, чл. 42 и чл. 49 ал. 5 ЗДДФЛ — БЕЗ данъка по т. 17. Поле 31: блок 2,
   * вид плащане 8 (при вид 7 — поле 18 на блок 1).
   */
  public static final String T16_TAX = "16";

  /**
   * ВИД ПЛАЩАНЕ 5 — вноските за месеца, изплатени през СЪЩИЯ месец.
   *
   * <p>⚠️ 5 и 6 НЕ СЕ ИЗБИРАТ ОТ КОДА: разликата е КОГА е изплатено, а фишът не е вързан с реалното
   * плащане. Затова т. 8.1 е ръчна и непопълнена спира генерирането — виж {@link
   * #PAYMENT_KIND_HINT}.
   */
  public static final String PAYMENT_KIND_SAME_MONTH = "5";

  /**
   * ВИД ПЛАЩАНЕ 6 — вноските за месеца, изплатени в ПО-КЪСЕН месец. Тогава месецът на блок 2
   * (данъкът) е месецът на изплащане, а датите — датата на изплащане (т. 18).
   */
  public static final String PAYMENT_KIND_LATER_MONTH = "6";

  /**
   * ВИД ПЛАЩАНЕ 8 — удържаният данък по чл. 42 ЗДДФЛ. Не се избира: файлът го пише сам в блок 2,
   * когато декларацията носи данък (т. 16 или т. 17).
   */
  public static final String PAYMENT_KIND_TAX = "8";

  /**
   * ПОДСКАЗКАТА НА Т. 8.1 И ТЕКСТЪТ НА ОТКАЗА — един низ за двете места.
   *
   * <p>⚠️ Същият низ стои като {@code help} на {@code BgD6Declaration.t81PaymentKind}; свидетелят
   * {@code BgD6FileFormatTest} ги държи равни.
   */
  public static final String PAYMENT_KIND_HINT =
      "5 — изплатено през същия месец; 6 — изплатено в по-късен месец";

  /**
   * ВИД ПЛАЩАНЕ ПО Т. 8 — код 7, за събирачите на диворастящи гъби и плодове.
   *
   * <p><b>ДОСЛОВНО, указание т. 8 буква „в“:</b> „за дължимите осигурителни вноски за лицата, които
   * извършват дейност по събиране на диворастящи гъби и плодове, И ДАНЪК ПО ЧЛ. 41А от Закона за
   * данъците върху доходите на физическите лица, се попълва код - 7.“
   *
   * <p><b>⚠️ ЕДИН КОД ЗА ДВЕТЕ ЗАДЪЛЖЕНИЯ, И САМО ТУК.</b> При всички останали вноските и данъкът
   * се делят на различни видове плащане (5 или 6 за вноските по буква „а“, 8 за данъка по чл. 42 по
   * буква „б“). Тази точка е ЕДИНСТВЕНАТА, в която едно число покрива и двете — затова кодът е
   * решение по НОРМА, а не избор от списък.
   *
   * <p>⚠️ Тук, а не в {@code BgD6Emitter}: точките и кодовете на Приложение № 4 живеят на едно
   * място, и точно затова разминаване между низа и указанието се вижда на един екран.
   */
