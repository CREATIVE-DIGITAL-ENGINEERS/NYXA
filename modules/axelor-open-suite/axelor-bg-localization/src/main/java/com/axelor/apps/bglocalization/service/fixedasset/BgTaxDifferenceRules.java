package com.axelor.apps.bglocalization.service.fixedasset;

import com.axelor.apps.account.db.FixedAsset;
import com.axelor.apps.bglocalization.db.BgFixedAssetWriteOff;
import java.math.BigDecimal;

/**
 * Данъчните временни разлики от амортизируеми активи, като чисти функции — ядрото на справката за
 * ГДД.
 *
 * <p><b>Смятането НЕ зависи от layout-а на образеца.</b> Величините идват от ЗКПО и са сверени в
 * WS-A1–A4; кое приложение и коя колона на образец 1010 ги носи е административен въпрос и живее
 * отделно, в {@code BgGddMapping}. Тъй че справката е готова, преди образецът за 2026 г. да излезе.
 *
 * <p>Сверено дословно на 10.09.2026 г. срещу консолидирания ЗКПО (посл. изм. и доп. ДВ бр. 30 от 27
 * март 2026 г.).
 */
public final class BgTaxDifferenceRules {

  private BgTaxDifferenceRules() {}

  /** Видът на реда в справката — всеки вид отговаря на РАЗЛИЧЕН член. */
  public static final class Kind {
    /**
     * Годишните СЧЕТОВОДНИ разходи за амортизации — чл. 54 ал. 2, шифър 7010, колона А.
     *
     * <p>⚠️ БРУТНА сума, не нетна разлика. Образец 1010 иска двете числа поотделно: 7010 носи
     * счетоводната амортизация, 8010 — данъчната, а нетирането е работа на самата декларация, която
     * сумира колона А и колона Б. Един нетен ред би оставил и двата шифъра празни в обичайния
     * случай, когато двата плана съвпадат — а те се попълват и тогава.
     */
    public static final String ART54_ACCOUNTING = "ART54_ACCOUNTING";

    /** Годишните ДАНЪЧНИ амортизации — чл. 54 ал. 1, шифър 8010, колона Б. Също БРУТНА сума. */
    public static final String ART54_TAX = "ART54_TAX";

    /** Увеличение със СБС при счетоводно отписване — чл. 66 ал. 1. */
    public static final String ART66_AL1 = "ART66_AL1";

    /** Намаление с ДБС при отписване от ДАП — чл. 66 ал. 2. */
    public static final String ART66_AL2 = "ART66_AL2";

    /** Обръщането по чл. 59 ал. 2, потвърдено от съставителя. */
    public static final String ART59_AL2 = "ART59_AL2";

    /**
     * Обръщане по чл. 59 ал. 2, което ЧАКА потвърждение — видим ред, не пропуск.
     *
     * <p>⚠️ Съществува, защото тихото пропускане прави дупката невидима. Забравено потвърждение е
     * пропусната ЗАДЪЛЖИТЕЛНА корекция, тоест по-малка данъчна печалба от дължимата — скрит данъчен
     * пасив. Същата асиметрия, по която ДДС гардрейлът отказва да свали корекция без доказателство:
     * показваш, не мълчиш.
     */
    public static final String ART59_AL2_PENDING = "ART59_AL2_PENDING";

    /**
     * Информативен ред: активът остава в ДАП по чл. 60 ал. 3 т. 2 (вдигнат праг).
     *
     * <p>Сумата му е НУЛА и това е целият смисъл — редът съществува, за да се види, че данъчната
     * амортизация ПРОДЪЛЖАВА, въпреки че активът е излязъл от счетоводния план. Липсата на ред тук
     * е неразличима от „няма такъв актив“.
     */
    public static final String ART60_AL3_T2 = "ART60_AL3_T2";

    private Kind() {}
  }

  /**
   * Годишната разлика по <b>чл. 54</b> за един актив.
   *
   * <p><b>ал. 1</b>, дословно: „При определяне на данъчния финансов резултат <b>се признават
   * годишните данъчни амортизации</b>, определени по реда на тази глава.“ → данъчната амортизация е
   * МИНУСЪТ.
   *
   * <p><b>ал. 2</b> (доп. — ДВ, бр. 110 от 2007 г., в сила от 01.01.2008 г.), дословно:
   * „Счетоводните разходи за амортизации <b>не се признават</b> за данъчни цели. При определяне на
   * данъчния финансов резултат счетоводният финансов резултат <b>се увеличава със счетоводните
   * амортизации</b>, независимо от това дали отчитането им води до намаляване на счетоводния
   * финансов резултат за годината на счетоводното им отчитане.“ → счетоводната амортизация е
   * ПЛЮСЪТ.
   *
   * <p>⚠️ <b>Алинеите се разменят лесно.</b> „+счетоводна (ал. 1) − данъчна (ал. 2)“ е обратното на
   * закона: ал. 1 е данъчната страна, ал. 2 — счетоводната. Проверката е в самите текстове по-горе,
   * не в паметта.
   *
   * <p>⚠️ И плюсът е БЕЗУСЛОВЕН. „независимо от това дали отчитането им води до намаляване на
   * счетоводния финансов резултат“ значи, че счетоводната амортизация се прибавя дори когато не е
   * минала през резултата (например капитализирана в друг актив) — тоест не се нетира срещу нищо.
   *
   * <p>При подразбирането на този модул (счетоводен план = данъчен) резултатът е НУЛА. Ненулев е
   * само когато счетоводният полезен срок е избран различен от данъчния.
   *
   * <p>⚠️ <b>СПРАВКАТА НЕ ПОЛЗВА ТОВА ЧИСЛО.</b> Образец 1010 иска двете БРУТНИ суми поотделно —
   * шифър 7010 (счетоводна) и шифър 8010 (данъчна) — а нетирането е работа на самата декларация,
   * която сумира колона А и колона Б. Функцията остава, защото изразява посоката на чл. 54 с едно
   * число и тестът ѝ пази разместването на алинеите; но редовете се излъчват брутни.
   */
  public static BigDecimal art54Adjustment(
      BigDecimal accountingDepreciation, BigDecimal taxDepreciation) {
    BigDecimal accounting =
        accountingDepreciation == null ? BigDecimal.ZERO : accountingDepreciation;
    BigDecimal tax = taxDepreciation == null ? BigDecimal.ZERO : taxDepreciation;
    return accounting.subtract(tax);
  }

  /**
   * Увеличението със СБС по <b>чл. 66 ал. 1</b> — в годината на СЧЕТОВОДНОТО отписване.
   *
   * <p>Дословно: „Когато активът се отписва от счетоводния амортизационен план, при определяне на
   * данъчния финансов резултат счетоводният финансов резултат <b>се увеличава със счетоводната
   * балансова стойност</b> на актива.“
   *
   * <p>Изключенията по ал. 3 се прилагат през {@link BgAssetWriteOffRules#art66Applies} — т. 1–3
   * важат само когато ДБС превишава СБС, а т. 4 (преобразуване) е безусловна. Затова НЕ се смята
   * сляпо +СБС.
   */
  public static BigDecimal art66Increase(BgFixedAssetWriteOff writeOff) {
    if (writeOff == null || !applies(writeOff)) {
      return BigDecimal.ZERO;
    }
    return nz(writeOff.getAccountingCarryingValue());
  }

  /**
   * Намалението с ДБС по <b>чл. 66 ал. 2</b> — САМО когато активът наистина е излязъл от ДАП.
   *
   * <p>Дословно: „Когато активът се отписва от данъчния амортизационен план, при определяне на
   * данъчния финансов резултат счетоводният финансов резултат <b>се намалява с данъчната
   * стойност</b> на актива.“
   *
   * <p>⚠️ <b>ТОВА Е TIMING GATE-ЪТ, И ТОЙ Е ЦЕЛИЯТ СМИСЪЛ НА {@code isArt60Al2Applied}.</b> Ал. 1 и
   * ал. 2 описват ДВЕ РАЗЛИЧНИ СЪБИТИЯ — отписване от СЧЕТОВОДНИЯ и от ДАНЪЧНИЯ план — и по чл. 60
   * ал. 3 те често падат в РАЗЛИЧНИ ГОДИНИ: напълно амортизиран за счетоводни цели актив (т. 1) или
   * отписан заради вдигнат праг (т. 2) остава в ДАП и излиза по реда на ал. 1, тоест при пълно
   * ДАНЪЧНО амортизиране (ал. 4). Справка, която пише +СБС и −ДБС в една и съща година, греши
   * декларацията — затова −ДБС се чете само при вдигнат флаг.
   *
   * <p>Върнатата стойност е ПОЛОЖИТЕЛНА величина; знакът е в вида на реда, не в числото, за да може
   * справката да сумира и двете колони, без да гадае посоки.
   */
  public static BigDecimal art66Decrease(BgFixedAssetWriteOff writeOff) {
    if (writeOff == null
        || !applies(writeOff)
        || !Boolean.TRUE.equals(writeOff.getIsArt60Al2Applied())) {
      return BigDecimal.ZERO;
    }
    return nz(writeOff.getTaxValue());
  }

  /** Дължи ли се изобщо преобразуване по чл. 66, или попада в изключенията по ал. 3. */
  public static boolean applies(BgFixedAssetWriteOff writeOff) {
    if (writeOff == null) {
      return false;
    }
    return BgAssetWriteOffRules.art66Applies(
        writeOff.getArt66ExceptionSelect(),
        writeOff.getAccountingCarryingValue(),
        writeOff.getTaxValue());
  }

  /**
   * Обръщането по <b>чл. 59 ал. 2</b>, ако е потвърдено — иначе нула.
   *
   * <p>Дословно: „При определянето на данъчния финансов резултат <b>за годината, през която е
   * изтекъл дванадесетмесечният срок</b> по ал. 1, годишната данъчна амортизация… се намалява с
   * размера на начислената данъчна амортизация за актива през дванадесетте месеца, през които
   * активът не се е използвал.“
   *
   * <p>⚠️ Потвърждаването решава ДАЛИ, а НЕ в коя година. Годината е {@code bgArt59Al2Year} и е
   * закована от закона; потвърждаване след подадена за нея ГДД значи КОРИГИРАЩА декларация, не ред
   * в текущата.
   */
  public static BigDecimal art59Reversal(FixedAsset fixedAsset) {
    if (fixedAsset == null || !isArt59Confirmed(fixedAsset)) {
      return BigDecimal.ZERO;
    }
    return nz(fixedAsset.getBgArt59Al2Reversal());
  }

  /** Потвърдено ли е обръщането. */
  public static boolean isArt59Confirmed(FixedAsset fixedAsset) {
    return fixedAsset != null && Boolean.TRUE.equals(fixedAsset.getBgIsArt59Al2Confirmed());
  }

  /**
   * Има ли изчислено, но НЕПОТВЪРДЕНО обръщане — редът „чака потвърждение“.
   *
   * <p>Гледа се сумата, а не само датата на спиране: нула обръщане няма какво да чака. Активите по
   * чл. 60 ал. 3 изобщо не се спират (чл. 59 ал. 4) и WS-A4 вече им оставя нула — тъй че тук не се
   * появяват.
   */
  public static boolean isArt59Pending(FixedAsset fixedAsset) {
    return fixedAsset != null
        && !isArt59Confirmed(fixedAsset)
        && nz(fixedAsset.getBgArt59Al2Reversal()).signum() != 0;
  }

  /**
   * Годината, в която редът влиза в декларацията.
   *
   * <p>За чл. 59 това е {@code bgArt59Al2Year}, а за чл. 66 — {@code taxYear} на записа в
   * регистъра. Изнесено като функция, защото „годината на реда“ е точно мястото, където справките
   * грешат.
   */
  public static Integer art59Year(FixedAsset fixedAsset) {
    return fixedAsset == null ? null : fixedAsset.getBgArt59Al2Year();
  }

  /**
   * Приключил ли е ДАНЪЧНИЯТ план на актива през дадена година.
   *
   * <p><b>Защо съществува.</b> При изключение по чл. 60 ал. 3 активът се отписва счетоводно, но
   * ОСТАВА в ДАП и излиза от него по реда на ал. 1 — при пълно данъчно амортизиране (ал. 4). Тогава
   * +СБС по чл. 66 ал. 1 идва в годината на счетоводното отписване, а −ДБС по ал. 2 — в тази,
   * по-късна година. Без тази функция намалението или се пише в грешната година, или изчезва
   * съвсем.
   *
   * <p>Мери се по РЕАЛИЗИРАНИТЕ данъчни редове: планът е приключил в годината, в която последният
   * реализиран ред пада и след която не остава начисляване. Таванът, който го изчерпва, е чл. 53
   * ал. 3 — „начислената данъчна амортизация не може да превишава данъчната амортизируема стойност
   * на актива“.
   */
  public static boolean taxPlanFinishedInYear(FixedAsset fixedAsset, int year) {
    if (fixedAsset == null) {
      return false;
    }
    java.util.List<com.axelor.apps.account.db.FixedAssetLine> lines =
        fixedAsset.getFiscalFixedAssetLineList();
    if (lines == null || lines.isEmpty()) {
      return false;
    }
    java.time.LocalDate last = null;
    boolean hasLater = false;
    for (com.axelor.apps.account.db.FixedAssetLine line : lines) {
      if (line == null || line.getDepreciationDate() == null) {
        continue;
      }
      if (line.getStatusSelect()
          != com.axelor.apps.account.db.repo.FixedAssetLineRepository.STATUS_REALIZED) {
        // Планов ред след годината значи, че планът НЕ е приключил — има още какво да се начисли.
        if (line.getDepreciationDate().getYear() > year) {
          hasLater = true;
        }
        continue;
      }
      if (last == null || line.getDepreciationDate().isAfter(last)) {
        last = line.getDepreciationDate();
      }
    }
    return last != null && last.getYear() == year && !hasLater;
  }

  private static BigDecimal nz(BigDecimal v) {
    return v == null ? BigDecimal.ZERO : v;
  }
}
