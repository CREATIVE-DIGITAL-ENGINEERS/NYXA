package com.axelor.apps.bglocalization.service.common;

import java.math.BigDecimal;
import java.math.RoundingMode;

/**
 * Превалутиране от левове в евро по Закона за въвеждане на еврото в Република България.
 *
 * <p><b>Каноничният конвертор на локализацията.</b> Всеки левов праг в българското законодателство
 * — прагът за данъчен амортизируем актив по ЗКПО чл. 50/51, регистрационният праг по ЗДДС, лимитите
 * по ЗДДФЛ — се чете като евро по едно и също правило. Затова правилото се пише ВЕДНЪЖ и се одитира
 * на едно място; втора конкурентна функция значи два отговора на един въпрос.
 *
 * <p><b>Защо изобщо се превалутира, вместо сумата да се препише.</b> ЗВЕРБ <b>чл. 11 ал. 2</b>,
 * дословно: „В съответствие с чл. 6 - 9 от Регламент (ЕО) № 974/98 стойностите, посочени в левове в
 * съществуващите правни инструменти, <b>се считат за стойности в евро</b> при прилагане на
 * официалния валутен курс и правилата за превалутиране по чл. 12 и съответно за закръгляване по чл.
 * 13 или по специалните правила за закръгляване, предвидени в този закон.“ Тоест левовата сума в
 * закон, който не е бил индивидуално превалутиран, СЕ ЧЕТЕ като евро — не остава в левове и не се
 * заменя с кръгло число по преценка.
 *
 * <p>Сверено дословно срещу ЗАКОН ЗА ВЪВЕЖДАНЕ НА ЕВРОТО В РЕПУБЛИКА БЪЛГАРИЯ, обн. ДВ бр. 70 от 20
 * август 2024 г., изм. и доп. ДВ бр. 25 от 25 март 2025 г., изм. ДВ бр. 49 от 17 юни 2025 г., изм.
 * и доп. ДВ бр. 63 от 1 август 2025 г. ⚠️ Прочетено през разпечатка на Lex.bg, не през официалния
 * текст на ДВ/БНБ — <b>да се потвърди</b>.
 */
public final class BgCurrencyConversion {

  private BgCurrencyConversion() {}

  /**
   * Официалният валутен курс на лева към еврото.
   *
   * <p><b>Числото НЕ е в закона — то е в регламента, към който законът препраща.</b> ЗВЕРБ <b>чл.
   * 5</b>, дословно: „Официалният валутен курс на лева към еврото е неотменимо фиксираният валутен
   * курс на лева към еврото, определен в <b>Регламент на Съвета</b>, приет в съответствие с чл.
   * 140, параграф 3 от Договора за функционирането на Европейския съюз.“ Тоест ЗВЕРБ описва само
   * ФОРМАТА — „изразен с шест цифри с всичките пет знака след десетичната запетая“ (чл. 12 ал. 1).
   *
   * <p>Актът е <b>Регламент (ЕС) 2025/1409 на Съвета от 8 юли 2025 г. за изменение на Регламент
   * (ЕО) № 2866/98 по отношение на валутния курс към еврото за България</b>. Член 1, дословно: „В
   * член 1 от Регламент (ЕО) № 2866/98 се вмъква следният ред между валутните курсове, приложими за
   * белгийския франк и германската марка: <b>„= 1,95583 Bulgarian lev“</b>.“ В сила от 1 януари
   * 2026 г. Сверено срещу EUR-Lex, CELEX:32025R1409.
   *
   * <p>Тоест числото е неотменимо фиксирано с акт на Съвета, а не избрано тук — и точно затова не
   * се конфигурира. Тестът пази формата (шест цифри, пет знака), която чл. 12 ал. 1 изисква.
   */
  public static final BigDecimal OFFICIAL_RATE = new BigDecimal("1.95583");

  /**
   * Знаци за самото деление, преди закръгляването по чл. 13.
   *
   * <p>ЗВЕРБ <b>чл. 12 ал. 2</b>: „Официалният валутен курс <b>не се закръглява или съкращава</b>
   * при извършването на превалутирането.“ Курсът тук е точен по конструкция (низ, не double), а
   * двайсетте знака гарантират, че междинното деление не влияе на решението по третия знак — то се
   * взима седемнайсет порядъка по-нагоре.
   *
   * <p>⚠️ И НЕ СЕ ДЕЛИ НА ОБЪРНАТ КУРС. Регламент (ЕО) № 1103/97 чл. 4 § 2 забранява ползването на
   * инверсен курс; умножението по 1/1.95583 дава друго число и е нарушение, а не оптимизация.
   */
  private static final int CONVERSION_SCALE = 20;

  /**
   * Превалутира левова сума в евро по общото правило — <b>чл. 12 ал. 1</b> плюс <b>чл. 13 ал.
   * 1</b>.
   *
   * <p><b>чл. 12 ал. 1</b>, дословно: „В съответствие с чл. 4 от Регламент (ЕО) № 1103/97
   * превалутирането от левове в евро се извършва, като числовата стойност в левове се <b>раздели на
   * пълната числова стойност на официалния валутен курс</b>, изразен с шест цифри с всичките пет
   * знака след десетичната запетая.“
   *
   * <p><b>чл. 13 ал. 1</b>, дословно: „…след превалутиране съгласно чл. 12 получената сума се
   * закръглява до втория знак след десетичната запетая <b>на базата на третия знак</b> след
   * десетичната запетая в съответствие със следното математическо правило за закръгляване: 1.
   * когато третият знак след десетичната запетая е по-малък от пет, вторият знак след десетичната
   * запетая остава непроменен; 2. когато третият знак след десетичната запетая е равен на или
   * по-голям от пет, вторият знак след десетичната запетая се увеличава с една единица.“
   *
   * <p><b>Защо HALF_UP изразява чл. 13 ал. 1 точно, а не приблизително.</b> Двете правила биха се
   * разминали само в един от два случая: третият знак под 5, но остатъкът над втория знак ≥ 0,005 —
   * или третият знак 5 и повече, но остатъкът < 0,005. И двата са аритметически невъзможни, защото
   * третият знак вече определя дали остатъкът е под или над пет хилядни. Тоест равенството е
   * доказуемо, а не съвпадение на примери.
   *
   * <p>⚠️ Общото правило важи и за счетоводните стойности, не само за прагове в закон — ЗВЕРБ
   * <b>чл. 48 ал. 2</b>: „<b>Стойността на всеки отделен наличен актив или пасив</b> се
   * преизчислява от левове в евро в съответствие с правилата по чл. 12 и <b>се закръглява по чл.
   * 13</b>, с изключение на позициите на възнагражденията за положен труд, паричните и социалните
   * помощи, както и пенсиите по част първа от Кодекса за социално осигуряване и добавките към тях и
   * гарантираните вземания по Закона за гарантираните вземания на работниците и служителите при
   * несъстоятелност на работодателя, които се превалутират по реда на чл. 45.“ Тоест разделението
   * „чл. 13 за активи, чл. 45 само за заплати“ е закон на две места, не извод.
   *
   * <p>(Самото преизчисляване на ЗАВАРЕНИТЕ активи по чл. 48 ал. 2 и данъчното признаване на
   * курсовите разлики по ал. 4 са ОТДЕЛНА задача — този конвертор дава правилото, не я изпълнява.)
   *
   * @param bgn сума в левове; не се допуска {@code null} — вж. защо в {@link #requireAmount}
   * @return сумата в евро, закръглена до два знака
   */
  public static BigDecimal toEur(BigDecimal bgn) {
    requireAmount(bgn);
    return bgn.divide(OFFICIAL_RATE, CONVERSION_SCALE, RoundingMode.HALF_UP)
        .setScale(2, RoundingMode.HALF_UP);
  }

  /**
   * Превалутира по СПЕЦИАЛНОТО правило за възнаграждения, обезщетения, помощи и пенсии — <b>чл. 45
   * ал. 1</b>.
   *
   * <p>Дословно: „Считано от датата на въвеждане на еврото в Република България възнагражденията за
   * положен труд, обезщетенията, паричните и социалните помощи, пенсиите по част първа от Кодекса
   * за социално осигуряване и добавките към тях и гарантираните вземания по Закона за гарантираните
   * вземания на работниците и служителите при несъстоятелност на работодателя се изплащат в евро и
   * се преизчисляват съгласно чл. 12. <b>В изключение от правилото на чл. 13, ако третият знак след
   * десетичната запетая е по-голям от нула, вторият знак след десетичната запетая се увеличава с
   * една единица.</b>“
   *
   * <p><b>Тук стои като режим на СЪЩАТА утилита, а не като втора функция някъде другаде.</b>
   * Разликата с {@link #toEur} е една стъпка, но сменя резултата: 700 лв дават 357,90 по чл. 13 и
   * 357,91 по чл. 45. Ако бяха два файла, разминаването щеше да се появи като „грешка в
   * закръглянето“ вместо като избор на режим.
   *
   * <p>⚠️ <b>И НЕ Е ROUND_UP/CEILING.</b> Законът гледа <b>третия знак</b>: при 0,0001 третият знак
   * е нула, тъй че увеличение НЕ се прави, докато CEILING би вдигнал. Затова правилото е написано
   * буквално — през третата цифра — а не през удобна константа на {@code RoundingMode}.
   *
   * <p>⚠️ Обхватът е тесен и изчерпателен: изброените в ал. 1 позиции. Праг за актив, данъчен лимит
   * или счетоводно салдо НЕ са между тях — за тях важи {@link #toEur}. Кое перо на фиша е
   * „възнаграждение“ по смисъла на ал. 1 е преценка на payroll частта, не на този файл.
   *
   * @param bgn сума в левове
   * @return сумата в евро по правилото на чл. 45 ал. 1
   */
  public static BigDecimal toEurForRemunerations(BigDecimal bgn) {
    requireAmount(bgn);
    BigDecimal exact = bgn.divide(OFFICIAL_RATE, CONVERSION_SCALE, RoundingMode.HALF_UP);
    BigDecimal twoDigits = exact.setScale(2, RoundingMode.DOWN);
    // Разликата между отрязване на ТРИ и на ДВА знака Е третият знак — стойност между 0,000 и
    // 0,009. Тъй че „третият знак е по-голям от нула“ се чете директно, без вадене на цифри.
    BigDecimal thirdDigit = exact.setScale(3, RoundingMode.DOWN).subtract(twoDigits);
    if (thirdDigit.signum() > 0) {
      return twoDigits.add(new BigDecimal("0.01"));
    }
    return twoDigits;
  }

  /**
   * Отказва {@code null} вместо да го приеме за нула.
   *
   * <p>Нулата не е безопасна стойност по подразбиране за конвертор, който храни ПРАГОВЕ: праг нула
   * значи „всичко минава“, тоест тих отказ от гейта. Тъй че липсващата сума се обажда веднага.
   */
  private static void requireAmount(BigDecimal bgn) {
    if (bgn == null) {
      throw new IllegalArgumentException(
          "Липсва сума за превалутиране. Нулата не е подразбиране: праг нула значи „всичко минава“,"
              + " тоест мълчалив отказ от проверката, вместо видима грешка.");
    }
  }
}
