  /**
   * ПОЛЕ 12 от вида договор — и ОТКАЗ, когато преводът не е еднозначен.
   *
   * <p><b>⚠️ ГОЛИТЕ „68“ И „121a“ СА СБОРНИ</b> — виж {@link #AMBIGUOUS}; точките им са свои
   * стойности и се превеждат еднозначно. „duk“ и „gd“ изобщо не са трудови договори и нямат място в
   * регистъра на заетостта.
   *
   * @param bgContractType стойност на {@code bg.employment.contract.type.select}
   * @param employType вид правоотношение: „01“ трудово, „02“/„03“ служебно
   */
  public static String contractGroundFor(String bgContractType, String employType) {
    String type = nz(bgContractType);
    // ДУК и ГД — ПЪРВИ: за тях видът правоотношение е празен (не са по КТ), и проверката по-долу
    // би обявила договора за управление за „служебно правоотношение (вид „“)“.
    if ("duk".equals(type) || "gd".equals(type)) {
      throw new BgEtzUnmappedGroundException(
          "„"
              + type
              + "“ не е трудов договор (ДУК е по ТЗ/ЗЗД, ГД — по ЗЗД) и НЯМА място в"
              + " регистъра на заетостта: там се вписват трудови и служебни правоотношения."
              + " ⚠️ ЕТЗ за такъв договор изобщо не се подава.");
    }
    if (!nz(employType).isEmpty() && !"01".equals(nz(employType))) {
      throw new BgEtzUnmappedGroundException(
          "основанието по т. 12 за СЛУЖЕБНО правоотношение (вид „"
              + nz(employType)
              + "“) не може да се изведе: номенклатурата е друга (кодове 100–116 и 198 по ЗДСл, 199"
              + " при вид 03), а"
              + " модулът няма носител на основанието за издаване на акта за назначаване."
              + " ⚠️ Стойността се въвежда от човек, не се извежда от вида договор по КТ.");
    }
    String code = CONTRACT_TYPE_MAP.get(type);
    if (code != null) {
      return code;
    }
    String why = AMBIGUOUS.get(type);
    if (why != null) {
      throw new BgEtzUnmappedGroundException(
          "видът договор „"
              + type
              + "“ НЕ СЕ ПРЕВЕЖДА еднозначно към т. 12: "
              + why
              + ". ⚠️ Един от няколкото кода би бил ДОГАДКА, а грешното основание се вписва"
              + " мълчаливо и се маха само със заличаване (код корекция 2).");
    }
    throw new BgEtzUnmappedGroundException(
        "видът договор „"
            + (type.isEmpty() ? "(празен)" : type)
            + "“ няма съответствие в т. 12. Допустимите кодове са в Наредбата (т. 12);"
            + " съответствието се допълва в BgEtzGrounds, а не се подразбира.");
  }

  /**
   * ПОЛЕ 27 от основанието за прекратяване — и ОТКАЗ при сборна или непокрита стойност.
   *
   * @param bgTerminationGround стойност на {@code bg.termination.ground.select}
   * @param legalFamily актът: „KT“, „ZDSL“, „ZVO“
   * @param employType вид правоотношение: „01“ трудово, „02“/„03“ служебно
   */
  public static String terminationGroundFor(
      String bgTerminationGround, String legalFamily, String employType) {

    String ground = nz(bgTerminationGround);
    if (ground.isEmpty()) {
      throw new BgEtzUnmappedGroundException(
          "договорът няма попълнено основание за прекратяване (EndOfContractReason"
              + ".bgTerminationGround), а т. 27 е задължителна при тип на документа 3.");
    }
    String why = AMBIGUOUS.get(ground);
    if (why != null) {
      throw new BgEtzUnmappedGroundException(
          "основанието „"
              + ground
              + "“ НЕ СЕ ПРЕВЕЖДА еднозначно към т. 27: "
              + why
              + ". ⚠️ Изберете точната точка в речника на основанията, преди да се подаде ЕТЗ.");
    }
    // ⚠️ ЗВО НЕ Е В НОМЕНКЛАТУРАТА, И ТОВА НЕ Е ПРОПУСК В ТАБЛИЦАТА ТУК.
    // Списъкът за трудово правоотношение покрива КТ, Закона за администрацията и Закона за
    // съдебната власт. Прекратяване по чл. 58 ал. 1 т. 3 ЗВО няма свой код. Кодът „064 — друго“
    // съществува, но е ИЗЯВЛЕНИЕ на подателя, не превод: затова се отказва тук и решението остава
    // за човек.
    if ("ZVO".equals(nz(legalFamily))) {
      throw new BgEtzUnmappedGroundException(
          "основание по ЗВО („"
              + ground
              + "“) няма собствен код в т. 27: номенклатурата за"
              + " трудово правоотношение покрива КТ, Закона за администрацията и Закона за"
              + " съдебната власт. ⚠️ Съществува код „064 — друго“, но той е ИЗЯВЛЕНИЕ на"
              + " подателя, а не превод, и не се слага автоматично: ако това е волята на"
              + " работодателя, изберете основание „064 — друго“.");
    }
    String expected = GROUND_FAMILY.get(ground);
    if (expected != null && !nz(legalFamily).isEmpty() && !expected.equals(nz(legalFamily))) {
      throw new BgEtzUnmappedGroundException(
          "основанието „"
              + ground
              + "“ е по акт „"
              + expected
              + "“, а основанието за прекратяване носи акт „"
              + nz(legalFamily)
              + "“. ⚠️ Номерата се повтарят между актовете — поправете акта или основанието.");
    }
    String code = TERMINATION_MAP.get(ground);
    if (code == null) {
      throw new BgEtzUnmappedGroundException(
          "основанието „"
              + ground
              + "“ няма съответствие в т. 27. ⚠️ Кодовете идват от"
              + " Наредбата (т. 27) и НЕ следват номера на члена — „001“ е чл. 71 ал. 1 КТ, не"
              + " член 1. Съответствието се допълва в BgEtzGrounds.");
    }
    // Последна проверка: преведеният код трябва да е в ПОДНОМЕНКЛАТУРАТА на този вид
    // правоотношение. Пази срещу ред в таблицата, който сочи кода на другия списък.
    if (!isEndCode(code, employType)) {
      throw new BgEtzUnmappedGroundException(
          "преводът на „"
              + ground
              + "“ дава код "
              + code
              + ", който не е в номенклатурата за вид"
              + " правоотношение „"
              + nz(employType)
              + "“ — таблицата в BgEtzGrounds сочи към"
              + " другата подноменклатура.");
    }
    return code;
  }

  private static Map<String, String> codesFor(
      String employType, Map<String, String> kt, Map<String, String> zdsl) {
    return "01".equals(nz(employType)) ? kt : zdsl;
  }

