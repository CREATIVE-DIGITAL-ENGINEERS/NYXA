package com.axelor.apps.bglocalization.service.vat;

import com.axelor.apps.bglocalization.service.vat.adapter.BgVatPurchaseColumn;
import com.axelor.apps.bglocalization.service.vat.adapter.BgVatSalesColumn;
import com.axelor.apps.bglocalization.service.vat.dto.BgVatAmountDto;
import com.axelor.apps.bglocalization.service.vat.dto.BgVatDocumentDto;
import com.axelor.apps.bglocalization.service.vat.dto.BgVatExportRequestDto;
import java.math.BigDecimal;
import java.util.List;
import java.util.Map;
import java.util.TreeMap;

/**
 * Deterministic fingerprint of the SOURCE inputs of a VAT package (the collected documents plus the
 * manual cells / declarant / scope that feed the four files). A package stores this fingerprint at
 * generation; re-computing it later and comparing detects whether the underlying VAT data changed —
 * i.e. whether the prepared package is stale and must be regenerated.
 *
 * <p>Pure and dependency-free so it is unit-testable without a database. Generation itself is
 * deterministic given these inputs, so equal fingerprints ⇒ byte-identical files.
 */
public final class BgVatSourceFingerprint {

  private static final String SEP = "|";
  private static final String REC = "\n";

  private BgVatSourceFingerprint() {}

  public static String compute(List<BgVatDocumentDto> documents, BgVatExportRequestDto request) {
    StringBuilder sb = new StringBuilder();

    // Scope + header inputs that change the generated bytes.
    sb.append("company=").append(nz(request.getCompanyVatNumber())).append(SEP);
    sb.append("period=").append(request.getPeriodFrom()).append("..").append(request.getPeriodTo());
    sb.append(SEP).append("report=").append(nz(request.getReportType()));
    sb.append(SEP).append("enc=").append(nz(request.getEncoding()));

    // Manual DEKLAR cells + declarant snapshot (all affect DEKLAR/VIES output).
    sb.append(SEP).append("k33=").append(bd(request.getCoefficientK33()));
    sb.append(SEP).append("k70=").append(bd(request.getCell70()));
    sb.append(SEP).append("k71=").append(bd(request.getCell71()));
    sb.append(SEP).append("k80=").append(bd(request.getCell80()));
    sb.append(SEP).append("k81=").append(bd(request.getCell81()));
    sb.append(SEP).append("k82=").append(bd(request.getCell82()));
    sb.append(SEP).append("decl=").append(nz(request.getDeclarantSubmitter()));
    sb.append(SEP).append("cap=").append(nz(request.getDeclarantCapacity()));
    sb.append(REC);

    // Collected documents, in collector order (deterministic).
    if (documents != null) {
      for (BgVatDocumentDto doc : documents) {
        sb.append("doc")
            .append(SEP)
            .append(nz(doc.getNapDocumentType()))
            .append(SEP)
            .append(nz(doc.getDocumentNumber()))
            .append(SEP)
            .append(doc.getDocumentDate())
            .append(SEP)
            .append(nz(doc.getCounterpartyDiaryId()))
            .append(SEP)
            .append(bd(doc.getTotalBase()))
            .append(SEP)
            .append(bd(doc.getTotalVat()))
            .append(SEP)
            .append(bd(doc.getTotalGross()))
            .append(SEP)
            .append(nz(doc.getSupplyTypeArt163a()));

        List<BgVatAmountDto> buckets = doc.getAmounts();
        if (buckets != null) {
          for (BgVatAmountDto b : buckets) {
            sb.append(SEP)
                .append("amt:")
                .append(nz(b.getTaxCode()))
                .append("=")
                .append(bd(b.getBase()))
                .append("/")
                .append(bd(b.getVatAmount()));
          }
        }
        appendPurchase(sb, doc.getPurchaseAmounts());
        appendSales(sb, doc.getSalesAmounts());
        sb.append(REC);
      }
    }

    return BgVatHashUtil.sha256Hex(sb.toString().getBytes(java.nio.charset.StandardCharsets.UTF_8));
  }

  private static void appendPurchase(StringBuilder sb, Map<BgVatPurchaseColumn, BigDecimal> map) {
    if (map == null || map.isEmpty()) {
      return;
    }
    TreeMap<String, BigDecimal> sorted = new TreeMap<>();
    for (Map.Entry<BgVatPurchaseColumn, BigDecimal> e : map.entrySet()) {
      sorted.put(e.getKey().name(), e.getValue());
    }
    for (Map.Entry<String, BigDecimal> e : sorted.entrySet()) {
      sb.append(SEP).append("p:").append(e.getKey()).append("=").append(bd(e.getValue()));
    }
  }

  private static void appendSales(StringBuilder sb, Map<BgVatSalesColumn, BigDecimal> map) {
    if (map == null || map.isEmpty()) {
      return;
    }
    TreeMap<String, BigDecimal> sorted = new TreeMap<>();
    for (Map.Entry<BgVatSalesColumn, BigDecimal> e : map.entrySet()) {
      sorted.put(e.getKey().name(), e.getValue());
    }
    for (Map.Entry<String, BigDecimal> e : sorted.entrySet()) {
      sb.append(SEP).append("s:").append(e.getKey()).append("=").append(bd(e.getValue()));
    }
  }

  private static String nz(String v) {
    return v == null ? "" : v;
  }

  private static String bd(BigDecimal v) {
    return v == null ? "0" : v.stripTrailingZeros().toPlainString();
  }
}
