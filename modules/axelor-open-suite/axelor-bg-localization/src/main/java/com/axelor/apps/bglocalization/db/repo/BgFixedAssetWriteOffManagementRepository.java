package com.axelor.apps.bglocalization.db.repo;

import com.axelor.apps.bglocalization.db.BgFixedAssetWriteOff;
import com.axelor.apps.bglocalization.service.fixedasset.BgAssetRemoval;
import com.axelor.apps.bglocalization.service.fixedasset.BgAssetWriteOffRules;
import javax.persistence.PersistenceException;

/**
 * Пази съгласуваността на реда в регистъра по чл. 60/66 при всеки запис.
 *
 * <p><b>Какво прави.</b> Преизчислява {@code isArt66Applied} от избраното изключение по ал. 3 и от
 * двете стойности. Изключенията по т. 1–3 важат САМО когато данъчната стойност превишава
 * счетоводната балансова, тоест флагът не е независим избор — той е следствие. Ръчно отметнат, той
 * би отменил законно преобразуване или би приложил отменено.
 *
 * <p><b>И защо в repository, а не в изгледа.</b> Регистърът се пълни от {@code
 * BgFixedAssetDisposalServiceImpl} при отписване, редактира се от формата, а WS-A5 ще го чете за
 * ГДД — три пътя, от които само единият минава през екран. Същият довод, по който в този модул
 * стоят {@code BgDeclarantManagementRepository} и {@code BgPaySlipManagementRepository}.
 *
 * <p>И годината се държи в съгласие с датата: тя е носеща колона, за да се групира справката по
 * нея, но носеща не значи независима — отписване през 2028 не бива да стои в декларацията за 2027,
 * защото някой е пипнал числото.
 */
public class BgFixedAssetWriteOffManagementRepository extends BgFixedAssetWriteOffRepository {

  @Override
  public BgFixedAssetWriteOff save(BgFixedAssetWriteOff entity) {
    if (entity != null) {
      entity.setIsArt66Applied(
          BgAssetWriteOffRules.art66Applies(
              entity.getArt66ExceptionSelect(),
              entity.getAccountingCarryingValue(),
              entity.getTaxValue()));

      if (entity.getWriteOffDate() != null) {
        entity.setTaxYear(entity.getWriteOffDate().getYear());
      }

      refuseUnprovenVatRelease(entity);
    }
    return super.save(entity);
  }

  /**
   * Отказва „не подлежи на корекция по чл. 79 ЗДДС“ без доказано основание.
   *
   * <p><b>Двете условия са едновременни.</b> Съставителят може да освободи отписването, но само
   * когато:
   *
   * <ol>
   *   <li><b>обективното условие е изпълнено</b> — непреодолима сила по избраното основание (чл. 80
   *       ал. 2 т. 1 б. „а“) ИЛИ балансова стойност под 10 на сто от отчетната (т. 3 б. „г“). Това
   *       са ЕДИНСТВЕНИТЕ две, които системата може да провери сама;
   *   <li><b>обявено е доказано или потвърдено унищожаване И е посочен документът</b> — защото
   *       всяко освобождаване по ал. 2 виси под условие в ОТВАРЯЩОТО изречение на точката, не в
   *       буквата: т. 1 иска „доказано или потвърдено унищожаване, загуба или липса“, т. 3 —
   *       „доказано или потвърдено унищожаване, включително изхвърляне на стоки по начин, който
   *       води до необратимото им изчезване“.
   * </ol>
   *
   * <p><b>Обхватът на изключенията е само чл. 79.</b> Дословно, чл. 80 ал. 2: „Корекции по чл. 79
   * не се извършват в случаите на:“ — за сравнение ал. 1 гласи „Корекции по чл. 79, 79а и 79б не се
   * извършват:“. Тоест 79а (изменение в използването) и 79б не се освобождават оттук и този отказ
   * не ги засяга.
   *
   * <p><b>Защо пазачът гледа само {@code NOT_DUE}.</b> Останалите стойности не са твърдение за
   * несъществуващ факт, а описание на събитие, което си има свидетел: {@code CHARGED_AS_SUPPLY}
   * начислява данък, а {@code REVERSE_CHARGED} твърди ДОСТАВКА по глава деветнадесета „а“ —
   * твърдение, което фактурата по отписването потвърждава или опровергава пред очите на
   * съставителя. Само {@code NOT_DUE} свежда дължим данък до нула срещу условие, което системата не
   * вижда, и затова само тя се пази.
   *
   * <p><b>Защо отказ, а не предупреждение.</b> Посоката на грешката не е симетрична. Обявено „не
   * подлежи“, когато корекция се дължи, е СКРИТ ДАНЪЧЕН ПАСИВ — не се вижда никъде, докато не дойде
   * ревизия. Обратното — начислена корекция, която не се дължи — стои на видно място в дневника за
   * продажби и се сваля с една поправка. Предупреждение, което може да се подмине, пази само втория
   * случай.
   *
   * <p><b>Практическото следствие.</b> Актив с обичайно износване и балансова стойност 25% от
   * отчетната НЕ може да бъде освободен, дори отметката за доказано унищожаване да е вдигната:
   * буква „в“ иска преценка за обективна неизползваемост, която не се приема на доверие от този
   * слой. За такъв случай начисляването остава и се коригира само след ревизия или изрично
   * становище — в бележката, не с отметка.
   *
   * <p>И защо в repository, а не в изгледа: регистърът се пълни от отписването, редактира се от
   * формата и ще се чете от Блок Б за самата корекция. Изгледът предупреждава, но правилото трябва
   * да важи и по REST, и по импорт.
   */
  protected void refuseUnprovenVatRelease(BgFixedAssetWriteOff entity) {
    if (!BgAssetRemoval.VatTreatment.NOT_DUE.equals(entity.getVatTreatmentSelect())) {
      return;
    }
    boolean objective =
        BgAssetWriteOffRules.isObjectiveVatReleaseConditionMet(
            entity.getVatGroundSelect(),
            entity.getAccountingCarryingValue(),
            entity.getTaxAmortizableValue());
    boolean documented =
        entity.getDocumentNumber() != null && !entity.getDocumentNumber().trim().isEmpty();

    if (!BgAssetWriteOffRules.mayReleaseFromVatCorrection(
        objective, Boolean.TRUE.equals(entity.getIsDestructionProven()), documented)) {
      throw new PersistenceException(
          "Не може да се обяви „не подлежи на корекция по чл. 79 ЗДДС“ без доказано основание."
              + " Освобождаванията по чл. 80 ал. 2 важат само при ДОКАЗАНО ИЛИ ПОТВЪРДЕНО"
              + " унищожаване, и системата проверява сама единствено двете обективни условия:"
              + " непреодолима сила (чл. 80 ал. 2 т. 1 б. „а“) или балансова стойност под 10 на"
              + " сто от отчетната (т. 3 б. „г“)."
              + (objective
                  ? " Обективното условие е изпълнено — остава да отметнете „Доказано/потвърдено"
                      + " унищожаване“ и да посочите документа."
                  : " Обективното условие НЕ е изпълнено за този актив, тъй че освобождаване не"
                      + " може да се обяви оттук.")
              + " Начисляването остава — излишна корекция се вижда в дневника и се сваля, докато"
              + " пропуснатата е скрит данъчен пасив.");
    }
  }
}
