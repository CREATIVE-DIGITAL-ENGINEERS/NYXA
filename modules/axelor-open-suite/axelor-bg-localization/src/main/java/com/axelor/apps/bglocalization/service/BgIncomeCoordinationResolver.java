package com.axelor.apps.bglocalization.service;

import java.math.BigDecimal;
import java.math.RoundingMode;

/**
 * КООРДИНАЦИЯ НА ОСИГУРИТЕЛНИЯ ДОХОД МЕЖДУ ПРАВООТНОШЕНИЯ — чистата аритметика, БЕЗ база и без
 * Guice.
 *
 * <p>Същото разделение като {@code BgCompensationResolver} / {@code BgCompensationService}:
 * правилото е тук и се тества без Postgres, а {@link BgInsurableIncomeService} само му подава
 * прочетените редове.
 *
 * <p><b>═══ НОРМАТА, ДОСЛОВНО ═══</b>
 *
 * <p><b>КСО чл. 6 ал. 11</b> (изпуснати са само скобите с историята на изменението): „(11) За
 * лицата, които получават доходи от дейности на различни основания по чл. 4, осигурителните вноски
 * се внасят върху сбора от осигурителните им доходи, но върху не повече от максималния месечен
 * размер на осигурителния доход, по следния ред: 1. доходи от дейности на лицата съгласно
 * последователността, посочена в чл. 4, ал. 1 и 10; 2. доходи от обезщетения, изплащани по Кодекса
 * на труда или по специални закони, върху които се дължат осигурителни вноски; 3. осигурителен
 * доход като еднолични търговци, собственици или съдружници в търговски или в неперсонифицирани
 * дружества, лица, които се облагат по реда на чл. 26, ал. 7 от Закона за данъците върху доходите
 * на физическите лица, упражняващи свободна професия и/или занаятчийска дейност, регистрирани
 * земеделски стопани и тютюнопроизводители; 4. доходи за работа без трудово правоотношение.“
 *
 * <p><b>ПРОВЕНАНС.</b> Сверено ДОСЛОВНО, дума по дума, срещу текста на КСО в редакцията му към
 * 08.2026 г. (същият текст и в редакцията към началото на 2026 г.). Ал. 11 е предишната ал. 10 —
 * ДВ, бр. 61 от 2015 г., в сила от 01.01.2016 г.; последната редакция на т. 1, 2 и 3 е ДВ, бр. 98
 * от 2016 г., в сила от 01.01.2017 г.
 *
 * <p><b>⚠️ И СВЕРКАТА НАМЕРИ НЕЩО, КОЕТО ПЪРВИЯТ ПРОЧИТ ИЗПУСНА: т. 1 САМАТА НОСИ РЕД.</b> „доходи
 * от дейности на лицата СЪГЛАСНО ПОСЛЕДОВАТЕЛНОСТТА, посочена в чл. 4, ал. 1 и 10“ — тоест вътре в
 * най-високото ниво има ВТОРА подредба, дадена от самата последователност на чл. 4 ал. 1 и ал. 10.
 * Заданието на клона я цитираше свито като „доходи от дейности (чл. 4 ал. 1 и 10)“ и подредбата
 * вътре изчезваше.
 *
 * <p><b>Какво следва оттук за ТОЗИ клон — нищо не се мени, но границата вече е ЗНАЙНА.</b> Двата
 * трудови договора при различни работодатели са и двата по чл. 4 ал. 1 т. 1, тоест на ЕДНО И СЪЩО
 * място в последователността — там ред между тях няма и „равен приоритет“ е верният прочит. Ако
 * някога се координират две РАЗЛИЧНИ основания вътре в т. 1 (например чл. 4 ал. 1 т. 1 срещу ал. 1
 * т. 7 — управител), редът вътре в т. 1 ще трябва да се моделира, а един скалар пак няма да го
 * изрази. Затова {@link Status#DECLARED_LOWER_PRIORITY} остава, а {@code
 * BgInsurableIncomeService#ownLevel} казва изрично, че нивото днес е константа.
 *
 * <p><b>═══ КАКВО ТОЗИ КЛАС МОДЕЛИРА, И КАКВО НЕ ═══</b>
 *
 * <p>Моделира се ЕДИН подслучай: <b>втори работодател, деклариран като ЕДНО ЧИСЛО</b> от РАВЕН или
 * по-висок приоритет. Тогава редът по ал. 11 не се налага да се разиграва — чуждият доход се
 * изчерпва ПРЕДИ или ЕДНОВРЕМЕННО с този, тоест на това правоотношение остава остатъкът до тавана:
 *
 * <pre>координирана_база = clamp( min(собствен_осиг_доход, MAX − деклариран), 0, MAX )</pre>
 *
 * <p><b>⚠️ „СОБСТВЕН“ ЗНАЧИ СУРОВ.</b> Осигурителният доход на ТОВА правоотношение за периода, БЕЗ
 * МОД под и БЕЗ единичен таван. Таванът влиза само през {@code MAX − деклариран} — приложен и
 * поотделно, той би режел два пъти и второто рязане би било невидимо.
 *
 * <p><b>⚠️ ПОД 0 НЯМА.</b> При изчерпан таван ({@code MAX − деклариран ≤ 0}) базата е 0,00, не
 * отрицателно число: отрицателна база би дала отрицателни вноски, тоест перо, което ДОБАВЯ пари към
 * нетото. Решение на Николай — и точно неговият случай (1252,00 срещу деклариран цял таван) е
 * златното число за нулата.
 *
 * <p><b>НЕ се моделират тук</b>, и всяко от трите е ОТКАЗ С НАЗОВАНА ПРИЧИНА, не тихо смятане:
 *
 * <ul>
 *   <li><b>морско лице с още източници</b> — чл. 4а ал. 6 подрежда осигурителния доход на морското
 *       лице на СВОЕ ниво, тоест сборът може да се реже на различни нива и един скалар не казва
 *       кое. ⚠️ Сверено срещу текста на КСО (редакция към 08.2026 г.): ал. 6 има ПЕТ точки, не
 *       четири, и „осигурителния доход като морски лица“ е т. 3 — тоест морското лице се ВМЪКВА
 *       между обезщетенията и самоосигуряващите се и ИЗМЕСТВА всичко под себе си с едно ниво.
 *       Затова номерата от ал. 11 просто не важат за него. Виж {@link
 *       Status#SEAFARER_MULTI_SOURCE};
 *   <li><b>деклариран доход от ПО-НИСЪК приоритет</b> — формулата реже ТОВА правоотношение, което е
 *       вярно само когато чуждото се изчерпва преди него. При по-нисък приоритет режещият и
 *       рязаният си разменят местата, а един скалар не изразява ред между различни нива. Виж {@link
 *       Status#DECLARED_LOWER_PRIORITY};
 *   <li><b>липсващ MAX за периода</b> — без таван цялата формула няма горна граница. Виж {@link
 *       Status#MISSING_CAP}.
 * </ul>
 *
 * <p><b>⚠️ И ЕДНО ЧЕТВЪРТО, КОЕТО НЕ Е ОТКАЗ, А ОТСЪСТВИЕ:</b> {@link Status#NOT_DECLARED}. Няма
 * декларация значи „нормалният единичен път“ — МОД под и единичен таван, — а не „координация с
 * нула“. Двете дават РАЗЛИЧНА база при доход под МОД и точно затова са различни състояния.
 */
public final class BgIncomeCoordinationResolver {

  private BgIncomeCoordinationResolver() {}

  // ═══ РЕДЪТ НА ИЗЧЕРПВАНЕ ПО ЧЛ. 6 АЛ. 11 ══════════════════════════════════

  /**
   * ⚠️ ПО-МАЛКО ЧИСЛО = ПО-ВИСОК ПРИОРИТЕТ, точно както са изброени точките на алинеята. Тоест
   * сравнението „по-нисък приоритет“ се пише {@code declaredLevel > ownLevel} и се чете обратно на
   * интуицията — затова е константа с име, а не гол int на място на извикването.
   */
  /** Т. 1 — доходи от дейности по чл. 4 ал. 1 и 10. Тук стои и вторият работодател. */
  public static final int LEVEL_ACTIVITY = 1;

  /** Т. 2 — обезщетения по КТ или по специални закони. */
  public static final int LEVEL_COMPENSATION = 2;

  /** Т. 3 — ЕТ, собственици и съдружници, свободни професии, земеделски стопани. */
  public static final int LEVEL_SELF_INSURED = 3;

  /** Т. 4 — доходи за работа без трудово правоотношение. */
  public static final int LEVEL_NO_EMPLOYMENT = 4;

  // ═══ ДЕКЛАРАЦИЯТА ═════════════════════════════════════════════════════════

  /**
   * Чуждият осигурителен доход, както е ДЕКЛАРИРАН: сума и ниво по ал. 11.
   *
   * <p><b>Защо носач, а не гол {@code BigDecimal}.</b> Сумата без нивото си не може да каже дали
   * формулата важи за нея — а точно това е разликата между сметка и {@link
   * Status#DECLARED_LOWER_PRIORITY}. Единицата е ЕВРО, месечен размер за периода на фиша.
   */
  public static final class Declaration {

    /** Сумата, или {@code null} при отсъствие. */
    public final BigDecimal amount;

    /** Нивото по ал. 11, на което стои декларираното. */
    public final int level;

    private Declaration(BigDecimal amount, int level) {
      this.amount = amount;
      this.level = level;
    }

    /** Няма декларация — нормалният единичен път. */
    public static Declaration absent() {
      return new Declaration(null, LEVEL_ACTIVITY);
    }

    /** Декларация на изрично посочено ниво по ал. 11. */
    public static Declaration of(BigDecimal amount, int level) {
      return new Declaration(amount, level);
    }

    /**
     * Декларация от ВТОРИ РАБОТОДАТЕЛ — т. 1 на ал. 11.
     *
     * <p>Наименуваният вход е единственият, който производството ползва днес: месечното поле на
     * фиша носи сума без произход, а подслучаят на този клон е точно вторият работодател. Виж
     * {@link BgInsurableIncomeService#coordinationOf}.
     */
    public static Declaration ofSecondEmployer(BigDecimal amount) {
      return new Declaration(amount, LEVEL_ACTIVITY);
    }

    /**
     * ⚠️ АКТИВНА САМО ПРИ СТРОГО ПОЛОЖИТЕЛНА СУМА, и това е решение, не удобство. Декларирана нула
     * значи „другият платец не е осигурил нищо“ — тоест сборът е само този доход и нормалният
     * единичен път (МОД под, единичен таван) е ВЕРНИЯТ отговор. Прочетена като активна координация,
     * нулата би махнала МОД пода без причина и би смъкнала базата тихо.
     *
     * <p>⚠️ И {@code null}, и нулата дават еднакво „не“ — нарочно. Носителят е поле на ЗАПИС
     * ({@code BgPaySlip.bgOtherPayerInsurableIncome}), а генерираният getter за decimal връща ZERO
     * за непопълнена колона, тоест „не съм пипал полето“ и „въведох 0,00“ са неразличими по модела.
     * Щом са неразличими, двете трябва да значат ЕДНО И СЪЩО — инак изборът между тях щеше да
     * зависи от това дали редът е стар или нов.
     */
    public boolean isActive() {
      return amount != null && amount.signum() > 0;
    }
  }

  // ═══ РЕЗУЛТАТЪТ ═══════════════════════════════════════════════════════════

  public enum Status {
    /** Няма декларация — повикващият да мине по нормалния единичен път. */
    NOT_DECLARED,
    /** Има координирана база. */
    COORDINATED,
    /** Липсва MAX_INSURABLE_INCOME за периода — таван няма, формулата няма горна граница. */
    MISSING_CAP,
    /**
     * Декларираното стои на ПО-НИСКО ниво по ал. 11 от това правоотношение. Формулата реже ТОВА
     * правоотношение, а редът иска обратното — и един скалар не изразява ред между различни нива.
     */
    DECLARED_LOWER_PRIORITY,
    /**
     * Морско лице с още източници. Чл. 4а ал. 6 подрежда осигурителния доход на морското лице на
     * СВОЕ ниво; кое от нивата се реже, един скалар не казва. Морското лице е отделно парче.
     */
    SEAFARER_MULTI_SOURCE
  }

  /** Или координирана база, или назована причина да я няма. */
  public static final class Outcome {

    private final Status status;
    private final BigDecimal base;
    private final BigDecimal declared;
    private final String detail;

    private Outcome(Status status, BigDecimal base, BigDecimal declared, String detail) {
      this.status = status;
      this.base = base;
      this.declared = declared;
      this.detail = detail;
    }

    public Status getStatus() {
      return status;
    }

    /** Координираната база, или {@code null} при всяко друго състояние. */
    public BigDecimal getBase() {
      return base;
    }

    /** Декларираният чужд доход — за прозрачност на екрана и в отказа. */
    public BigDecimal getDeclared() {
      return declared;
    }

    public String getDetail() {
      return detail;
    }

    /** Има ли координирана база. */
    public boolean isCoordinated() {
      return status == Status.COORDINATED;
    }

    /** Няма декларация — нормалният единичен път остава в сила. */
    public boolean isNotDeclared() {
      return status == Status.NOT_DECLARED;
    }

    /** ⚠️ ОТСЪСТВИЕТО НЕ БЛОКИРА. Блокират само трите назовани причини. */
    public boolean isBlocking() {
      return status != Status.COORDINATED && status != Status.NOT_DECLARED;
    }
  }

  // ═══ ПРАВИЛОТО ════════════════════════════════════════════════════════════

  /**
   * Координираната база по чл. 6 ал. 11 за ЕДНО правоотношение срещу ЕДНА декларация.
   *
   * @param ownInsurableIncome осигурителният доход на ТОВА правоотношение за периода, СУРОВ — без
   *     МОД под и без единичен таван. {@code null} се чете като нула: липсата на начисления е
   *     законен месец, а не липса на отговор
   * @param ownLevel нивото по ал. 11 на ТОВА правоотношение — виж константите {@code LEVEL_*}
   * @param ownIsSeafarer морско лице ли е ТОВА правоотношение ({@code BgInsuredType.bgIsSeafarer});
   *     при активна декларация това е ОТКАЗ, не сметка
   * @param declared декларираният чужд доход; {@link Declaration#absent()} значи „нормален единичен
   *     път“
   * @param cap максималният месечен осигурителен доход за периода; {@code null} е ОТКАЗ
   */
  public static Outcome coordinate(
      BigDecimal ownInsurableIncome,
      int ownLevel,
      boolean ownIsSeafarer,
      Declaration declared,
      BigDecimal cap) {

    if (declared == null || !declared.isActive()) {
      return new Outcome(Status.NOT_DECLARED, null, null, null);
    }
    BigDecimal amount = declared.amount;

    // ⚠️ МОРСКОТО ЛИЦЕ СЕ ПИТА ПЪРВО, преди приоритета и преди тавана. Причината му е за ДРУГ
    // файл (чл. 4а ал. 6 и отделно парче работа), а другите две сочат данни или подател. Обърнат,
    // редът би пратил читателя да оправя приоритет на случай, който изобщо не се моделира.
    if (ownIsSeafarer) {
      return new Outcome(
          Status.SEAFARER_MULTI_SOURCE,
          null,
          amount,
          "морско лице с деклариран доход от друг платец ("
              + amount.toPlainString()
              + "): чл. 4а ал. 6 КСО подрежда осигурителния доход на морското лице на СВОЕ ниво,"
              + " тоест кое от нивата се реже не следва от едно число. Морското лице е отделна"
              + " задача и до нея координацията тук НЕ се прилага");
    }
    if (declared.level > ownLevel) {
      return new Outcome(
          Status.DECLARED_LOWER_PRIORITY,
          null,
          amount,
          "декларираният доход стои на ниво "
              + declared.level
              + " по КСО чл. 6 ал. 11, а това правоотношение — на ниво "
              + ownLevel
              + ". По-ниският приоритет се изчерпва СЛЕД това правоотношение, тоест реже се той, а"
              + " не тази база. Един скалар не изразява ред между различни нива");
    }
    if (cap == null) {
      return new Outcome(
          Status.MISSING_CAP,
          null,
          amount,
          "липсва параметър "
              + BgInsurableIncomeService.CODE_MAX_INSURABLE_INCOME
              + " за периода, а при деклариран чужд доход таванът Е самото правило —"
              + " без него остатъкът до него не може да се сметне");
    }

    // ⚠️ ЕДНО ЗАКРЪГЛЯНЕ, НАКРАЯ — спецификация § 5.3. Изваждането и min-ът вървят с пълна точност:
    // таванът е с четири знака в каталога (2111,6400), а базата е пари и се закръгля веднъж.
    BigDecimal headroom = cap.subtract(amount);
    BigDecimal own = ownInsurableIncome != null ? ownInsurableIncome : BigDecimal.ZERO;
    BigDecimal base = own.min(headroom);
    if (base.signum() < 0) {
      base = BigDecimal.ZERO;
    }
    // ⚠️ И горната граница пак: деклариран доход НАД тавана дава отрицателен остатък, който вече е
    // изяден от нулата отгоре, но собственият доход над тавана без декларация не минава оттук —
    // min-ът с остатъка го е ограничил. Проверката остава, за да е базата ограничена И отгоре на
    // едно място, а не да зависи от това кой от двата пътя е бил взет.
    if (base.compareTo(cap) > 0) {
      base = cap;
    }
    return new Outcome(Status.COORDINATED, base.setScale(2, RoundingMode.HALF_UP), amount, null);
  }
}
