package com.axelor.apps.bglocalization.service.etz;

/**
 * ОСНОВАНИЕТО НА ПРОМЯНАТА ПО ЧЛ. 123 — т. 3 на {@code etz123employer}, единайсетте стойности.
 *
 * <p>Изброени дословно по Приложение № 2 към Заповед {@value BgEtzXsd#ORDER_NUMBER}. Схемата ги
 * ограничава до 1–11; описанието им е в приложението и в Наредбата.
 *
 * <p><b>⚠️ ТОВА НЕ Е „КОД КОРЕКЦИЯ“.</b> Двете стоят едно до друго в записа и се бъркат по име:
 * {@code codecorrection} (т. 2) казва редовни/корекция/заличаване, а {@code correctiontype} (т. 3)
 * казва ЗАЩО се сменя работодателят. Разменени, файлът остава валиден по схема — и двете са малки
 * цели числа — и вписва грешно правно основание.
 *
 * <p><b>⚠️ И НЯМА ПОДРАЗБИРАЩА СЕ СТОЙНОСТ.</b> Съблазнително е „1 — сливане“ да е начална, защото
 * е първа. Основанието обаче е правен факт за конкретното прехвърляне и се избира от човек.
 */
public enum BgEtzCorrectionType {

  /** 1 — при сливане на предприятия. */
  MERGER(1, "сливане на предприятия"),
  /** 2 — при вливане на едно предприятие в друго. */
  ABSORPTION(2, "вливане на едно предприятие в друго"),
  /** 3 — при разпределяне на дейността между две или повече предприятия. */
  DIVISION(3, "разпределяне на дейността между две или повече предприятия"),
  /** 4 — при преминаване на обособена част от едно предприятие към друго. */
  PART_TRANSFER(4, "преминаване на обособена част към друго предприятие"),
  /** 5 — при смяна на собственика на предприятието или на обособена част. */
  OWNER_CHANGE(5, "смяна на собственика на предприятието или на обособена част"),
  /** 6 — наем/аренда или концесия — при сключване ИЛИ при прекратяване на договора. */
  LEASE_OR_CONCESSION(6, "отдаване под наем/аренда или възлагане на концесия"),
  /** 7 — при промяна на правноорганизационната форма. */
  LEGAL_FORM_CHANGE(7, "промяна на правноорганизационната форма"),
  /** 8 — при смяна на ЕИК БЕЗ да се сменя работодателят. */
  EIK_CHANGE(8, "промяна на ЕИК/служебен номер, без да се променя работодателят"),
  /** 9 — при преотстъпване или прехвърляне на дейност, вкл. на материални активи. */
  ACTIVITY_TRANSFER(9, "преотстъпване или прехвърляне на дейност, вкл. материални активи"),
  /** 10 — при преобразуване или преминаване на дейност между администрации. */
  ADMIN_REORGANISATION(10, "преобразуване/преминаване на дейност между администрации"),
  /** 11 — при ФАКТИЧЕСКА промяна на работодателя по чл. 10 ал. 5 т. 4 от Наредбата. */
  DE_FACTO_CHANGE(11, "фактическа промяна на работодателя по чл. 10 ал. 5 т. 4");

  private final int code;
  private final String title;

  BgEtzCorrectionType(int code, String title) {
    this.code = code;
    this.title = title;
  }

  /** Стойността, както влиза в т. 3. */
  public int getCode() {
    return code;
  }

  public String getTitle() {
    return title;
  }

  /** Стойността като низ за записа. */
  public String asValue() {
    return String.valueOf(code);
  }

  /** Разпознава кода; отказва при непознат, вместо да върне {@code null}. */
  public static BgEtzCorrectionType of(int code) {
    for (BgEtzCorrectionType type : values()) {
      if (type.code == code) {
        return type;
      }
    }
    throw new IllegalArgumentException(
        "основание на промяната „" + code + "“ е извън 1–11 по Приложение № 2");
  }
}
