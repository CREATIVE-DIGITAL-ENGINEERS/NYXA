package com.axelor.apps.bglocalization.service;

import java.math.BigDecimal;
import java.math.RoundingMode;

/**
 * ГРАЖДАНСКИЯТ ДОГОВОР — приспадането по КСО чл. 6 ал. 4 и прагът по чл. 4 ал. 3 т. 5 и 6.
 *
 * <p><b>Чиста функция, нула заявки</b> — по образеца на {@link BgIncomeCoordinationResolver} и
 * {@code BgSelfInsuredRules}: правилото се проверява без Postgres, без Guice и без Hibernate.
 * Параметрите ({@code MIN_WAGE}) идват ГОТОВИ отвън, защото са темпорални и се четат веднъж, на
 * датата на периода.
 *
 * <p><b>ДВЕ СТЪПКИ, КОИТО КОД 10 НЯМА, И ТЕ СА РАЗЛИЧНИ ВЪПРОСИ.</b>
 *
 * <ol>
 *   <li><b>Приспадането.</b> КСО чл. 6 ал. 4, дословно: „Възнаграждението за лицата по чл. 4, ал.
 *       3, т. 5 и 6, върху което се дължат осигурителни вноски, се определя след намаляването му с
 *       разходите за дейността, определени по реда на Закона за данъците върху доходите на
 *       физическите лица.“ Тоест базата е възнаграждението МИНУС нормативните разходи по чл. 29 ал.
 *       1 ЗДДФЛ — 25 на сто за услуги и извънтрудови правоотношения (т. 3), 40 на сто за авторски,
 *       занаят, адвокат и нотариус (т. 2), 60 на сто за непреработена земеделска продукция (т. 1).
 *       НАП Приложение № 1 (ВК-30-10237/12.08.2026) разд. 11 отпечатва базата със същите думи:
 *       „Възнаграждението след намаляване на разходите за дейността, но върху не повече от 2111,64
 *       евро до 31.07.2026 г., съответно 2300 евро от 01.08.2026 г.“
 *   <li><b>Прагът.</b> Чл. 4 ал. 3 т. 5 осигурява лицето само ако възнаграждението СЛЕД намалението
 *       е „равно или над една минимална работна заплата“ и лицето „не е осигурено на друго
 *       основание през съответния месец“. Т. 6 осигурява лицето, осигурено на друго основание,
 *       „НЕЗАВИСИМО ОТ РАЗМЕРА на полученото възнаграждение“.
 * </ol>
 *
 * <p><b>⚠️ ПРАГЪТ Е ВРАТА, А НЕ ПОД — И ЦЯЛАТА РАЗЛИКА Е ТУК.</b> Под МРЗ по т. 5 вноски НЕ СЕ
 * ДЪЛЖАТ изобщо; над МРЗ се дължат върху ДЕЙСТВИТЕЛНАТА намалена сума, а не върху МРЗ. Затова
 * {@code bgFloorType} на код 14 стои на {@code NONE} и трябва да остане там: прочетен като под,
 * прагът би вдигнал база 450,00 до 620,20 — правдоподобно число, за което няма основание в нито
 * една от двете точки. И обратното: изр. 1 на чл. 6 ал. 3, което дължи вноски „върху не по-малко от
 * минималния осигурителен доход“, изброява САМО работниците и служителите и лицата по чл. 4 ал. 1
 * т. 7 и 8 — ал. 3 т. 5 и 6 ги няма в него, тоест МОД по НКПД тук не важи ({@code bgAppliesMod =
 * false}).
 *
 * <p><b>⚠️ ТАВАНЪТ НЕ Е ТУК.</b> Максималният месечен осигурителен доход се налага от {@link
 * BgInsurableIncomeService} върху вече намалената база, по същия път, по който минава и заплатата.
 * Втора негова сметка тук би била второ копие на число, което се сменя два пъти в една година
 * (ЗБДОО чл. 9 т. 1 и т. 2).
 *
 * <p><b>⚠️ КАКВО ОСТАВА ИЗВЪН ОСИГУРЯВАНЕТО, ЗА ДА НЕ СЕ СМЕТНЕ ЗА УРЕДЕНО.</b> Под прага по т. 5
 * отпада ОСИГУРЯВАНЕТО, не данъкът: авансовият данък по чл. 43 ЗДДФЛ се дължи и при 450,00 лева
 * основа. Той обаче не минава оттук — извънтрудовите доходи влизат в регистъра {@code
 * BgIndividualIncomePayment} и в справката по чл. 73 ал. 1, а не в Д1. Виж {@code
 * BgIncomeTaxResolver#business}, който смята същото приспадане по същата ставка за данъчната
 * страна.
 *
 * <p><b>⚠️ И ЗДРАВНОТО ПОД ПРАГА НЕ ИЗЧЕЗВА — ТО ИЗЛИЗА ОТ ТОЗИ ПОТОК.</b> ЗЗО чл. 40 ал. 1 т. 3 б.
 * „а“, дословно: „когато е получено възнаграждение под минималната работна заплата за страната,
 * след намаляването му с разходите за дейността, осигуряването се извършва по реда на ал. 5“ —
 * тоест лицето внася само̀ по образец 7, а възложителят не удържа нищо. Същият изход като при СОЛ
 * (виж {@code BgSelfInsuredRules}); тук се проявява като липса на вноски, не като вноска за сметка
 * на лицето.
 */
public final class BgCivilContractResolver {

  /**
   * Вид осигурен 14 — „Работещи без трудови правоотношения“, тоест лицата по КСО чл. 4 ал. 3 т. 5 и
   * 6.
   *
   * <p>⚠️ ЕДИН КОД, А НЕ ФЛАГ В РЕЧНИКА, и това е обмислено. Двете правила тук висят на ЕДНА точка
   * от Приложение № 1 и на ЕДНА алинея на чл. 6; флаг „прилага ли се чл. 6 ал. 4“ би бил колона с
   * една истинна стойност — име на едно и също нещо, казано два пъти. Появи ли се втори код с
   * приспадане (днес няма такъв в номенклатурата), колоната си заслужава; дотогава кодът е
   * по-честният носител.
   *
   * <p>⚠️ И НЕ Е {@code EmploymentContract.bgContractType = "gd"}. Онова поле ОПИСВА договора и е
   * свободно да е празно; режимът се клони по вида осигурен — същото разделение, по което ДУК
   * тръгва от код 10, а не от стойността „duk“.
   */
  public static final String INSURED_TYPE_CODE = "14";

  /** Всяко число в пари се закръгля до евроцент, половина нагоре — спецификация § 5.3. */
  private static final int SCALE = 2;

  private static final BigDecimal HUNDRED = new BigDecimal("100");

  private BgCivilContractResolver() {}

  /** Този вид осигурен ли е гражданският договор. Празно и непознато се четат като „не“. */
  public static boolean isCivilContract(String insuredTypeCode) {
    return insuredTypeCode != null && INSURED_TYPE_CODE.equals(insuredTypeCode.trim());
  }

  /** Изходът на правилото — вж. {@link Outcome}. */
  public enum Status {

    /** Вноски се дължат върху {@link Outcome#getBase()} — по т. 5 над прага или по т. 6. */
    INSURED,

    /**
     * Чл. 4 ал. 3 т. 5, отрицателната ѝ половина: под една МРЗ и без друго основание — осигуряване
     * НЕ ВЪЗНИКВА. Базата е нула и това е ЗАКОННА нула, не липса на данни.
     */
    BELOW_THRESHOLD,

    /**
     * Договорът не казва по кой ред на чл. 29 ал. 1 се признават разходите — ОТКАЗ.
     *
     * <p>⚠️ ОТКАЗ, А НЕ „БЕЗ ПРИСПАДАНЕ“, и посоката е причината. Сметната без намаление, базата
     * излиза ПО-ГОЛЯМА (2000,00 вместо 1500,00) и вноските — завишени с една трета, при чист зелен
     * резултат на екрана. Отказът с назована причина е единственият от двата изхода, който се
     * вижда.
     */
    MISSING_EXPENSE_RATE,

    /**
     * Минималната работна заплата за периода липсва в речника на параметрите — ОТКАЗ.
     *
     * <p>⚠️ Пита се САМО когато отговорът зависи от нея, тоест когато лицето НЕ е осигурено на
     * друго основание. По т. 6 прагът не участва в нито едно число и отказ по негов повод би спрял
     * верен фиш заради стойност, която не се ползва.
     */
    MISSING_MIN_WAGE
  }

  /** Базата, приспаднатите разходи и защо. */
  public static final class Outcome {

    private final BigDecimal base;
    private final BigDecimal expense;
    private final Status status;
    private final String detail;

    private Outcome(BigDecimal base, BigDecimal expense, Status status, String detail) {
      this.base = base;
      this.expense = expense;
      this.status = status;
      this.detail = detail;
    }

    /**
     * Осигурителната база ПРЕДИ тавана — възнаграждението минус разходите, или нула под прага.
     * {@code null} при отказ: число там би било сметнато по правило, което не е приложено.
     */
    public BigDecimal getBase() {
      return base;
    }

    /** Приспаднатите нормативни разходи — същото число, което данъчната страна пише в колона 13. */
    public BigDecimal getExpense() {
      return expense;
    }

    public Status getStatus() {
      return status;
    }

    /** Причината за отказ, или {@code null}. */
    public String getDetail() {
      return detail;
    }

    public boolean isResolved() {
      return status == Status.INSURED || status == Status.BELOW_THRESHOLD;
    }
  }

  /**
   * Базата на гражданския договор за един месец.
   *
   * @param gross договореното възнаграждение — БРУТО, преди разходите
   * @param expenseRate нормативните разходи в ПРОЦЕНТИ по чл. 29 ал. 1 ЗДДФЛ ({@code
   *     BgIncomeType.expenseRate}); {@code null} е ОТКАЗ
   * @param insuredOnOtherGround осигурено ли е лицето на друго основание през месеца — т. 6 срещу
   *     т. 5
   * @param minWage минималната работна заплата за периода ({@code MIN_WAGE}); ползва се САМО когато
   *     {@code insuredOnOtherGround} е {@code false}
   */
  /**
   * НОРМАТИВНИТЕ РАЗХОДИ ПО ЧЛ. 29 АЛ. 1 ЗДДФЛ — <b>ЕДНАТА ФОРМУЛА ЗА ДВЕТЕ СТРАНИ НА ФИША</b>.
   *
   * <p><b>⚠️ ИЗВАДЕНО КАТО ИМЕ, А НЕ ПРЕПИСАНО ВТОРИ ПЪТ</b> — по същия довод, по който {@code
   * BgPaySlipResolver#employeeContributions} е извадено от данъчната основа. Едно и също приспадане
   * се иска на две места по две норми: КСО чл. 6 ал. 4 реже ОСИГУРИТЕЛНАТА база (виж {@link
   * #resolve}), а ЗДДФЛ чл. 43 ал. 1 през чл. 29 реже ДАНЪЧНАТА (виж {@code
   * BgPaySlipService#businessExpense}). Двата текста сочат ЕДНА ставка и {@link #resolve} го казва
   * дословно: „{@code getExpense()} е същото число, което данъчната страна пише в колона 13“.
   * Преписана отделно, втората сметка е свободна да се размине с първата по ЗАКРЪГЛЯНЕ — а разлика
   * от една стотинка между двете основи на един фиш е точно онова правдоподобно число, което никой
   * контрол не хваща.
   *
   * <p><b>⚠️ ДОХОДЪТ СЕ ПОДАВА, ЗАЩОТО ДВЕТЕ НОРМИ МЕРЯТ ОТ РАЗЛИЧНО ЧИСЛО.</b> Ал. 4 казва
   * „възнаграждението“, чл. 29 казва „придобитият доход“. На нормалния граждански фиш двете
   * съвпадат, но осигурителната страна тръгва от осигурителното бруто, а данъчната — от ОБЛАГАЕМИТЕ
   * начисления ({@code BgPaySlipResolver#accruedTaxableTotal}). Закована тук, едната от двете щеше
   * да е приспадане, сметнато от чуждото си число.
   *
   * <p><b>⚠️ {@code null} СТАВКА ДАВА {@code null} РАЗХОД, А НЕ НУЛА.</b> Нула би значела „разходи
   * не се признават“ — верен отговор за някои шаблони на чл. 29 — и приспадането щеше да изчезне
   * мълчаливо: данък 200,00 вместо 150,00 при чист зелен екран. Липсата е ОТКАЗ и се назовава от
   * този, който я е поискал: {@link Status#MISSING_EXPENSE_RATE} за осигуровките, {@code
   * BgIncomeTaxService#applyBusiness} за данъка.
   *
   * @param income доходът, от който се приспада — БРУТО, преди разходите
   * @param expenseRate нормативните разходи в ПРОЦЕНТИ по чл. 29 ал. 1 ЗДДФЛ ({@code
   *     BgIncomeType.expenseRate}); {@code null} е ОТКАЗ
   */
  public static BigDecimal expenseOf(BigDecimal income, BigDecimal expenseRate) {
    if (expenseRate == null) {
      return null;
    }
    return percentOf(income == null ? zero() : scaled(income), expenseRate);
  }

  public static Outcome resolve(
      BigDecimal gross, BigDecimal expenseRate, boolean insuredOnOtherGround, BigDecimal minWage) {

    if (expenseRate == null) {
      return new Outcome(
          null,
          null,
          Status.MISSING_EXPENSE_RATE,
          "договорът няма вид доход по ЗДДФЛ, тоест не се знае по коя точка на чл. 29 ал. 1 се"
              + " признават разходите за дейността. КСО чл. 6 ал. 4 дължи вноските върху"
              + " възнаграждението СЛЕД намаляването му с тях — без ставката базата излиза"
              + " завишена, а не непълна");
    }

    BigDecimal amount = gross == null ? zero() : scaled(gross);
    // ⚠️ ПРЕЗ ОБЩАТА ВРАТА, не наум: същото приспадане чете и данъчната страна по чл. 43 ал. 1.
    BigDecimal expense = expenseOf(amount, expenseRate);
    BigDecimal reduced = max0(amount.subtract(expense));

    // ⚠️ Т. 6 се проверява ПЪРВА и прагът дори не се чете. Лицето, осигурено на друго основание, се
    // осигурява „независимо от размера“ — тоест МРЗ не участва в нито едно от числата му.
    if (insuredOnOtherGround) {
      return new Outcome(reduced, expense, Status.INSURED, null);
    }

    if (minWage == null) {
      return new Outcome(
          null,
          expense,
          Status.MISSING_MIN_WAGE,
          "липсва параметър "
              + BgInsurableIncomeService.CODE_MIN_WAGE
              + " за периода. По КСО чл. 4 ал. 3 т. 5 той решава ДАЛИ изобщо възниква осигуряване"
              + " — без него не може да се каже нито че се дължи, нито че не се дължи");
    }

    // „равно или над една минимална работна заплата“ — равното е ВЪТРЕ, затова >= 0.
    if (reduced.compareTo(scaled(minWage)) >= 0) {
      return new Outcome(reduced, expense, Status.INSURED, null);
    }

    return new Outcome(zero(), expense, Status.BELOW_THRESHOLD, null);
  }

  private static BigDecimal percentOf(BigDecimal amount, BigDecimal rate) {
    return amount.multiply(rate).divide(HUNDRED, SCALE, RoundingMode.HALF_UP);
  }

  private static BigDecimal max0(BigDecimal v) {
    return v.signum() < 0 ? zero() : v;
  }

  private static BigDecimal scaled(BigDecimal v) {
    return v.setScale(SCALE, RoundingMode.HALF_UP);
  }

  private static BigDecimal zero() {
    return BigDecimal.ZERO.setScale(SCALE);
  }
}
