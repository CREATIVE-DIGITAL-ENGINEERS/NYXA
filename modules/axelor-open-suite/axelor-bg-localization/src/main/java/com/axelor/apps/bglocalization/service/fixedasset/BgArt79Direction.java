package com.axelor.apps.bglocalization.service.fixedasset;

/**
 * Посоката на корекцията по чл. 79 ЗДДС — стойностите на {@code bg.vat.art79.direction.select}.
 *
 * <p>„Корекция“ е думата на ЗАКОНА и за двете посоки: ППЗДДС чл. 66 ал. 4 гласи „Корекциите по чл.
 * 79, <b>ал. 5 и 6</b> от закона се извършват чрез издаване на протокол…“. Затова полетата върху
 * отписването са едни и същи, а посоката е маркер.
 *
 * <p>Двете никога не съвпадат за едно извеждане: или активът НАПУСКА облагаемата дейност (ал. 3 —
 * дължим данък, дневник за продажбите), или излиза с ОБЛАГАЕМА ДОСТАВКА (ал. 5 — приспадане,
 * дневник за покупките). Едно поле със знак би направило посоката въпрос на тълкуване на знака, а
 * дневникът, в който влиза сумата, не е нещо, което се тълкува.
 */
public final class BgArt79Direction {

  /** Дължим данък по чл. 79 ал. 3 — дневник за продажбите, к.12. */
  public static final String CORRECTION = "CORRECTION";

  /** Приспадане на неползван кредит по чл. 79 ал. 5 — дневник за покупките, к.11. */
  public static final String DEDUCTION = "DEDUCTION";

  private BgArt79Direction() {}
}
