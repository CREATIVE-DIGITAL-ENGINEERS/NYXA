package com.axelor.apps.bglocalization.service.payroll.ledger;

import com.axelor.apps.bglocalization.db.BgPaySlip;
import com.axelor.apps.bglocalization.service.BgCivilContractResolver;
import com.axelor.apps.bglocalization.service.d1.BgD1Carrier;
import java.util.Arrays;
import java.util.LinkedHashSet;
import java.util.Set;

/**
 * ПО КОЯ ВЕДОМОСТ ВЪРВИ ЕДНО ЛИЦЕ — РАЗБИВАНЕ, а не филтър.
 *
 * <p>Микроинвест дава разчетно-платежната ведомост в пет разреза (трудови, граждански,
 * самоосигуряващи се, ДУК, аванси). Четири от тях са ВИД ПРАВООТНОШЕНИЕ и това е въпрос с точно
 * един отговор на фиш; петият (аванси) НЕ Е — виж {@link BgPayrollLedgerSelection}.
 *
 * <p><b>⚠️ РАЗБИВАНЕТО Е ПЪЛНО И НЕПРЕСИЧАЩО СЕ, И ТОЧНО ЗАТОВА ИМА ПЕТА СТОЙНОСТ.</b> Четирите
 * разреза на образеца не покриват всичко, което базата може да носи: фиш по договор БЕЗ попълнен
 * вид осигурен съществува днес, в тази база. Четете ли разбиването като „останалото е трудов
 * договор“, такъв фиш влиза при наетите мълчаливо — тоест ведомостта на трудовите договори събира
 * ред, за който никой не е казал, че е трудов. {@link #UNCLASSIFIED} е мястото му: той се ПЕЧАТА, с
 * празна графа за вида осигурен, и се брои в преброяването. Отчетът показва честно, а не подрежда.
 *
 * <p><b>⚠️ И РАЗРЕЗЪТ СЕ КЛОНИ ПО ВИДА ОСИГУРЕН, А НЕ ПО {@code bgContractType}.</b> Полето „Вид
 * договор“ е ОПИСАТЕЛНО и свободно да е празно — собственият му домейн го казва дословно: „нула
 * реда производствен код го четат“. Клонено по него, ведомостта щеше да разпределя хората по
 * стойност, която никой пазач не пълни, докато фишът, декларацията и вноските им се смятат по
 * ДРУГА. {@link BgCivilContractResolver#INSURED_TYPE_CODE} прави точно същия избор и го обяснява.
 *
 * <p><b>⚠️ САМООСИГУРЯВАЩИЯТ СЕ НЕ СЕ ПОЗНАВА ПО КОД, А ПО НОСИТЕЛ.</b> Фишът има две взаимно
 * изключващи се страни — трудов договор и регистрация — и регистрацията е СТРУКТУРА, не стойност в
 * колона. Списък от кодове (12, 13, 22, 41) щеше да върши работа, докато номенклатурата не се
 * смени; носителят не се мени с редакция на Наредба Н-13. Затова {@link BgD1Carrier#isSelfInsured}
 * пита пръв.
 */
public enum BgPayrollLedgerVariant {

  /**
   * Наетите — ведомостта по подразбиране.
   *
   * <p>⚠️ ОПРЕДЕЛЕН ПО ИЗКЛЮЧВАНЕ, И ТОВА Е ОБЯВЕНА ГРАНИЦА, а не пропуск. Модулът НЯМА ос „това
   * правоотношение трудово ли е“ — {@code BgInsuredType.bgEntitledToLengthOfServiceBonus} е
   * най-близкото, но собственият му коментар изрично отказва да бъде четен така (код 97 Е трудов и
   * флагът му е свален; кодове 05/06/17/24/83 не са трудови по КТ). Дотогава „трудов договор“ тук
   * значи: фишът виси на договор, носи вид осигурен и той НЕ е 10 или 14.
   */
  EMPLOYMENT("TD", "Трудови договори"),

  /** Гражданските договори — вид осигурен 14, КСО чл. 4 ал. 3 т. 5 и 6. */
  CIVIL("GD", "Граждански договори"),

  /**
   * Вид осигурен 10 — КСО чл. 4 ал. 1 т. 7.
   *
   * <p>⚠️ ЗАГЛАВИЕТО НЕ Е САМО „ДУК“, И ТОВА Е ТОЧНОСТ, А НЕ ПРЕДПАЗЛИВОСТ. Кодът е ПО-ШИРОК от
   * договора за управление и контрол: същия код носят членовете на СД, УС и НС, контрольорите,
   * синдиците и ликвидаторите — те са по същата точка и НЯМАТ ДУК. Ведомост, озаглавена „ДУК“, би
   * твърдяла за всеки от тях договор, какъвто не е сключван.
   */
  MANAGEMENT("DUK", "ДУК и приравнени (вид осигурен 10)"),

  /** Самоосигуряващите се — фишът виси на регистрация, не на договор. */
  SELF_INSURED("SOL", "Самоосигуряващи се"),

  /**
   * ⚠️ НЕ Е „ГРЕШКА“ И НЕ Е ПРАЗНА СТОЙНОСТ — това е шестият разрез, който образецът няма, защото
   * на хартия на Микроинвест такъв фиш не може да съществува. Тук може: видът осигурен е
   * незадължителен на договора. Редът се печата с празна графа, за да се ВИДИ.
   */
  UNCLASSIFIED("OTHER", "Без определен вид осигурен");

  /** Вид осигурен 10 — управители, прокуристи, членове на СД/УС/НС, контрольори, синдици. */
  public static final String MANAGEMENT_INSURED_TYPE_CODE = "10";

  private final String code;
  private final String label;

  BgPayrollLedgerVariant(String code, String label) {
    this.code = code;
    this.label = label;
  }

  /** Кодът, с който разрезът пътува през селекцията на екрана и през параметъра на отчета. */
  public String getCode() {
    return code;
  }

  /** Заглавието върху хартията. */
  public String getLabel() {
    return label;
  }

  /**
   * Разрезът на един фиш. Празен фиш дава {@link #UNCLASSIFIED} — той няма нито носител, нито код.
   *
   * <p>⚠️ РЕДЪТ НА ПРОВЕРКИТЕ Е СМИСЛОВ: носителят пръв (структура), кодът след него (данни).
   * Обратният ред би пратил самоосигуряващо се лице с попълнен код 14 при гражданските договори —
   * правдоподобен ред на грешната ведомост.
   */
  public static BgPayrollLedgerVariant of(BgPaySlip slip) {
    BgD1Carrier carrier = BgD1Carrier.of(slip);
    if (carrier.isSelfInsured()) {
      return SELF_INSURED;
    }
    String code = carrier.insuredTypeCode();
    if (code == null) {
      return UNCLASSIFIED;
    }
    if (BgCivilContractResolver.isCivilContract(code)) {
      return CIVIL;
    }
    if (MANAGEMENT_INSURED_TYPE_CODE.equals(code)) {
      return MANAGEMENT;
    }
    // ⚠️ Договор няма → няма трудово правоотношение, каквото и да казва кодът. Фиш без нито един от
    // двата носителя е отказ на BgSelfInsuredRules#refuseCarrier, но ведомостта чете и чернови.
    return carrier.getContract() == null ? UNCLASSIFIED : EMPLOYMENT;
  }

  /** Разрезът по кода му, или {@code null}, когато кодът не е ничий. */
  public static BgPayrollLedgerVariant byCode(String code) {
    for (BgPayrollLedgerVariant variant : values()) {
      if (variant.code.equals(code)) {
        return variant;
      }
    }
    return null;
  }

  /** Кодовете на всички разрези — редът е редът на изброяването. */
  public static Set<String> codes() {
    Set<String> out = new LinkedHashSet<>();
    Arrays.stream(values()).forEach(v -> out.add(v.code));
    return out;
  }
}
