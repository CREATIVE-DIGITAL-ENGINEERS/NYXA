    if (facts.withoutPayer > 0) {
      line(out, "   ⚠️ " + facts.withoutPayer + " реда за тази година БЕЗ посочен платец — те НЕ");
      line(out, "      са приписани на подателя. Отвори ги и посочи дружеството-платец; редове");
      line(out, "      отпреди появата на полето го нямат. Приписани мълчаливо, те биха подали");
      line(out, "      чужди доходи от твое име.");
    }
    if (facts.otherForm > 0) {
      line(out, "   • " + facts.otherForm + " реда с кодове на ДРУГ образец (101–111) — те са в");
      line(out, "      справката по чл. 73 ал. 6 и се събират право от фишовете. Не е пропуск.");
    }
