    line(out, "   редът за подаване се одобряват със СВОЯ заповед на изпълнителния директор на");
    line(out, "   НАП (указание т. 1) и този договор още не е в проекта; всяка друга услуга би");
    line(out, "   подала друга декларация. Подаването остава ръчно на портала на НАП.");
    line(out, "");

    line(out, "СРОК: 28 февруари на следващата година (указание т. 2). При открита грешка в");
    line(out, "данните за конкретно физическо лице СЛЕД този срок — промяна до 30 СЕПТЕМВРИ на");
