package com.axelor.apps.bglocalization.service.fixedasset;

import java.util.ArrayList;
import java.util.Arrays;
import java.util.List;

/**
 * Съответствието величина → ред на образец 1010 (ГДД по чл. 92 ЗКПО), Част V „Преобразуване на
 * счетоводния финансов резултат“.
 *
 * <p><b>Защо мапингът е отделен файл.</b> Величините идват от ЗКПО и са сверени дословно (чл. 54,
 * чл. 59 ал. 2, чл. 66, чл. 60 ал. 3); кой шифър ги носи е АДМИНИСТРАТИВЕН въпрос. Смятането е
 * готово преди образеца и не се пипа, когато образецът се смени — сменя се само този файл.
 *
 * <p>⚠️ И ЗКПО НИКЪДЕ НЕ КАЗВА КОЙ УТВЪРЖДАВА ОБРАЗЕЦА. Чл. 92 ал. 1 гласи само „подават годишна
 * данъчна декларация <b>по образец</b>“. Тоест шифрите нямат основание в закона и не бива да се
 * извеждат от него.
 *
 * <p><b>⚠️ СВЕРКАТА НЕ Е МОЯ.</b> Шифрите и заглавията по-долу идват от сверка на ВЪЗЛОЖИТЕЛЯ срещу
 * официалния образец, обнародван в <b>ДВ бр. 16 от 25.02.2025 г. (Заповед № ЗМФ-158 от 21.02.2025
 * г.)</b>, с бележката, че промяната в ДВ бр. 22 от 24.02.2026 г. не засяга тези редове. Опитах да
 * ги потвърдя независимо срещу ДВ и НАП на 11.09.2026 г. и НЕ успях: страницата на НАП връща 404,
 * списъкът на ДВ показва само последните броеве, lex.bg отказва достъп (403), а директното четене
 * по номер на материал в ДВ иска идентификатор, който не се извежда. Затова статусът тук казва ЧИЯ
 * е сверката, вместо да я представя за проверена от кода.
 *
 * <p><b>⚠️ Специалният пълен образец за данъчна 2026 г. в евро</b> се очаква края на 2026 /
 * началото на 2027 г. Шифрите да се пресверят тогава. Рискът е нисък — сумите вече се обработват в
 * евро ({@code BgCurrencyConversion}), а редовете по амортизациите са стабилни поне от 2025 г.
 */
public final class BgGddMapping {

  private BgGddMapping() {}

  /** Източникът на сверката — изведен веднъж, за да не се преписва по редовете. */
  public static final String SOURCE =
      "образец 1010, Част V; ДВ бр. 16 от 25.02.2025 г., Заповед № ЗМФ-158 от 21.02.2025 г.;"
          + " непроменени в ДВ бр. 22 от 24.02.2026 г.";

  /** Колона А — увеличения на счетоводния финансов резултат. */
  public static final String COLUMN_INCREASE = "А";

  /** Колона Б — намаления на счетоводния финансов резултат. */
  public static final String COLUMN_DECREASE = "Б";

  /**
   * Един ред на образеца: шифър, дословно заглавие, колона, основание и чия е сверката.
   *
   * <p>⚠️ Записът е per-ШИФЪР, а не един глобален флаг, и това е нарочно. Сверени са ЧЕТИРИ реда по
   * амортизациите; глобален „verified = true“ би твърдял, че е сверен ЦЕЛИЯТ образец — включително
   * редове, за които нямаме шифър. Преекспониране от този вид е точно това, което маркерът трябва
   * да предотврати.
   */
  public static final class Line {
    public final String code;
    public final String title;
    public final String column;
    public final String legalGround;
    public final boolean verified;
    public final String note;

    Line(
        String code,
        String title,
        String column,
        String legalGround,
        boolean verified,
        String note) {
      this.code = code;
      this.title = title;
      this.column = column;
      this.legalGround = legalGround;
      this.verified = verified;
      this.note = note;
    }

    /** Как редът се изписва в справката — шифър, колона и заглавие. */
    public String label() {
      if (code == null || code.isEmpty()) {
        return "(без самостоятелен шифър) " + title;
      }
      return String.format("шифър %s, колона %s — %s", code, column, title);
    }
  }

  /** Шифър 7010 — годишните СЧЕТОВОДНИ разходи за амортизации (чл. 54 ал. 2). */
  public static final Line ART54_ACCOUNTING =
      new Line(
          "7010",
          "Годишни счетоводни разходи за амортизации",
          COLUMN_INCREASE,
          "чл. 54 ал. 2 ЗКПО",
          true,
          "Брутна сума. Чл. 54 ал. 2: „счетоводният финансов резултат се увеличава със"
              + " счетоводните амортизации, независимо от това дали отчитането им води до"
              + " намаляване на счетоводния финансов резултат за годината“ — тоест увеличението е"
              + " БЕЗУСЛОВНО и не се нетира срещу данъчната амортизация. Нетирането е работа на"
              + " самата декларация, която сумира колона А и колона Б.");

  /** Шифър 8010 — годишните ДАНЪЧНИ амортизации (чл. 54 ал. 1). */
  public static final Line ART54_TAX =
      new Line(
          "8010",
          "Годишни данъчни амортизации",
          COLUMN_DECREASE,
          "чл. 54 ал. 1 ЗКПО",
          true,
          "Брутна сума. Чл. 54 ал. 1: „признават се годишните данъчни амортизации, определени по"
              + " реда на тази глава“. ⚠️ Тук се НЕТИРА обръщането по чл. 59 ал. 2 — вж."
              + " ART59_REVERSAL.");

  /** Шифър 7020 — СБС на отписаните от счетоводния план активи (чл. 66 ал. 1). */
  public static final Line ART66_INCREASE =
      new Line(
          "7020",
          "Счетоводна балансова стойност на отписаните активи от счетоводния амортизационен план",
          COLUMN_INCREASE,
          "чл. 66 ал. 1 ЗКПО",
          true,
          "В годината на СЧЕТОВОДНОТО отписване. ⚠️ Не се слива с 8020: по чл. 60 ал. 3 двете"
              + " събития често падат в РАЗЛИЧНИ години.");

  /** Шифър 8020 — данъчната стойност на отписаните от ДАП активи (чл. 66 ал. 2). */
  public static final Line ART66_DECREASE =
      new Line(
          "8020",
          "Данъчна стойност на отписаните активи от данъчния амортизационен план",
          COLUMN_DECREASE,
          "чл. 66 ал. 2 ЗКПО",
          true,
          "В годината, в която активът излиза от ДАНЪЧНИЯ план. При изключение по чл. 60 ал. 3"
              + " активът остава в плана и излиза по реда на ал. 1 — тоест ПО-КЪСНО от 7020."
              + " Затова справката чете два отделни потока и не ги слива в една година.");

  /**
   * Обръщането по чл. 59 ал. 2 — БЕЗ самостоятелен шифър.
   *
   * <p>⚠️ <b>ДА СЕ ПОТВЪРДИ — това е тълкуване, не сверен ред.</b> Ал. 2 казва, че „<b>годишната
   * данъчна амортизация</b> на данъчно задълженото лице <b>се намалява</b> с размера на начислената
   * данъчна амортизация за актива през дванадесетте месеца“. Тоест обръщането не е самостоятелно
   * намаление на финансовия резултат, а корекция ВЪТРЕ в годишната данъчна амортизация — числото,
   * което отива в шифър 8010. Отделен ред за него в образеца не е сверен и не се предполага.
   *
   * <p>⚠️ И посоката е обратна на интуицията: по-малко призната данъчна амортизация значи ПО-МАЛКО
   * намаление, тоест ПО-ВИСОК данъчен резултат. Затова сумата се ИЗВАЖДА от 8010, а не се прибавя
   * към намаленията.
   */
  public static final Line ART59_REVERSAL =
      new Line(
          "",
          "Обръщане по чл. 59 ал. 2 — нетира се в шифър 8010",
          COLUMN_DECREASE,
          "чл. 59 ал. 2 ЗКПО",
          false,
          "Няма сверен самостоятелен шифър. Сумата НАМАЛЯВА числото в 8010.");

  /** Всички редове, които справката може да произведе. */
  public static List<Line> all() {
    return Arrays.asList(
        ART54_ACCOUNTING, ART54_TAX, ART66_INCREASE, ART66_DECREASE, ART59_REVERSAL);
  }

  /**
   * Сверен ли е ЦЕЛИЯТ мапинг — ИЗЧИСЛЕНО, а не обявено.
   *
   * <p>Заменя предишния глобален {@code IS_VERIFIED = false}. Разликата е, че този отговор не може
   * да се разсинхронизира с редовете: щом остане несверен ред, изразът сам казва „не“.
   */
  public static boolean isFullyVerified() {
    for (Line line : all()) {
      if (!line.verified) {
        return false;
      }
    }
    return true;
  }

  /**
   * Печатният маркер — изброява ТОЧНО несверените редове, или е празен.
   *
   * <p>⚠️ Празният низ значи „няма какво да се потвърждава“, и това е целта: предупреждение, което
   * стои и след като нещата са сверени, спира да се чете. Затова текстът назовава конкретните
   * редове, вместо да твърди нещо общо за образеца.
   */
  public static String unverifiedNote() {
    List<String> pending = new ArrayList<>();
    for (Line line : all()) {
      if (!line.verified) {
        pending.add(line.title);
      }
    }
    if (pending.isEmpty()) {
      return "";
    }
    return "⚠️ Следното още НЕ е сверено срещу образец 1010 и се пренася ръчно: "
        + String.join("; ", pending)
        + ". Останалите редове са сверени срещу "
        + SOURCE
        + ". Стойностите са изведени от ЗКПО и не зависят от образеца.";
  }
}
