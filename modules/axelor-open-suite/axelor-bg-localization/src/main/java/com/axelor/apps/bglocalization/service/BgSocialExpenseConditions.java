package com.axelor.apps.bglocalization.service;

/**
 * СЪСТОЯНИЕТО НА ТРИТЕ УСЛОВИЯ за един месец и едно лице — входът на {@link
 * BgSocialExpenseCapResolver#apply}.
 *
 * <p>Ръчен клас, не запис: тук няма таблица. Двете фирмени условия се ЧЕТАТ от {@code
 * BgSocialExpenseException}, третото се ИЗЧИСЛЯВА от предходните фишове — тоест трите идват от три
 * различни места и се събират тук, за да влязат в резолвера като едно нещо.
 *
 * <p><b>⚠️ ВСИЧКИТЕ ТРИ ПОЛЕТА СА В ОТРИЦАТЕЛНАТА ПОСОКА, И ТОВА Е САМОТО ПОДРАЗБИРАНЕ.</b> {@code
 * false} значи „условието Е изпълнено“. Оттам следва, че обект с три нули — тоест {@link #allMet()}
 * — е ОПТИМИСТИЧНОТО подразбиране: липсващият ред в {@code BgSocialExpenseException} и
 * неизчисленото средно дават „наред“, а не „обложи всичко“.
 *
 * <p>Написани в положителната посока ({@code publicDebtsClear}), същите три нули щяха да значат
 * „има задължения, операторът не е лицензиран, заплатата е под средната“ — тоест всяка фирма, която
 * не води списък с лоши месеци, щеше да плаща данък върху разходите върху ЦЕЛИЯ размер по чл. 213
 * ал. 3 и чл. 214 ал. 3. Посоката на имената тук не е стил; тя е разликата между двете
 * противоположни подразбирания.
 *
 * <p><b>⚠️ ТРИТЕ УСЛОВИЯ НЕ СА ЕДНО И НЕ ОБВЪРЗВАТ ЕДНИ И СЪЩИ КАПАЧКИ.</b> Публичните задължения
 * се появяват в ДВЕ норми — ЗКПО чл. 208 (за 60-те) и чл. 209а ал. 1 т. 2 (за ваучерите). Другите
 * две са само в чл. 209а ал. 1, тоест чупят САМО ваучерите. Кое условие обвързва кое се чете от
 * реда на капачката ({@code bgRequiresNoPublicDebts} и другите два признака), НЕ от кода ѝ.
 */
public final class BgSocialExpenseConditions {

  /**
   * Фирмата има подлежащи на принудително изпълнение публични задължения към КРАЯ на месеца — ЗКПО
   * чл. 208 и чл. 209а ал. 1 т. 2.
   *
   * <p>⚠️ ФИРМЕНО-МЕСЕЧНО, не пер-лице: паднало, то оскъпява месеца на ВСЯКО лице във фирмата.
   */
  public final boolean publicDebts;

  /**
   * Заплатата за месеца е ПОД средномесечната за предходните три — ЗКПО чл. 209а ал. 1 т. 1.
   *
   * <p>⚠️ ПЕР-ЛИЦЕ, и това е единственото условие, което е такова: пада за едното лице и не пада за
   * съседа му на същия месец. Слято с фирмените, едно лице с намалена заплата щеше да обложи
   * ваучерите на целия екип.
   *
   * <p>⚠️ И СЕ МЕРИ ВЪРХУ ДОГОВОРЕНОТО, НЕ ВЪРХУ ИЗПЛАТЕНОТО. Дословно: „ДОГОВОРЕНОТО основно
   * месечно възнаграждение на лицето в месеца на предоставяне на ваучерите е не по-малко от
   * СРЕДНОМЕСЕЧНОТО ДОГОВОРЕНО основно възнаграждение на лицето за предходните три месеца“. Тоест
   * непълен месец, болничен или неплатен отпуск НЕ свалят договореното и НЕ чупят условието — а
   * сметнато върху начисленото, всеки болничен месец щеше да обложи ваучерите на лицето.
   */
  public final boolean salaryBelowThreeMonthAverage;

  /** Ваучерите НЕ са от лицензиран оператор — ЗКПО чл. 209а ал. 1 т. 3. ФИРМЕНО. */
  public final boolean operatorUnlicensed;

  public BgSocialExpenseConditions(
      boolean publicDebts, boolean salaryBelowThreeMonthAverage, boolean operatorUnlicensed) {
    this.publicDebts = publicDebts;
    this.salaryBelowThreeMonthAverage = salaryBelowThreeMonthAverage;
    this.operatorUnlicensed = operatorUnlicensed;
  }

  /**
   * ОПТИМИСТИЧНОТО ПОДРАЗБИРАНЕ: и трите условия са изпълнени.
   *
   * <p>Това е отговорът при ЛИПСВАЩ ред в {@code BgSocialExpenseException} — и е верният отговор, а
   * не удобният: обичайният месец на обичайната фирма е без публични задължения и с лицензиран
   * оператор, а ред се пише единствено когато има какво да се каже.
   */
  public static BgSocialExpenseConditions allMet() {
    return new BgSocialExpenseConditions(false, false, false);
  }
}
