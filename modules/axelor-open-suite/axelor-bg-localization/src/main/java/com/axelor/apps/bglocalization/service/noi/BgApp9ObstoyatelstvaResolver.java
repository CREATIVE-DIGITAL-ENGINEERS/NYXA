  /** Видът отсъствие, както влиза в свидетелите — код и наименование, за да е разпознаваем. */
  private static String describeAbsence(BgApp9Facts facts) {
    if (!isBlank(facts.absenceTypeName)) {
      return facts.absenceTypeName;
    }
    if (!isBlank(facts.absenceTypeCode)) {
      return facts.absenceTypeCode;
    }
    return "вид отсъствие не е подаден";
  }

  private static boolean isBlank(String value) {
    return value == null || value.trim().isEmpty();
  }
