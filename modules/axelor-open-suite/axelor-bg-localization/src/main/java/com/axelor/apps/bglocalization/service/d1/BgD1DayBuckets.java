/**
 * ДНИТЕ НА ФИША → КОФИТЕ НА Т. 16. Чиста аритметика: без база, без Guice, без Axelor.
 *
 * <p><b>⚠️ КОФАТА СЕ ЧЕТЕ ОТ РЕЧНИКА, А НЕ СЕ ИЗВЕЖДА.</b> Разграничителят е {@code
 * BgAbsenceType.d1Code} — колона, попълнена от seed-а и сверена срещу указанията т. 16.1–16.5 и
 * 16.А. Изкушението е кофата да се изведе от {@code category} или от {@code legalBasis}; и двете са
 * измеримо негодни:
 *
 * <ul>
 *   <li><b>Категорията се РАЗЦЕПВА.</b> Категория „Болнични“ (2) отива в ТРИ различни кофи: 16.2
 *       при обезщетение от ДОО, <b>16.А</b> при възнаграждение от работодателя по чл. 40 ал. 5 КСО,
 *       и <b>16.4</b> при болничен БЕЗ право на обезщетение. Един switch по категория би слял трите
 *       в едно число — при това правдоподобно, защото сборът им е верният общ брой дни.
 *   <li><b>Едно и също основание отива в две кофи.</b> Отпускът по чл. 164б КТ (осиновяване на дете
 *       до 5 г.) е в <b>16.2</b>, когато има право на обезщетение по чл. 53в КСО, и в <b>16.3</b>,
 *       когато няма — указание т. 16.3 казва дословно „В тази точка се попълват и дните БЕЗ право
 *       на обезщетение по КСО“. Тоест разграничителят е ПРАВНОТО СЛЕДСТВИЕ, а не нормата.
 *   <li><b>Основанието е свободен текст</b> и вече е обявено за ненадеждно другаде в модула.
 * </ul>
 *
 * <p><b>⚠️ И ЕДНО, КОЕТО РЕЧНИКЪТ КАЗВА С МЪЛЧАНИЕ: ПЕТ ВИДА ОТСЪСТВИЕ НЯМАТ КОФА.</b> Неплатеният
 * отпуск над 30 дни (по желание и по производствена необходимост), неприсъствието, самоотлъчката и
 * непредставеният болничен носят празен {@code d1Code} — и това е СТОЙНОСТ, не пропуск: те не се
 * зачитат за осигурителен стаж, тоест не влизат в нито една от кофите на т. 16. Празен код тук
 * значи „преброено и оставено извън“, а {@link #UNBUCKETED} го прави проверимо.
 *
 * <p><b>⚠️ „ИЗВЪН КОФИТЕ“ ОБАЧЕ НЕ ЗНАЧИ „БЕЗ ПОСЛЕДИЦА“.</b> Тези дни се ВАДЯТ от остатъка на т.
 * 16.1 — виж {@link #outsideInsurance} и {@code BgD1RecordBuilder#fillDays}. Пропуснати, те биха
 * останали ВЪТРЕ в т. 16.1, тоест декларацията би ги обявила за дни в осигуряване, докато т. 14/15
 * за същите дати обявява, че осигуряването е ПРЕКЪСНАТО ({@link BgD1InsuranceSegments}, КСО чл. 10
 * ал. 2). Същият предикат сваля и заплатата им, в {@code BgPayrollInputBuilder#leaveDaysOf} — двете
 * половини се движат заедно нарочно.
 */
public final class BgD1DayBuckets {

  /** Кофата „отработени и други дни с осигурителни вноски“. */
  public static final String B_16_1 = "16.1";

  /** Кофата „дни ВНР и/или дни с право на обезщетение по чл. 53в КСО“. */
  public static final String B_16_2 = "16.2";

  /** Кофата „дни за отглеждане на дете“. */
  public static final String B_16_3 = "16.3";

  /** Кофата „дни без осигурителни вноски, зачетени за осигурителен стаж“. */
  public static final String B_16_4 = "16.4";

  /** Кофата „дни в неплатен отпуск, зачетени за осигурителен стаж“ (чл. 9 ал. 2 т. 3 КСО). */
  public static final String B_16_5 = "16.5";

  /**
   * Кофата „дни ВНР с възнаграждение от работодателя по чл. 40 ал. 5 КСО“ — т. 16<b>.А</b>.
   *
   * <p>⚠️ БУКВАТА Е КИРИЛСКО „А“ (U+0410), не латинско „A“ (U+0041). Затова стойността се ВЗИМА от
   * {@link BgD1Point#T16_A_EMPLOYER_SICK}, а не се преписва: {@code "16.A".equals("16.А")} е
   * НЕВЯРНО, тоест втори литерал е втори шанс за същата грешка — а тя оставя кофата празна и губи
   * дните ѝ мълчаливо. Същият капан като при т. 31а, и той вече е ухапал веднъж в този модул.
   */
  public static final String B_16_A = BgD1Point.T16_A_EMPLOYER_SICK;

  /**
   * Шестте кофи, В РЕДА НА ДЕКЛАРАЦИЯТА. ⚠️ Редът е част от договора: заб. 1 иска сборът им да
   * пълни позиции 1 и 2 на т. 16, а сериализаторът ги подава като полета 20–25 в този ред.
   */
  public static final Set<String> BUCKETS =
      Collections.unmodifiableSet(
          new LinkedHashSet<>(Arrays.asList(B_16_1, B_16_2, B_16_3, B_16_4, B_16_5, B_16_A)));

  /**
   * Кодовете на отсъствия, които НАРОЧНО остават извън всяка кофа — празен {@code d1Code}.
   *
   * <p>Не се зачитат за осигурителен стаж, тоест никоя точка от т. 16 не ги иска. Списъкът е тук,
   * за да е ПРОВЕРИМ: {@code BgD1DayBucketSeedTest} пада, ако някой от петте получи кофа, и пада,
   * ако шести вид остане без кофа, без да е обявен тук. Празен код без списък е неразличим от
   * забравена клетка.
   *
   * <p><b>⚠️ РЕЦЕПТАТА ЗА ЕДИНСТВЕНИЯ ОТВОРЕН ПРОЧИТ — {@code paid_157_special}.</b> Отпускът по КТ
   * чл. 157 ал. 1 т. 4, 5 и 7 е заведен с кофа <b>16.4</b> („други дни в осигуряване без
   * осигурителни вноски“) и {@code countsAsInsuranceService = true}, тоест осигуряването НЕ се
   * прекъсва. Това е ПРОЧИТ, не изведено: КСО чл. 9 ал. 2 изброява периодите, зачетени за стаж без
   * вноски, и чл. 157 НЕ е в списъка, а ЗСВ (съдебни заседатели) и ЗЗБ (доброволни формирования) не
   * са сверени. Каже ли счетоводителят „прекъсване по КСО чл. 10 ал. 2“, флипът е ДВЕ места и нищо
   * друго:
   *
   * <ol>
   *   <li>в {@code bg_absence_type.csv} (и en/, и fr/, байт по байт еднакви) на ред {@code
   *       paid_157_special}: {@code d1Code} става ПРАЗЕН и {@code countsAsInsuranceService} става
   *       {@code false} — двете ЗАЕДНО, инак {@link #insuranceFlagsConflict} отказва реда;
   *   <li>{@code "paid_157_special"} се добавя в списъка по-долу.
   * </ol>
   *
   * <p>Парите НЕ се менят от флипа — и в двата прочита работодателят не дължи размера и дните се
   * карвират (в първия през кофата, във втория през {@link #outsideInsurance}). Менят се т. 16.4 →
   * изваждаемо на т. 16.1 и появата на двойка т. 14/15. Втората стъпка е в ПРОИЗВОДСТВЕН код и това
   * е съзнателна цена: списъкът пази инварианта „карвиращото множество = Д1-изваждащото множество“,
   * а разхлабен до „подмножество“, той щеше да замълчи точно когато вид тихо излезе от карва.
   */
  public static final Set<String> UNBUCKETED =
      Collections.unmodifiableSet(
          new LinkedHashSet<>(
              Arrays.asList(
                  "unpaid_prod_gt30",
                  "unpaid_own_gt30",
                  "non_attendance",
                  "awol",
                  "sicknote_unsubmitted")));

  /**
   * <b>ИЗВЪН ОСИГУРЯВАНЕТО</b> — денят не се зачита за осигурителен стаж И не е в нито една кофа на
   * т. 16. <b>Единственият предикат, по който се местят ЗАЕДНО заплатата и т. 16.1.</b>
   *
   * <p><b>⚠️ ЕДИН МЕТОД, ДВА ЧИТАТЕЛЯ, И ТОВА Е НАРОЧНО.</b> Викат го {@code
   * BgPayrollInputBuilder#leaveDaysOf} (карвът на заплатата) и {@code BgD1DaySource#read}
   * (изваждаемото на т. 16.1). Написан на двете места, той е свободен да се разминат — а разминат,
   * фишът плаща 17 дни, докато декларацията обявява 22 дни в осигуряване. Точно това разминаване
   * този предикат затваря, и точно затова не се преписва.
   *
   * <p><b>⚠️ КОТВАТА Е {@code countsAsInsuranceService}, А НЕ ПРАЗНИЯТ {@code d1Code}.</b> Това е
   * колоната, от която {@link BgD1InsuranceSegments} ВЕЧЕ строи прекъсванията по <b>КСО чл. 10 ал.
   * 2</b> („осигуряването се прекъсва през периодите, които не се зачитат за осигурителен стаж“) и
   * от нея излизат двойките т. 14/15. Ако т. 16.1 чете ДРУГО, двете точки на един и същи запис си
   * противоречат: т. 15 обявява прекъсване от 7.12, а т. 16.1 брои 7–11.12 като дни в осигуряване.
   * Ключвана по същата колона, т. 16.1 започва да казва същото по конструкция.
   *
   * <p><b>⚠️ И ВЪПРЕКИ ТОВА Е КОНЮНКЦИЯ, А НЕ ГОЛ ФЛАГ.</b> Ред с КОФА и {@code false} би извадил
   * деня ДВА ПЪТИ — веднъж като своята кофа (16.3/16.4/16.5) и втори път като този изваждаем.
   * Празната кофа прави това невъзможно: ден извън осигуряването не е в нито едно друго събираемо.
   * Несъгласието на двете половини не се преглъща, а се обявява — {@link #insuranceFlagsConflict}.
   *
   * @param d1Code {@code BgAbsenceType.d1Code} — кофата, или празно
   * @param countsAsInsuranceService {@code BgAbsenceType.countsAsInsuranceService}, или {@code
   *     null} за непопълнено
   */
  public static boolean outsideInsurance(String d1Code, Boolean countsAsInsuranceService) {
    return Boolean.FALSE.equals(countsAsInsuranceService) && isBlank(d1Code);
  }

  /**
   * ДВЕТЕ ПОЛОВИНИ НА ПРЕДИКАТА СОЧАТ В РАЗЛИЧНИ ПОСОКИ — речникът си противоречи.
   *
   * <p>Два случая, и двата тихи, ако не се обявят:
   *
   * <ul>
   *   <li><b>кофа + {@code false}</b> — денят е и в кофата си, и извън осигуряването. Броен и на
   *       двете места, той излиза от т. 16.1 два пъти; изключен и от двете, изчезва.
   *   <li><b>празна кофа + {@code true} ИЛИ НЕПОПЪЛНЕН флаг</b> — денят не е в нито една точка на
   *       т. 16, но се твърди, че се зачита за стаж. ⚠️ Непопълненият флаг е тук НАРОЧНО: {@code
   *       Boolean.FALSE.equals(null)} е {@code false}, тоест нов вид, създаден от екрана без
   *       отметка, щеше да МИНЕ през {@link #outsideInsurance} и да се плати цял, мълчаливо.
   *       Празната клетка е единственото, което този метод отказва да прочете като стойност.
   * </ul>
   *
   * <p>⚠️ ЧЕТЕ СЕ САМО ЗА СЪПОСТАВЕН вид. Заявка без {@code BgAbsenceType} е ДРУГ дефект („не се
   * знае в коя кофа“) и си има собствен отказ — слети, двата щяха да сочат различна поправка под
   * едно име.
   */
  public static boolean insuranceFlagsConflict(String d1Code, Boolean countsAsInsuranceService) {
    return isBlank(d1Code) != Boolean.FALSE.equals(countsAsInsuranceService);
  }

  private static boolean isBlank(String value) {
    return value == null || value.trim().isEmpty();
  }

  private BgD1DayBuckets() {}

  /** Едно отсъствие: кофата му от речника и дните, паднали в този период. */
  public static final class Entry {

    /** {@code BgAbsenceType.d1Code} — кофата. {@code null} или празно значи „извън т. 16“. */
    public final String bucket;

    /** Работни дни в периода. */
    public final int days;

    public Entry(String bucket, int days) {
      this.bucket = bucket;
      this.days = days;
    }

    @Override
    public String toString() {
      return (bucket == null || bucket.isEmpty() ? "—" : bucket) + ":" + days;
    }
  }

  /**
   * Сборът по кофи — шест числа, всяко от които може да е нула.
   *
   * <p>⚠️ ВСИЧКИТЕ ШЕСТ КЛЮЧА ВИНАГИ СА В КАРТАТА, включително нулевите. Липсващ ключ и нула са
   * различни твърдения на всяко друго място в този модул — но НЕ тук: т. 16 е брой ДНИ, а „нула дни
   * в платен отпуск“ и „няма платен отпуск“ са едно и също наблюдение. Пълната карта прави сбора по
   * заб. 1 проверим без проверки за null на шест места.
   *
   * <p>⚠️ Отсъствие с ПРАЗНА кофа се ПРОПУСКА, а не пада. Празният {@code d1Code} е стойност (виж
   * {@link #UNBUCKETED}); отказ тук би спрял декларацията заради самоотлъчка.
   *
   * <p>⚠️ Отсъствие с НЕПОЗНАТА кофа също се пропуска — но {@link #unknownBuckets} го връща, за да
   * може извикващият да го ОБЯВИ. Тихо преброено в „други“, то би изчезнало от декларацията, а
   * сборът в т. 16 щеше да е по-малък от истинския.
   */
  public static Map<String, Integer> sum(Iterable<Entry> entries) {
    Map<String, Integer> out = new LinkedHashMap<>();
    for (String bucket : BUCKETS) {
      out.put(bucket, 0);
    }
    if (entries == null) {
      return Collections.unmodifiableMap(out);
    }
    for (Entry e : entries) {
      if (e == null || e.bucket == null) {
        continue;
      }
      String bucket = e.bucket.trim();
      if (!out.containsKey(bucket)) {
        continue;
      }
      out.put(bucket, out.get(bucket) + e.days);
    }
    return Collections.unmodifiableMap(out);
  }

  /**
   * Кофите, които са НЕПОЗНАТИ — нито една от шестте, нито празна.
   *
   * <p>Отделен метод, а не изключение в {@link #sum}: сборът трябва да се получи и когато един ред
   * е сгрешен, за да се види КОЛКО липсва. Изключение би оставило декларацията без нито едно число.
   */
  public static Set<String> unknownBuckets(Iterable<Entry> entries) {
    Set<String> unknown = new LinkedHashSet<>();
    if (entries == null) {
      return unknown;
    }
    for (Entry e : entries) {
      if (e == null || e.bucket == null) {
        continue;
      }
      String bucket = e.bucket.trim();
      if (!bucket.isEmpty() && !BUCKETS.contains(bucket)) {
        unknown.add(bucket);
      }
    }
    return unknown;
  }

  /**
   * ПОЗИЦИИ 1 И 2 НА Т. 16 — сборът от т. 16.1 до 16.5 и т. 16.А, дословно по заб. 1.
   *
   * <p>⚠️ ИЗВЕЖДА СЕ, НЕ СЕ ВЪВЕЖДА. „В позиции 1 и 2 на т. 16 се вписва СБОРЪТ от дните, отразени
   * в т. 16.1 до 16.5 и т. 16.А.“ Общият брой, записан независимо от съставките си, може да се
   * размине с тях — а НАП сверява точно това равенство.
   */
  public static int total(Map<String, Integer> byBucket) {
    if (byBucket == null) {
      return 0;
    }
    int total = 0;
    for (String bucket : BUCKETS) {
      Integer days = byBucket.get(bucket);
      total += days == null ? 0 : days;
    }
    return total;
  }
}
