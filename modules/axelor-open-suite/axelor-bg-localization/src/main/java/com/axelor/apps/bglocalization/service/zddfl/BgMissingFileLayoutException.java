package com.axelor.apps.bglocalization.service.zddfl;

/**
 * ОТКАЗЪТ, КОГАТО ФИЗИЧЕСКИЯТ ФОРМАТ ГО НЯМА.
 *
 * <p><b>⚠️ ХВЪРЛЯ СЕ, А НЕ СЕ ПИШЕ КАТО ПРЕДУПРЕЖДЕНИЕ.</b> Файл към НАП, построен по ДОГАДКА за
 * ширини, разделител и ред на полетата, изглежда точно като верен файл: има го, сваля се, качва се
 * на портала и се отхвърля там — или, по-лошо, се приема с разместени данни. Банер над такъв файл
 * не спира никого. Затова слоят отказва да произведе байтове изобщо.
 *
 * <p>⚠️ Прецедентът е {@code BgVatExportService#SALES_FORMAT_DISCLAIMER} — но там форматът беше
 * ИЗВЛЕЧЕН от приет файл и оставаше под съмнение само зоната на клона. Тук няма извлечено нищо:
 * указание т. 1 към образец 5-2001 казва дословно „във формат и по ред, ОДОБРЕНИ СЪС ЗАПОВЕД на
 * изпълнителния директор на НАП“, а тази заповед не е в проекта.
 */
public class BgMissingFileLayoutException extends IllegalStateException {

  private static final long serialVersionUID = 1L;

  public BgMissingFileLayoutException(String formName) {
    super(
        "Физическият формат на "
            + formName
            + " НЕ Е ПОТВЪРДЕН — файл не се произвежда. Структурата на записа (разделител или"
            + " фиксирана ширина, ред и дължина на полетата, формат на датите и сумите, кодировка,"
            + " име на файла, заглавен/краен запис) идва със ЗАПОВЕД на изпълнителния директор на"
            + " НАП, която още не е в проекта. Догаденият формат е ПО-ЛОШ от липсващия: той се"
            + " сваля и се качва, а разместените данни не личат от нито един екран.");
  }
}
