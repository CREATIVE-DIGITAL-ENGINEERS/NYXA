package com.axelor.apps.bglocalization.service.zddfl;

/**
 * ФИЗИЧЕСКИЯТ ФОРМАТ НА ЕДИН ОБРАЗЕЦ — интерфейсът, зад който стои заповедта на НАП.
 *
 * <p><b>⚠️ ДОКУМЕНТЕН, А НЕ РЕДОВИ — И ТОВА Е ПРОМЯНА СПРЯМО ПЪРВОНАЧАЛНИЯ ШЕВ.</b> Дотук
 * интерфейсът връщаше {@code List<String>} и услугата ги слепваше с CRLF през {@code
 * BgVatFileWriter} плюс евентуален {@code CHR(26)} — форма, взета от ДДС-дневниците и от Д1, където
 * записът Е ред. Форматът по чл. 73 се оказа <b>XML</b>: там „ред“ няма смисъл, краят на реда се
 * нормализира при четене, а маркер за край на файл не съществува. Редовият шев би заставил писача
 * да реже документа на парчета само за да ги слепи обратно.
 *
 * <p><b>⚠️ ВСЕКИ МЕТОД ТУК Е ВЪПРОС, НА КОЙТО ЗАПОВЕДТА ОТГОВАРЯ.</b> Докато {@link #isConfirmed()}
 * е {@code false}, всеки друг хвърля {@link BgMissingFileLayoutException} — тоест нито един въпрос
 * не може да бъде отговорен мълчаливо с подразбираща се стойност.
 *
 * @param <C> съдържанието на образеца, събрано от ЗАПИСАНИЯ отчет (не от регистъра)
 */
public interface BgDeclarationFileLayout<C> {

  /** Името на образеца за човешките съобщения, напр. „образец 5-2001 (чл. 73 ал. 1)“. */
  String formName();

  /**
   * Потвърден ли е форматът срещу заповед на изпълнителния директор на НАП.
   *
   * <p>⚠️ ЕДИНСТВЕНИЯТ метод, който НЕ хвърля при непотвърден формат — той е въпросът „има ли
   * формат“, а не въпрос КЪМ формата. Извикващият го пита ПРЕДИ да поиска каквото и да е друго.
   */
  boolean isConfirmed();

  /** Името на файла, както го иска заповедта. */
  String fileName();

  /** Кодировката — име на {@code Charset}, напр. {@code WINDOWS-1251}. */
  String encoding();

  /**
   * Съдържанието → ЦЕЛИЯТ документ като текст.
   *
   * <p>⚠️ Текст, а не байтове: кодирането е на услугата, защото тя е и мястото, където знак извън
   * кодировката трябва да ПАДНЕ, вместо да бъде заменен с въпросителна.
   */
  String document(C content);

  /** Отказът на едно място — извиква се първо от всяка реализация. */
  default void requireConfirmed() {
    if (!isConfirmed()) {
      throw new BgMissingFileLayoutException(formName());
    }
  }
}
