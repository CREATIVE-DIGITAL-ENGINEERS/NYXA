package com.axelor.apps.bglocalization.service;

import com.axelor.apps.bglocalization.service.payroll.BgEarningsResolver;

/**
 * НЕНОРМИРАН РАБОТЕН ДЕН + СИРВ — ЗАБРАНЕНА КОМБИНАЦИЯ, А НЕ ВЪПРОС „ПЛАЩА ЛИ СЕ“.
 *
 * <p><b>Нормата е една и е категорична.</b> КТ чл. 142 ал. 5 дословно: „Не се допуска сумирано
 * изчисляване на работното време за работниците и служителите с ненормиран работен ден.“ Тоест лице
 * с ненормиран работен ден НЕ МОЖЕ да е на сумирано отчитане — двойката не е рядка, не е спорна и
 * не е въпрос на избор на работодателя, тя е недопустима.
 *
 * <p><b>⚠️ ГРЕШНАТА АЛИНЕЯ ДОТУК, И ИМЕННО ТЯ РОДИ „ОТВОРЕНИЯ ВЪПРОС“.</b> Енджинът се позоваваше
 * на чл. 139а ал. 2 — „Не може да се установява ненормиран работен ден за работниците и служителите
 * с НАМАЛЕНО работно време“ — и оттам извеждаше, че комбинацията с СИРВ е възможна, защото СИРВ по
 * чл. 142 не е намалено работно време (чл. 137). Прочитът на ал. 2 е верен, но не е пълен: другата
 * посока на същата забрана е в ДРУГ член. Чл. 142 ал. 5 затваря точно нея. Затова тук вече няма
 * наименувана булева константа за обръщане от ТРЗ — нямаше казус, който да се решава.
 *
 * <p><b>Двата читателя и защо правилото не се преписва.</b> Записът на договора ({@code
 * BgEmploymentContractManagementRepository}) ОТКАЗВА двойката — тя не бива да съществува. Часовият
 * енджин ({@link BgEarningsResolver}) я ОТКАЗВА ВТОРИ ПЪТ, защото заварен ред, seed или миграция
 * могат да я носят отпреди пазача, а фиш, сметнат върху недопустим режим, е тих надник върху
 * основание, което законът не дава. Второ копие на правилото би се разминало при първата поправка,
 * и то тихо — същият довод като при {@link BgInsuredTypeCategoryRule}.
 *
 * <p><b>⚠️ ЗАЩО ОТКАЗ, А НЕ „НЕ СЕ ДЪЛЖИ“.</b> Изходът в енджина е {@code REFUSED}, не {@code
 * NOT_ENTITLED}: последното значи „правото го няма на това лице“ и е ВЕРНИЯТ фиш, тоест адресат
 * няма. Тук фишът НЕ е верен — сгрешен е договорът, и някой трябва да го поправи СЕГА. Свито до „не
 * се дължи“, недопустимият договор щеше да живее вечно, а перото да мълчи вместо да сочи.
 *
 * <p>⚠️ Нищо тук не мени правилата за ненормиран ден при ДОПУСТИМ режим: извънредният труд в
 * работни дни не се заплаща (чл. 263 ал. 1), а в дните на седмичната почивка и на официалните
 * празници се заплаща в размерите по чл. 262 ал. 1 т. 2 и 3 (ал. 2). Тези три отговора не минават
 * оттук.
 */
public final class BgWorkTimeModeRule {

  private BgWorkTimeModeRule() {}

  /**
   * НЕДОПУСТИМА ЛИ Е ДВОЙКАТА — ненормиран работен ден при сумирано изчисляване.
   *
   * <p>Режимът се сравнява ОКАСТРЕН: полето е низ от речника {@code bg.work.time.mode.select} и
   * минава през импорт и през REST, а „ 2 “ е същият режим като „2“. Празно или {@code null} е
   * незададен въпрос, не подневно отчитане — то се отказва по собствена причина от перото, което го
   * чете.
   */
  public static boolean isForbiddenPair(boolean unregulatedWorkDay, String workTimeMode) {
    if (!unregulatedWorkDay || workTimeMode == null) {
      return false;
    }
    return BgEarningsResolver.WORK_TIME_MODE_SIRV.equals(workTimeMode.trim());
  }

  /**
   * ИМЕТО НА ЗАБРАНАТА — едно изречение, нормата дословно и ДВЕТЕ полета в него.
   *
   * <p>{@code null}, когато двойката е допустима. Двете полета стоят заедно в съобщението по същия
   * довод като при {@link BgInsuredTypeCategoryRule#noRatesFor}: сгрешено може да е което и да е от
   * тях, а едно-полево съобщение праща оператора да поправя другото.
   */
  public static String forbiddenPairRefusal(boolean unregulatedWorkDay, String workTimeMode) {
    if (!isForbiddenPair(unregulatedWorkDay, workTimeMode)) {
      return null;
    }
    return "КТ чл. 142, ал. 5 не допуска СИРВ при ненормиран работен ден. Дословно: „Не се допуска"
        + " сумирано изчисляване на работното време за работниците и служителите с ненормиран"
        + " работен ден.“ По този договор са отметнати И ДВЕТЕ — „Ненормиран работен ден (КТ чл."
        + " 139а)“ и режим на отчитане „Сумирано изчисляване (СИРВ)“. Сгрешено може да е което и да"
        + " е от двете: или ненормираният ден не е установен със заповед по чл. 139а ал. 3, или"
        + " режимът на отчитане е подневен. Поправи едното от двете на трудовия договор.";
  }
}
