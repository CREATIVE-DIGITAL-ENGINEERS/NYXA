package com.axelor.apps.bglocalization.service.fixedasset;

import com.axelor.apps.account.db.FixedAsset;
import com.axelor.apps.account.db.FixedAssetLine;
import com.axelor.apps.account.db.repo.FixedAssetLineRepository;
import java.math.BigDecimal;
import java.time.LocalDate;
import java.util.List;

/**
 * Преустановяване на начисляването на данъчни амортизации по чл. 59 ЗКПО, като чисти функции.
 *
 * <p><b>чл. 59 ал. 1</b>, дословно: „Начисляването на данъчни амортизации се преустановява, когато
 * съответният актив временно не се използва (не носи икономическа изгода) през период, <b>по-дълъг
 * от дванадесет месеца</b>. Начисляването се преустановява от началото на месеца, <b>следващ
 * месеца, през който е изтекъл срокът</b> по изречение първо, и се възобновява от началото на
 * месеца на връщането на актива в експлоатация. Данъчният амортизируем актив <b>не се отписва</b>
 * от данъчния амортизационен план.“
 *
 * <p><b>чл. 59 ал. 2</b>, дословно: „При определянето на данъчния финансов резултат за годината,
 * през която е изтекъл дванадесетмесечният срок по ал. 1, годишната данъчна амортизация на данъчно
 * задълженото лице <b>се намалява</b> с размера на начислената данъчна амортизация за актива през
 * дванадесетте месеца, през които активът не се е използвал. С размера на намалението по изречение
 * първо <b>се коригират стойностите</b> на данъчния амортизируем актив към датата на
 * преустановяване начисляването на данъчна амортизация, както следва: 1. намалява се начислената
 * данъчна амортизация за актива; 2. <b>увеличава се данъчната стойност на актива</b>.“
 *
 * <p><b>чл. 59 ал. 4</b>, дословно: „Не се преустановява начисляването на данъчни амортизации за
 * активите по чл. 60, ал. 3.“
 *
 * <p>⚠️ <b>ТОВА НЕ Е ПАУЗА.</b> Ал. 2 връща назад дванадесетте начислени месеца и УВЕЛИЧАВА
 * данъчната стойност. Запазването на стойностите е <b>чл. 61 ал. 1</b> (предишен текст на чл. 61 —
 * ДВ, бр. 98 от 2018 г., в сила от 01.01.2019 г.) и важи при преоценка, обезценка, промяна в
 * счетоводната политика и ДДС регистрация — друга ситуация. И законът НИКЪДЕ не формулира
 * удължаване на плана: планът върви по-дълго като СЛЕДСТВИЕ от свалената амортизация и вдигнатата
 * данъчна стойност, под същия таван на чл. 53 ал. 3.
 *
 * <p>Сверено дословно на 09.09.2026 г. срещу консолидирания ЗКПО (посл. изм. и доп. ДВ бр. 30 от 27
 * март 2026 г.).
 *
 * <p>⚠️ <b>Анотацията на чл. 59 гласи „в сила от 01.01.2007 г.“ и това НЕ е печатна грешка</b> —
 * макар съседните разпоредби от СЪЩИЯ ДВ бр. 110 от 2007 г. (чл. 50 ал. 1 т. 2, чл. 60 ал. 3 т. 1)
 * да са в сила от 01.01.2008 г. Обяснението е в § 68 от преходните разпоредби на онзи закон,
 * дословно: „Законът влиза в сила от 1 януари 2008 г. с изключение на параграфи 7, 21, 24, 38 - 45,
 * 49, 50, § 54, т. 3 - 7, § 55, т. 1 - 4 и § 56 - 59, <b>които влизат в сила от 1 януари 2007
 * г.</b>“ Изменението на чл. 59 е сред изключенията. В консолидирания текст 38 разпоредби носят
 * 01.01.2007, а 76 — 01.01.2008; разминаването е на ЗАКОНА, не на цитата, и „уеднаквяването“ му би
 * го счупило.
 */
public final class BgAssetSuspensionRules {

  private BgAssetSuspensionRules() {}

  /** Дванадесетмесечният срок по ал. 1 изречение първо. */
  public static final int TERM_MONTHS = 12;

  /**
   * Датата, от която данъчната амортизация спира — първият ден на тринайсетия месец на неползване.
   *
   * <p>⚠️ <b>ДА СЕ ПОТВЪРДИ — броенето на срока има два прочита и разликата е ЕДИН МЕСЕЦ
   * амортизация.</b> Прочит (а): срокът се брои по общото правило за срокове в месеци и изтича на
   * съответното число на дванадесетия месец (актив, спрян на 01.03.2026, дава изтичане 01.03.2027,
   * тоест спиране от 01.04.2027). Прочит (б): дванадесетте месеца са цели месеци от месеца на
   * спирането, изтичат в края на дванадесетия (февруари 2027) и спирането е от 01.03.2027.
   *
   * <p><b>Тук е приложен прочит (б), и доводът е ВЪТРЕШНАТА СВЪРЗАНОСТ на ал. 1 с ал. 2, не
   * предпазливост.</b> Ал. 2 обръща „начислената данъчна амортизация за актива през ДВАНАДЕСЕТТЕ
   * месеца, през които активът не се е използвал“. По прочит (а) спирането започва след тринайсетия
   * месец, тъй че тринайсетият остава начислен и НЕ попада в обърнатите дванадесет — един месец
   * амортизация за неползван актив увисва без основание. По прочит (б) двете алинеи се захващат:
   * обърнатите дванадесет месеца плюс спирането оттам нататък дават нула амортизация за целия
   * период на неползване. Прочит, при който едната алинея оставя дупка в другата, е по-слаб.
   *
   * <p>Формулата затова тръгва от НАЧАЛОТО на месеца, в който активът е спрял да се ползва —
   * законът мери в месеци, не в дни, и в самия текст всички граници са „началото на месеца“.
   */
  public static LocalDate suspensionStart(LocalDate idleSince) {
    if (idleSince == null) {
      return null;
    }
    return idleSince.withDayOfMonth(1).plusMonths(TERM_MONTHS);
  }

  /**
   * Последният ден, за който още се начислява — краят на дванадесетия месец на неползване.
   *
   * <p>Не е ново правило, а другата страна на {@link #suspensionStart}: изнесено е, защото
   * справките и филтрите на плана мислят в „до дата“, а не в „от дата“, и обръщането на границата
   * на ръка е точно там, където се раждат едномесечните грешки.
   */
  public static LocalDate lastChargedDay(LocalDate idleSince) {
    LocalDate start = suspensionStart(idleSince);
    return start == null ? null : start.minusDays(1);
  }

  /**
   * Дължи ли се вече преустановяване към дадена дата.
   *
   * <p>Три отговора „не“, и всеки от тях е реален случай: липсва дата на спиране; активът се е
   * върнал в експлоатация ПРЕДИ да изтече срокът (тогава периодът не е „по-дълъг от дванадесет
   * месеца“ и чл. 59 изобщо не се задейства — консервация за три месеца не спира нищо); или срокът
   * още не е изтекъл.
   */
  public static boolean isSuspensionDue(
      LocalDate idleSince, LocalDate returnedToService, LocalDate asOf) {
    LocalDate start = suspensionStart(idleSince);
    if (start == null || asOf == null) {
      return false;
    }
    if (returnedToService != null && returnedToService.isBefore(start)) {
      return false;
    }
    return !asOf.isBefore(start);
  }

  /**
   * Възобновяване — „от началото на месеца на връщането на актива в експлоатация“.
   *
   * <p>Началото на месеца НА връщането, не на следващия. Ал. 1 нарочно е асиметрична: спирането е
   * от следващия месец, възобновяването е от текущия. Изравняването на двете „за симетрия“ би дало
   * месец амортизация в грешната посока.
   */
  public static LocalDate resumptionStart(LocalDate returnedToService) {
    return returnedToService == null ? null : returnedToService.withDayOfMonth(1);
  }

  /**
   * Годината, за която се прави намалението по ал. 2 — „годината, през която е изтекъл
   * дванадесетмесечният срок“.
   *
   * <p>Това е годината на ПОСЛЕДНИЯ начислен месец, не на първия спрян. При срок, който изтича през
   * декември, двете са различни години и намалението отива в предходната.
   */
  public static Integer reversalYear(LocalDate idleSince) {
    LocalDate last = lastChargedDay(idleSince);
    return last == null ? null : last.getYear();
  }

  /**
   * Размерът на обръщането по ал. 2 — начислената ДАНЪЧНА амортизация през дванадесетте месеца на
   * неползване.
   *
   * <p>⚠️ Само РЕАЛИЗИРАНИ редове. Плановите редове са бъдеще, а ал. 2 обръща начисленото; сборът с
   * плановите би върнал амортизация, която никога не е влизала в данъчния финансов резултат. Същият
   * капан свали чл. 60 ал. 3 т. 1 при WS-A3 — виж {@code BgAssetWriteOffRules#carryingValue}.
   *
   * <p>⚠️ И само от ДАНЪЧНИЯ план. Ал. 2 говори за данъчна амортизация; счетоводната при
   * консервация се спира по счетоводната политика и не се урежда оттук.
   *
   * @return сборът, или нула когато няма какво да се обръща
   */
  public static BigDecimal reversalAmount(FixedAsset fixedAsset, LocalDate idleSince) {
    LocalDate from = idleSince == null ? null : idleSince.withDayOfMonth(1);
    LocalDate until = suspensionStart(idleSince);
    if (fixedAsset == null || from == null) {
      return BigDecimal.ZERO;
    }
    List<FixedAssetLine> lines = fixedAsset.getFiscalFixedAssetLineList();
    if (lines == null) {
      return BigDecimal.ZERO;
    }
    BigDecimal total = BigDecimal.ZERO;
    for (FixedAssetLine line : lines) {
      if (line == null
          || line.getDepreciationDate() == null
          || line.getStatusSelect() != FixedAssetLineRepository.STATUS_REALIZED) {
        continue;
      }
      LocalDate date = line.getDepreciationDate();
      if (date.isBefore(from) || !date.isBefore(until)) {
        continue;
      }
      total = total.add(line.getDepreciation());
    }
    return total;
  }

  /**
   * Датата на спиране, ако спиране изобщо се дължи — иначе {@code null}.
   *
   * <p>Отделно от {@link #suspensionStart}, което е само аритметика на срока. Тук се вземат ТРИТЕ
   * решения, които правят разликата между „срокът изтича на тази дата“ и „този актив се спира“: има
   * ли обявена дата на неползване, изключен ли е активът по ал. 4, и не се ли е върнал в
   * експлоатация ПРЕДИ срокът да изтече.
   *
   * <p>⚠️ Стои тук, а не в repository-то, за да има свидетел. Модулът няма mock-подпора, тъй че
   * решение, оставено в услуга или в repository, се проверява само на живо — а точно това решение
   * определя дали активът ще носи обръщане по ал. 2 или не.
   */
  public static LocalDate suspensionFor(
      FixedAsset fixedAsset, LocalDate idleSince, LocalDate returnedToService) {
    if (idleSince == null || isSuspensionExcluded(fixedAsset)) {
      return null;
    }
    LocalDate start = suspensionStart(idleSince);
    if (returnedToService != null && returnedToService.isBefore(start)) {
      // Върнат преди срокът да изтече: периодът не е „по-дълъг от дванадесет месеца“ и чл. 59
      // изобщо не се задейства. Консервация за три месеца не спира нищо.
      return null;
    }
    return start;
  }

  /**
   * Обръщането по ал. 2, ако спиране се дължи — иначе нула.
   *
   * <p>Двойка на {@link #suspensionFor} и с една и същa проверка: сума без дължимо спиране би
   * върнала амортизация, която законът не отнема.
   */
  public static BigDecimal reversalFor(
      FixedAsset fixedAsset, LocalDate idleSince, LocalDate returnedToService) {
    if (suspensionFor(fixedAsset, idleSince, returnedToService) == null) {
      return BigDecimal.ZERO;
    }
    return reversalAmount(fixedAsset, idleSince);
  }

  /** Годината на намалението, ако спиране се дължи — иначе {@code null}. */
  public static Integer reversalYearFor(
      FixedAsset fixedAsset, LocalDate idleSince, LocalDate returnedToService) {
    if (suspensionFor(fixedAsset, idleSince, returnedToService) == null) {
      return null;
    }
    return reversalYear(idleSince);
  }

  /**
   * Изключен ли е активът от преустановяване по <b>ал. 4</b>.
   *
   * <p>„Не се преустановява начисляването на данъчни амортизации за активите по чл. 60, ал. 3“ —
   * тоест за напълно амортизираните за счетоводни цели (т. 1) и за отписаните в резултат на
   * увеличение в стойностния праг на същественост (т. 2). И двете групи остават в ДАП по ал. 4 и
   * излизат по реда на ал. 1, тоест амортизацията им ТЕЧЕ; спиране върху тях би влязло в пряко
   * противоречие с това.
   *
   * <p>⚠️ Ал. 4 препраща към целия чл. 60 ал. 3, тъй че и двете точки трябва да се четат — проверка
   * само на напълно амортизираните пропуска активите по вдигнатия праг.
   */
  public static boolean isSuspensionExcluded(FixedAsset fixedAsset) {
    if (fixedAsset == null) {
      return false;
    }
    return BgAssetWriteOffRules.isFullyDepreciatedForAccounting(fixedAsset)
        || fixedAsset.getBgMaterialityIncrease() != null;
  }
}
