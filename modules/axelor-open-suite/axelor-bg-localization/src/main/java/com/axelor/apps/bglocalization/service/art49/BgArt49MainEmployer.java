package com.axelor.apps.bglocalization.service.art49;

import com.axelor.apps.base.db.Company;
import com.axelor.apps.hr.db.EmploymentContract;
import java.time.LocalDate;
import java.util.List;

/**
 * КОГО ПРЕИЗЧИСЛЯВА РАБОТОДАТЕЛЯТ — единственият въпрос на чл. 49 ал. 1, зададен ПРЕДИ смятането.
 *
 * <p><b>Нормата, дословно.</b> Чл. 49 ал. 1 ЗДДФЛ: „Работодателят до 31 януари на следващата
 * данъчна година изчислява годишната данъчна основа по чл. 25, ал. 1 и 3, намалена по реда на ал.
 * 3, и определя годишния размер на данъка, КОГАТО КЪМ 31 ДЕКЕМВРИ на данъчната година ТОЙ е
 * работодател по ОСНОВНОТО трудово правоотношение на работника или служителя.“ Три условия в едно
 * изречение: този работодател, това лице, тази дата.
 *
 * <p><b>⚠️ И ТОВА НЕ Е ФИЛТЪР ЗА УДОБСТВО, А ГРАНИЦАТА НА ПРАВОМОЩИЕТО.</b> Указание т. 7 към
 * образеца: „данни в колона 6 на редове 8.1, 8.2 и 8.3, както и в колони от 11 до 14 включително,
 * както и колони от 17 до 21 на ред 8.3 се попълват САМО от работодател по основно трудово
 * правоотношение за съответното лице“. Тоест за лице без основно ТПО тук справката НЕ Е непълна —
 * тя е ВЯРНА с празни колони, а попълнени, същите колони биха били твърдение, което този
 * работодател няма право да прави: годишният данък на лицето се определя другаде — при другия
 * работодател по чл. 49 или от самото лице с годишна данъчна декларация по чл. 50.
 *
 * <p><b>⚠️ ЧИСТА ФУНКЦИЯ ВЪРХУ ВЕЧЕ ПРОЧЕТЕНИ ДОГОВОРИ.</b> Прочитът от базата стои в {@code
 * BgArt73Para6ReportService}; тук няма нито заявка, нито Guice. Причината е същата, с която {@code
 * BgArt73Para6Aggregator} е чист: правилото на чл. 49 ал. 1 трябва да може да се свери със свидетел
 * с дати, без база.
 *
 * <p><b>⚠️ КАКВО НЕ ПИТА ТОЗИ КЛАС — ТРИ НЕЩА, И ВСЯКОТО Е НАРОЧНО.</b>
 *
 * <ul>
 *   <li><b>Не пита за отказ на лицето.</b> Чл. 49 няма алинея, с която работникът да поиска
 *       преизчисляване да НЕ се прави — сверено дословно върху ал. 1–8. Онова, което лицето подава
 *       или не подава, е по ал. 4 и то управлява САМО намаленията по ал. 3, тоест облекченията, а
 *       не самото преизчисляване. Виж {@code BgArt49Reliefs} за втората врата.
 *   <li><b>Не пита за код 102.</b> Чл. 49 ал. 8 изключва доходите по § 1 т. 26 б. „и“ от годишната
 *       основа и от годишния данък — но това е изключване на ДОХОД, а не на ЛИЦЕ. Същото лице може
 *       да има и доход по код 101; тогава то се преизчислява, а доходът му по код 102 остава
 *       настрана. Изключването живее в {@code BgArt49Recalculation}, където се събират основите.
 *   <li><b>Не пита за доход от ДРУГ работодател.</b> Чл. 49 ал. 2 го включва в основата, ако лицето
 *       предостави служебна бележка по чл. 45 — вход, който модулът няма и който е обявен като
 *       граница. Наличието му не мени КОЙ преизчислява, а само с колко.
 * </ul>
 */
public final class BgArt49MainEmployer {

  private BgArt49MainEmployer() {}

  /**
   * ДАТАТА, КЪМ КОЯТО СЕ ГЛЕДА — 31 декември на данъчната година.
   *
   * <p>⚠️ Не „последният ден с фиш“ и не „днес“. Лице, напуснало на 15 декември, НЯМА основно ТПО
   * към 31 декември и не се преизчислява от този работодател, макар да има единайсет месеца фишове;
   * лице, постъпило на 20 декември, се преизчислява, макар да има един. Двата случая изглеждат
   * несправедливо, ако мярката е доходът — но мярката на нормата е ДАТАТА.
   */
  public static LocalDate yearEnd(int taxYear) {
    return LocalDate.of(taxYear, 12, 31);
  }

  /**
   * Този работодател ли е работодател по ОСНОВНОТО ТПО на лицето към 31 декември.
   *
   * <p>Изисква едновременно: договор на СЪЩОТО дружество, вдигнат {@code bgIsPrimaryContract} и
   * действие към 31 декември (започнал не по-късно и незавършил по-рано).
   *
   * @param contracts договорите на лицето — вече прочетени; {@code null} се чете като „няма“
   * @param company дружеството, което подава справката
   * @param taxYear данъчната година
   */
  public static boolean recalculates(
      List<EmploymentContract> contracts, Company company, int taxYear) {
    return contractAt(contracts, company, taxYear) != null;
  }

  /**
   * ДОГОВОРЪТ, който прави дружеството работодател по основното ТПО — или {@code null}.
   *
   * <p>⚠️ Връща договора, а не само „да/не“, за да може повикващият да напише КОЙ договор е
   * основанието. Отказ без основание не се проверява от човек.
   */
  public static EmploymentContract contractAt(
      List<EmploymentContract> contracts, Company company, int taxYear) {
    if (contracts == null || company == null) {
      return null;
    }
    LocalDate date = yearEnd(taxYear);
    for (EmploymentContract contract : contracts) {
      if (contract != null && isMainAt(contract, company, date)) {
        return contract;
      }
    }
    return null;
  }

  /**
   * Един договор: основен ли е, на това дружество ли е и действа ли на датата.
   *
   * <p><b>⚠️ ЛИПСВАЩА НАЧАЛНА ДАТА НЕ СЕ ЧЕТЕ КАТО „ОТВСЯКОГА“.</b> Договор без {@code startDate} е
   * непопълнен запис, а не безсрочно действащ: прочетен като действащ, той би вкарал в
   * преизчисляването лице, за което никой не е казал кога е постъпило. Липсваща КРАЙНА дата е друго
   * — тя е нормалният запис на безсрочен договор и се чете като „още действа“.
   *
   * <p>⚠️ {@code bgIsPrimaryContract} се чете направо: генерираният getter за boolean връща FALSE
   * при NULL колона, а подразбирането на полето е TRUE, тоест заварен ред без стойност се чете като
   * „не е основен“ и НЕ влиза. Това е предпазливата посока — колони 6 и 17–21 остават празни,
   * вместо да бъдат попълнени за лице, за което правомощието не е потвърдено.
   */
  private static boolean isMainAt(EmploymentContract contract, Company company, LocalDate date) {
    if (!contract.getBgIsPrimaryContract() || !company.equals(contract.getPayCompany())) {
      return false;
    }
    LocalDate start = contract.getStartDate();
    LocalDate end = contract.getEndDate();
    return start != null && !start.isAfter(date) && (end == null || !end.isBefore(date));
  }
}
