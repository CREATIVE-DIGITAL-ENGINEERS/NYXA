package com.axelor.apps.bglocalization.service.fixedasset;

import com.axelor.apps.account.db.FixedAsset;
import com.axelor.apps.account.db.FixedAssetLine;
import com.axelor.apps.account.db.repo.FixedAssetLineRepository;
import java.math.BigDecimal;
import java.time.LocalDate;
import java.util.List;

/**
 * Отписване на актив по ЗКПО — чл. 60 (данъчният план) и чл. 66 (данъчното преобразуване), като
 * чисти функции.
 *
 * <p>Изнесени от услугите нарочно: модулът няма mock-подпора в тестовете, а всяко от тези правила
 * иска свидетел с ЧИСЛА или с ДАТИ. Услугите отгоре само подават актива и прибират резултата.
 */
public final class BgAssetWriteOffRules {

  private BgAssetWriteOffRules() {}

  // ------------------------------------------------------------------ чл. 60

  /**
   * Датата, до която данъчният амортизационен план остава, когато активът се отписва счетоводно —
   * последният ден на месеца ПРЕДИ месеца на счетоводното отписване.
   *
   * <p>Чл. 60 ал. 2 ЗКПО, дословно: „Когато активът се отпише за счетоводни цели, преди да е
   * напълно амортизиран за данъчни цели, той се отписва от данъчния амортизационен план <b>в
   * началото на месеца</b>, през който се отписва за счетоводни цели.“
   *
   * <p><b>Следствието, което базата пропуска.</b> Отписване „в началото на месеца“ значи, че самият
   * месец на отписване НЕ носи данъчна амортизация — нито пълна, нито пропорционална. Базовият
   * {@code AbstractFixedAssetLineServiceImpl.generateProrataDepreciationLine} обаче му дава ДНЕВЕН
   * дял, при това и за данъчния план, защото не различава двата. Върнатата тук дата е точката, до
   * която данъчните редове се пазят: всичко от месеца на отписване нататък пада.
   *
   * <p>Разликата не е козметична. Машина с ДАС 10 000 и норма 30% (250/месец), отписана на
   * 30.06.2028 след 29 реализирани месеца: по базата данъчната амортизация става 7 500 и ДБС 2 500,
   * а по чл. 60 ал. 2 — 7 250 и ДБС 2 750. Тези 250 влизат право в намалението по чл. 66 ал. 2.
   */
  public static LocalDate taxWriteOffCutDate(LocalDate accountingWriteOffDate) {
    if (accountingWriteOffDate == null) {
      return null;
    }
    return accountingWriteOffDate.withDayOfMonth(1).minusDays(1);
  }

  /**
   * Напълно ли е амортизиран активът за СЧЕТОВОДНИ цели — чл. 60 ал. 3 т. 1.
   *
   * <p>За такъв актив ал. 2 НЕ се прилага: той остава в данъчния амортизационен план и се отписва
   * оттам по реда на ал. 1, тоест когато бъде напълно амортизиран и за данъчни цели (ал. 4).
   * Случаят е чест точно когато счетоводният срок е по-къс от данъчния — примерно компютърна
   * техника, изписана счетоводно за 2 години при данъчна норма 50% плюс спиране по чл. 59.
   *
   * <p>Мери се по счетоводния борд, а не по флаг: активът е напълно амортизиран счетоводно, когато
   * няма планов ред с остатъчна стойност, тоест когато счетоводната балансова стойност е нула.
   */
  public static boolean isFullyDepreciatedForAccounting(FixedAsset fixedAsset) {
    if (fixedAsset == null) {
      return false;
    }
    return accountingCarryingValue(fixedAsset).signum() == 0;
  }

  /**
   * Изключен ли е активът от рязането по чл. 60 ал. 2 — по ЦЯЛАТА ал. 3, не само по т. 1.
   *
   * <p>Дословно: „(3) Алинея 2 не се прилага при отписване на активи: 1. … които са напълно
   * амортизирани за счетоводни цели; 2. в резултат на увеличение в стойностния праг на
   * същественост.“
   *
   * <p>Т. 2 се разпознава по връзката към събитието („вдигане на прага“), а не по стойността на
   * актива, и това е разликата, която прави проверката вярна: тригерът в закона е УВЕЛИЧЕНИЕ В
   * ПРАГА, тоест събитие за цялото дружество, а не свойство на актива. Актив, който винаги е бил
   * под прага, не попада тук — той никога не е влизал в ДАП.
   *
   * <p>Функцията е една, защото двете точки имат едно и също следствие (ал. 4: излизане по реда на
   * ал. 1) и защото чл. 59 ал. 4 препраща към цялата ал. 3 наведнъж — вж. {@code
   * BgAssetSuspensionRules#isSuspensionExcluded}.
   */
  /**
   * Напълно ли е амортизиран активът за ДАНЪЧНИ цели.
   *
   * <p>Мери се по данъчната стойност: чл. 53 ал. 4 определя ДБС като ДАС минус начислената данъчна
   * амортизация, а чл. 53 ал. 3 не позволява начисленото да превиши ДАС — тъй че нулева ДБС значи
   * изчерпан план. Това е и условието, при което чл. 60 ал. 1 изважда актива сам.
   */
  public static boolean isFullyTaxDepreciated(FixedAsset fixedAsset) {
    return fixedAsset != null && taxValue(fixedAsset).signum() == 0;
  }

  /**
   * Дължи ли се отписване на ПОРОДЕНИЯ по чл. 64 актив, когато старият се отписва счетоводно.
   *
   * <p><b>чл. 64 ал. 4</b>, дословно: „Когато активът, във връзка с който са извършени последващите
   * разходи, се отпише от счетоводния амортизационен план, <b>преди данъчният амортизируем актив по
   * ал. 1 да е напълно амортизиран</b>, последният се отписва от данъчния амортизационен план при
   * условията и по реда на <b>чл. 60</b>.“
   *
   * <p>⚠️ Условието е „ПРЕДИ да е напълно амортизиран“, тъй че вече изчерпаният план НЕ се пипа —
   * той излиза сам по чл. 60 ал. 1, а второ отписване би му отрязало редове, които вече ги няма.
   *
   * <p>⚠️ И проверява се ДАНЪЧНАТА изчерпаност на ПОРОДЕНИЯ актив, не счетоводната и не тази на
   * стария. Старият тъкмо се отписва счетоводно — това е тригерът, не условието.
   */
  public static boolean requiresArt64Cascade(FixedAsset generatedFixedAsset) {
    if (generatedFixedAsset == null) {
      return false;
    }
    // Присъствието в ДАП се чете през вече съществуващата проверка от чл. 63/64 — един въпрос,
    // един отговор. Актив, който изобщо не е в плана (например под прага по чл. 50/51), няма
    // откъде да се отпише.
    return BgSubsequentCostRules.isInTaxPlan(generatedFixedAsset)
        && !isFullyTaxDepreciated(generatedFixedAsset);
  }

  public static boolean isArt60Al3Excluded(FixedAsset fixedAsset) {
    if (fixedAsset == null) {
      return false;
    }
    return isFullyDepreciatedForAccounting(fixedAsset)
        || fixedAsset.getBgMaterialityIncrease() != null;
  }

  // ------------------------------------------------------------------ стойности

  /**
   * Счетоводната балансова стойност (СБС) към момента на отписване.
   *
   * <p>Взима се от последния РЕАЛИЗИРАН ред на СЧЕТОВОДНИЯ борд, защото именно неговият {@code
   * accountingValue} е отчетна стойност минус НАЧИСЛЕНАТА досега амортизация. При липса на
   * реализирани редове (актив, който още не е амортизиран) СБС е самата отчетна стойност.
   *
   * <p>⚠️ Не се чете {@code FixedAsset.accountingValue}: то се обновява при реализиране на ред и
   * при отписване вече е било намалено от последния (пропорционален) ред, но за актив без нито един
   * реализиран ред остава празно, а генерираният getter на BigDecimal връща ZERO — тоест „още не е
   * амортизиран“ и „изцяло амортизиран“ идват като едно и също число.
   */
  public static BigDecimal accountingCarryingValue(FixedAsset fixedAsset) {
    return carryingValue(
        fixedAsset, fixedAsset == null ? null : fixedAsset.getFixedAssetLineList());
  }

  /**
   * Данъчната стойност (ДБС) към момента на отписване — чл. 53 ал. 4: данъчната амортизируема
   * стойност, намалена с начислената данъчна амортизация.
   *
   * <p>Чете се от ДАНЪЧНИЯ борд ({@code fiscalFixedAssetLineList}), защото ДАС не приспада
   * остатъчна стойност (чл. 53 ал. 1) и затова {@code accountingValue} на данъчния ред вече Е
   * данъчната стойност — виж {@code BgFixedAssetLineTaxComputationServiceImpl}.
   *
   * <p>⚠️ Извиква се СЛЕД като данъчният борд е отрязан по чл. 60 ал. 2, инак ДБС излиза по-малка с
   * една месечна вноска.
   */
  public static BigDecimal taxValue(FixedAsset fixedAsset) {
    return carryingValue(
        fixedAsset, fixedAsset == null ? null : fixedAsset.getFiscalFixedAssetLineList());
  }

  /**
   * Остатъчната стойност по даден борд: {@code accountingValue} на последния РЕАЛИЗИРАН ред, а при
   * борд без реализирани редове — отчетната стойност на актива.
   *
   * <p>⚠️ САМО РЕАЛИЗИРАНИТЕ, И ТОВА НЕ Е ПРИДИРЧИВОСТ. Планираните редове описват БЪДЕЩЕТО и
   * последният от тях по определение е с нулева остатъчна стойност — там планът свършва. Четен
   * заедно с тях, всеки актив изглежда напълно амортизиран още в деня на завеждането си.
   *
   * <p>Пример: машина с 29 реализирани месеца и 11 планирани би излязла със СБС = 0, защото
   * последният ПЛАНОВ ред (2029-04-30) носи нула. Оттам {@link #isFullyDepreciatedForAccounting} би
   * казал „да“, чл. 60 ал. 3 т. 1 би се приложил по погрешка и данъчният борд би останал нерязан —
   * тоест поправката по ал. 2 не би се случила, при зелени тестове.
   *
   * <p>С реализираните въпросът е верният: „колко струва активът СЕГА“, а не „колко ще струва,
   * когато планът приключи“.
   */
  protected static BigDecimal carryingValue(FixedAsset fixedAsset, List<FixedAssetLine> lines) {
    if (fixedAsset == null) {
      return BigDecimal.ZERO;
    }
    FixedAssetLine newest = null;
    if (lines != null) {
      for (FixedAssetLine line : lines) {
        if (line.getDepreciationDate() == null
            || line.getStatusSelect() != FixedAssetLineRepository.STATUS_REALIZED) {
          continue;
        }
        if (newest == null
            || line.getDepreciationDate().isAfter(newest.getDepreciationDate())
            || (line.getDepreciationDate().isEqual(newest.getDepreciationDate())
                && line.getId() != null
                && newest.getId() != null
                && line.getId() > newest.getId())) {
          newest = line;
        }
      }
    }
    return newest == null ? fixedAsset.getGrossValue() : newest.getAccountingValue();
  }

  // ------------------------------------------------------------------ чл. 66

  /**
   * Прилага ли се преобразуването по чл. 66 ал. 1 и 2, или попада в изключенията по ал. 3.
   *
   * <p>Ал. 3 изброява четири случая, и трите първи важат САМО „когато данъчната стойност превишава
   * счетоводната балансова стойност на актива“:
   *
   * <ol>
   *   <li>непризнати разходи от липси на активи и свързани с тях вземания;
   *   <li>отписване за сметка на собствения капитал;
   *   <li>отписване по реда на чл. 60 ал. 6 (активът престава да се ползва за дейност, за която се
   *       формира данъчен финансов резултат);
   *   <li>преобразуване на дружества и преустройство на кооперации по глава деветнадесета, раздели
   *       II и III — <b>без</b> условие за съотношението между двете стойности.
   * </ol>
   *
   * <p>Условието „ДБС превишава СБС“ не е украса: то стеснява изключението до случаите, в които
   * преобразуването би било в полза на данъчно задълженото лице (по-голямо намаление от
   * увеличение). Пропуснато, изключението би отнело и законното намаление.
   */
  public static boolean art66Applies(
      String exceptionSelect, BigDecimal accountingCarryingValue, BigDecimal taxValue) {
    if (exceptionSelect == null || BgArt66Exception.NONE.equals(exceptionSelect)) {
      return true;
    }
    if (BgArt66Exception.REORGANISATION.equals(exceptionSelect)) {
      // ал. 3 т. 4 — безусловно.
      return false;
    }
    BigDecimal sbs = accountingCarryingValue == null ? BigDecimal.ZERO : accountingCarryingValue;
    BigDecimal dbs = taxValue == null ? BigDecimal.ZERO : taxValue;
    // ал. 3 т. 1–3 — само когато данъчната стойност ПРЕВИШАВА счетоводната балансова.
    return dbs.compareTo(sbs) <= 0;
  }

  /**
   * Нетното преобразуване на счетоводния финансов резултат при отписване: {@code +СБС − ДБС}.
   *
   * <p>Чл. 66 ал. 1 увеличава резултата със счетоводната балансова стойност, ал. 2 го намалява с
   * данъчната стойност. Двете са отделни пера в ГДД и се пазят поотделно; тази функция дава само
   * сбора им за сверка. Върната е нула, когато важи изключение по ал. 3.
   */
  public static BigDecimal art66Net(
      String exceptionSelect, BigDecimal accountingCarryingValue, BigDecimal taxValue) {
    if (!art66Applies(exceptionSelect, accountingCarryingValue, taxValue)) {
      return BigDecimal.ZERO;
    }
    BigDecimal sbs = accountingCarryingValue == null ? BigDecimal.ZERO : accountingCarryingValue;
    BigDecimal dbs = taxValue == null ? BigDecimal.ZERO : taxValue;
    return sbs.subtract(dbs);
  }

  // ------------------------------------------------------------------ ЗДДС: чл. 79 / чл. 80

  /**
   * Десетте процента по чл. 80 ал. 2 т. 3 б. „г“ ЗДДС — балансовата стойност под 10 на сто от
   * отчетната.
   *
   * <p>Дословно: „брак на дълготрайни активи, когато балансовата им стойност е по-ниска от 10 на
   * сто от отчетната им стойност“.
   *
   * <p>⚠️ ТОВА Е САМО АРИТМЕТИКАТА, НЕ ЦЯЛОТО ОСНОВАНИЕ. Буква „г“ виси под отварящото изречение на
   * т. 3, а то иска „ДОКАЗАНО ИЛИ ПОТВЪРДЕНО унищожаване, включително изхвърляне на стоки по начин,
   * който води до необратимото им изчезване“. Тоест изпълнените 10 процента НЕ освобождават сами —
   * иска се и документ за унищожаването. Затова тази функция само мери числото, а решението минава
   * през {@link #mayReleaseFromVatCorrection}.
   *
   * <p>Строго „по-ниска“: равното на 10 на сто не освобождава.
   */
  public static boolean isBelowTenPercentOfGross(
      BigDecimal accountingCarryingValue, BigDecimal grossValue) {
    if (grossValue == null || grossValue.signum() == 0) {
      return false;
    }
    BigDecimal sbs = accountingCarryingValue == null ? BigDecimal.ZERO : accountingCarryingValue;
    BigDecimal threshold = grossValue.multiply(new BigDecimal("10")).divide(new BigDecimal("100"));
    return sbs.compareTo(threshold) < 0;
  }

  /**
   * Изпълнено ли е ОБЕКТИВНОТО условие за освобождаване от корекция — това, което системата може да
   * провери сама.
   *
   * <p>Две са проверимите: непреодолимата сила (тя идва от избраната причина, не от преценка) и
   * десетте процента по б. „г“ (чисто число). Останалите основания по чл. 80 ал. 2 — технологичен
   * брак в допустимите норми, изтекъл срок на годност, обективна неизползваемост от обичайна
   * употреба — са преценки и документи, които този слой не вижда, и затова НЕ се предполагат.
   */
  public static boolean isObjectiveVatReleaseConditionMet(
      String vatGroundSelect, BigDecimal accountingCarryingValue, BigDecimal grossValue) {
    if (BgAssetRemoval.VatGround.ART80_2_1_A.equals(vatGroundSelect)) {
      return true;
    }
    return isBelowTenPercentOfGross(accountingCarryingValue, grossValue);
  }

  /**
   * Може ли отписването да се обяви за НЕподлежащо на корекция по чл. 79 ЗДДС.
   *
   * <p><b>Двете условия са едновременни, и това е нарочно.</b> Системата никога не сваля сама на
   * „не подлежи“; съставителят може, но само когато:
   *
   * <ol>
   *   <li>обективното условие е изпълнено — непреодолима сила по избраната причина ИЛИ балансова
   *       стойност под 10 на сто от отчетната (чл. 80 ал. 2 т. 3 б. „г“); И
   *   <li>е обявено ДОКАЗАНО ИЛИ ПОТВЪРДЕНО унищожаване И е посочен документът, който го доказва.
   * </ol>
   *
   * <p><b>Защо толкова строго.</b> Посоката на грешката не е симетрична. Обявено „не подлежи“,
   * когато корекция се дължи, е СКРИТ ДАНЪЧЕН ПАСИВ — не се вижда никъде, докато не дойде ревизия.
   * Обратното — начислена корекция, която не се дължи — стои на видно място в дневника и се сваля с
   * една поправка. Затова освобождаването иска доказателство, а начисляването е подразбиране.
   *
   * <p>Практическото следствие: актив с обичайно износване и балансова стойност 25% от отчетната НЕ
   * може да бъде освободен по погрешка, дори съставителят да отметне доказаното унищожаване —
   * обективното условие не е изпълнено и б. „в“ иска преценка, която не се приема на доверие.
   */
  public static boolean mayReleaseFromVatCorrection(
      boolean objectiveConditionMet, boolean destructionProven, boolean hasDocumentReference) {
    return objectiveConditionMet && destructionProven && hasDocumentReference;
  }
}
