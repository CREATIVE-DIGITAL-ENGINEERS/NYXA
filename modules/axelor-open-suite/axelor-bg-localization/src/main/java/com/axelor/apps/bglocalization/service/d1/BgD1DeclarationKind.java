package com.axelor.apps.bglocalization.service.d1;

import com.axelor.apps.base.db.Period;
import com.axelor.apps.bglocalization.db.BgD1Declaration;

/**
 * ВИДЪТ НА ДЕКЛАРАЦИЯ ОБР. 1 — редовна или коригираща. Чиста функция: без база, без Guice.
 *
 * <p><b>ЗАЩО СЪЩЕСТВУВА.</b> Коригиращият фиш носи СЪЩИЯ период като оригинала ({@code
 * BgPaySlipService#retroCopyOf}), а изборът на фишове пита точно периода. Без вид всяка декларация
 * за онзи месец взима и двата фиша и произвежда файл с редовен И коригиращ запис за едно лице.
 *
 * <p><b>⚠️ РАЗГРАНИЧИТЕЛЯТ Е ВИДЪТ НА ДЕКЛАРАЦИЯТА, А НЕ СЪСТАВЪТ НА НАБОРА.</b> Отказ върху
 * СМЕСВАНЕТО би затворил единствения изход, който сам сочи: отделна коригираща декларация не може
 * да се направи, защото оригиналът не сменя статуса си и няма вид.
 *
 * <p><b>⚠️ И МОДЕЛЪТ Е ВЕРЕН НЕЗАВИСИМО ОТ ПРАВИЛОТО ЗА СМЕСВАНЕТО.</b> Правилото „в един файл не
 * се смесват код 0 и код 1 за същото лице“ идва от спецификацията на НАП за входните файлове от
 * 2015 г. (EMPL2015.TXT, при Н-8); текущата по Н-13 не е налична. Тук то НЕ се ползва като
 * предпоставка: коригиращата не съдържа редовни записи, а редовната — записи с код. Каквото и да
 * казва бъдещата спецификация, разделянето остава допустимо. {@code
 * BgD1CorrectionRules#refuseMixedCodes} си остава НАХОДКА и не се пипа.
 *
 * <p><b>⚠️ КОЯ ДЕКЛАРАЦИЯ НОСИ КОРЕКЦИЯТА, РЕШАВА ТОВА ДАЛИ НАП ДЪРЖИ РЕДОВНАТА, а не признакът на
 * фиша.</b> Корекция се отваря в ЗАТВОРЕН период ({@code BgPaySlipResolver#refuseRetroPeriod}), а
 * затварянето е ПРЕДИ подаването — тоест има прозорец, в който копието съществува, а Д1 още не е
 * подадена. Тогава то е просто ДЕЙСТВАЩИЯТ фиш и влиза в редовната като обикновен запис (без „К“):
 * НАП никога не е виждала стария. Щом НАП държи редовната, тя не се генерира наново ({@code
 * BgD1RegenerationRules}) и корекцията минава през коригиращата. Двете врати се допълват: {@link
 * #refuseCorrectingBeforeAccepted} пуска коригиращата точно когато историята спира редовната.
 * Разделянето по признак („редовната — без ретро, коригиращата — само ретро“) е вярно само за
 * втория случай; в първия дава Д1 с оригинала и Д6 с двата фиша.
 *
 * <p><b>⚠️ И ЗАЩО КОРЕКЦИЯТА Е САМО ЗА ЗАСЕГНАТИТЕ ЛИЦА.</b> Декларация обр. 1 е декларация за ЕДНО
 * ЛИЦЕ за ЕДИН МЕСЕЦ (Н-13, чл. 9 ал. 1), тоест „коригирам месеца“ не съществува като действие —
 * съществува „коригирам записа на това лице“. Коригиращата носи ретро-фишовете и нищо друго.
 */
public final class BgD1DeclarationKind {

  /**
   * Редовната декларация — носи ДЕЙСТВАЩИЯ фиш на всяко лице ({@code
   * BgEffectivePaySlips#effectiveFor}), включително корекция, направена преди подаването.
   */
  public static final String REGULAR = "REGULAR";

  /**
   * Коригиращата — носи САМО ретро-фишовете (коригиращи и заличаващи копия), които редовната още не
   * носи ({@code BgEffectivePaySlips#correctingFor}), и само когато НАП държи редовната.
   */
  public static final String CORRECTING = "CORRECTING";

  /**
   * Допълнителната — НОВИ РЕДОВЕ (без код корекция) за месец, чиято редовна НАП вече държи. Днес
   * носи само частите на обезщетение по чл. 222 ал. 1 КТ ({@link BgCompensationParts}), изплатено
   * след като Д1 за месеца на частта е подадена: това не е корекция на подаден запис, а запис,
   * който НАП още не е виждала.
   */
  public static final String SUPPLEMENTARY = "SUPPLEMENTARY";

  private BgD1DeclarationKind() {}

  /**
   * ВИДЪТ НА ЕДНА ДЕКЛАРАЦИЯ, С ЛИПСАТА ПРОЧЕТЕНА КАТО „РЕДОВНА“.
   *
   * <p><b>⚠️ ТОЗИ МЕТОД Е ЦЯЛАТА МИГРАЦИЯ — и точно КЪДЕ живее подразбирането е измерено.</b>
   * {@code default="REGULAR"} се превежда в ИНИЦИАЛИЗАТОР НА ПОЛЕТО на генерирания клас ({@code
   * private String bgDeclarationKind = "REGULAR"}), а НЕ в getter-а: той връща полето както е.
   * Тоест всеки НОВ обект носи вида от само себе си, но ред, записан ПРЕДИ колоната да съществува,
   * носи NULL в базата и се зарежда с NULL — инициализаторът не е минавал през него. Прочетено
   * наивно, такава декларация би излязла от ВСЕКИ филтър по вид и би спряла да носи фишове
   * мълчаливо. Затова липсата се чете тук, на ЕДНО място, а backfill НЯМА: колоната описва какво
   * декларацията Е БИЛА, а всяка заварена е била редовна по определение — друга не е могла да се
   * направи.
   *
   * <p>⚠️ И празният низ се чете като липса: {@code required="true"} на колоната не пази от низ от
   * интервали, дошъл при внос.
   */
  public static String of(BgD1Declaration declaration) {
    String kind = declaration == null ? null : declaration.getBgDeclarationKind();
    if (kind == null || kind.trim().isEmpty()) {
      return REGULAR;
    }
    return kind.trim();
  }

  public static boolean isCorrecting(BgD1Declaration declaration) {
    return CORRECTING.equals(of(declaration));
  }

  /** Допълнителна ли е — виж {@link #SUPPLEMENTARY}. */
  public static boolean isSupplementary(BgD1Declaration declaration) {
    return SUPPLEMENTARY.equals(of(declaration));
  }

  // ═══ ОТКАЗИТЕ ════════════════════════════════════════════════════════════

  /**
   * КОРИГИРАЩАТА СОЧИ РЕДОВНАТА, КОЯТО ПОПРАВЯ — иначе отказ.
   *
   * <p><b>Три условия, и всяко се проверява поотделно, защото поправките им са различни:</b> има ли
   * посочена декларация, редовна ли е тя, и за същия период и същата фирма ли е. Слети в едно
   * съобщение („препратката е невалидна“), операторът не знае кое от трите да поправи.
   *
   * <p>⚠️ Полето {@code correctsPrevious} съществуваше като „проследимост, не поведение“ и нямаше
   * нито един читател. Тук става ПРЕДУСЛОВИЕ: коригираща, която сочи чужд месец или чужда фирма,
   * поправя запис, който НАП не свързва с нея.
   */
  public static String refuseCorrectingTarget(BgD1Declaration declaration) {
    if (declaration == null || !isCorrecting(declaration)) {
      return null;
    }
    BgD1Declaration target = declaration.getCorrectsPrevious();
    if (target == null) {
      return "Коригиращата декларация не сочи коя РЕДОВНА декларация поправя (поле „Коригира"
          + " декларация“). Без нея не се знае кой подаден запис се замества — а по чл. 9 ал. 4"
          + " корекция без приета преди това декларация е твърдение за нещо, което НАП не познава.";
    }
    if (isCorrecting(target)) {
      return "Полето „Коригира декларация“ сочи ДРУГА КОРИГИРАЩА декларация. Коригира се РЕДОВНАТА"
          + " — онази, чиито записи са подадени. Верига от корекции, всяка сочеща предишната, не"
          + " казва кой е първоначалният запис.";
    }
    String period =
        refuseDifferent(
            "периода на данните",
            nameOf(declaration.getBgDataPeriod()),
            nameOf(target.getBgDataPeriod()));
    if (period != null) {
      return period;
    }
    return refuseDifferent(
        "дружеството",
        declaration.getCompany() == null ? null : declaration.getCompany().getName(),
        target.getCompany() == null ? null : target.getCompany().getName());
  }

  /**
   * КОРИГИРАЩАТА ЧАКА, ДОКАТО НАП ДЪРЖИ РЕДОВНАТА — иначе отказ.
   *
   * <p>По чл. 9 ал. 4 корекция се подава СЛЕД приемането на декларацията. Докато редовната не е
   * приета, корекцията не е корекция: копието е ДЕЙСТВАЩИЯТ фиш и влиза в редовната като обикновен
   * запис. Коригираща Д1 тогава би подала „К“ на запис, който НАП не познава — и същият фиш би
   * стигнал до НАП два пъти.
   *
   * @param historyStatus статусът от историята на подаванията, при който НАП държи данните ({@code
   *     BgD1RegenerationRules#HISTORY_BLOCKING_STATUSES}), или {@code null}
   */
  public static String refuseCorrectingBeforeAccepted(
      BgD1Declaration declaration, String historyStatus) {
    if (declaration == null || !isCorrecting(declaration)) {
      return null;
    }
    if (historyStatus != null
        && BgD1RegenerationRules.HISTORY_BLOCKING_STATUSES.contains(historyStatus.trim())) {
      return null;
    }
    String period = nameOf(declaration.getBgDataPeriod());
    return "Коригиращата декларация за „"
        + (period == null ? "(без период)" : period)
        + "“ не се генерира: НАП още не държи РЕДОВНАТА за този период (няма прието подаване)."
        + " Корекцията вече е ДЕЙСТВАЩИЯТ фиш — генерирайте наново РЕДОВНАТА Д1 и тя ще я носи като"
        + " обикновен запис. Коригираща се прави след като редовната е приета (чл. 9 ал. 4).";
  }

  private static String refuseDifferent(String what, String mine, String theirs) {
    String a = mine == null ? "(празно)" : mine;
    String b = theirs == null ? "(празно)" : theirs;
    if (a.equals(b)) {
      return null;
    }
    return "Коригиращата декларация и онази, която поправя, се разминават по "
        + what
        + ": „"
        + a
        + "“ срещу „"
        + b
        + "“. Коригира се записът за СЪЩИЯ месец и СЪЩОТО задължено лице — по тях НАП намира"
        + " предишната декларация (чл. 9 ал. 1 т. 1). Разминати, корекцията не поправя нищо, а"
        + " създава втори запис.";
  }

  private static String nameOf(Period period) {
    return period == null ? null : period.getName();
  }
}
