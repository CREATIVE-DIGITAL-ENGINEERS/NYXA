  /**
   * Наборът факти, или отказът — трето състояние до „ето факти“ и „без пропорция“.
   *
   * <p>Отделен тип, а не {@code null}: {@code null} е точно мълчанието, което този клас гони.
   * Образецът е {@code BgInsurableIncomeService.Proration} — или сума, или причина защо няма.
   */
  public static final class Decision {

    /** Наборът факти за {@code BgInsurableIncomeService}, или {@code null} при отказ. */
    public final BgWorkTimeFacts facts;

    /** Причината за отказ, или {@code null}. Изречение за човек, не код за грешка. */
    public final String refusal;

    /** Режимът, по който е взето решението — за диагностика и за проследимост. */
    public final Regime regime;

    /**
     * Допускането, приложено за да се стигне до режима, или {@code null}.
     *
     * <p>⚠️ НОСИ СЕ В РЕШЕНИЕТО, а не се губи в {@link #regimeOf}. Допускане, което не стига до
     * изхода, е подразбиране — човекът пред екрана вижда число и няма как да разбере, че част от
     * него е нечий разумен прочит на липсваща стойност.
     */
    public final String assumption;

    private Decision(BgWorkTimeFacts facts, String refusal, Regime regime, String assumption) {
      this.facts = facts;
      this.refusal = refusal;
      this.regime = regime;
      this.assumption = assumption;
    }

    public boolean isRefused() {
      return refusal != null;
    }

    public boolean isAssumed() {
      return assumption != null;
    }

    /**
     * СПИРА ли отказът сметката — единственият въпрос, който повикващият има право да задава.
     *
     * <p><b>Отказът е УСЛОВЕН, а не безусловен.</b> Той пази ЕДИН избор: кой ред по НЕВД чл. 1 важи
     * — ал. 4 (часове) при непълно работно време или ал. 3 (дни) при пълно. Този избор изобщо не се
     * прави за вид осигурен с {@code bgZeroWorkTime}: там {@code BgInsurableIncomeService} получава
     * {@code prorates = false} и прагът се дължи ЦЯЛ, тоест работното време не влиза в сметката с
     * нито едно число. Отказ заради вход, от който резултатът не зависи, не пази нищо — само
     * блокира.
     *
     * <p>⚠️ ЗАТОВА {@link #isRefused()} НЕ СЕ ЧЕТЕ ГОЛ — нито в {@code
     * BgPaySlipService.contributions}, нито в {@code BgContributionPreviewController}. Иначе фиш на
     * морско лице (код 92) би се отказал заради непопълнено {@code
     * EmploymentContract.bgHoursPerDay} — при вид, чийто праг не се пропорционира.
     *
     * <p>⚠️ ОБРАТНАТА ПОСОКА Е ДРУГА. При {@code proratesWithWorkTime = true} — тоест за всяко
     * трудово правоотношение — липсващият режим си е валиден отказ и трябва да спира: двата реда по
     * чл. 1 дават РАЗЛИЧНО число за един и същ месец, и избор по подразбиране е праг наужким.
     *
     * @param proratesWithWorkTime отговорът на {@code
     *     BgInsurableIncomeService.proratesWithWorkTime} — СЪЩИЯТ прочит, с който резолверът после
     *     ще смята. Не се извежда тук: два източника за един факт са свободни да се разминат.
     */
    public boolean blocks(boolean proratesWithWorkTime) {
      return proratesWithWorkTime && isRefused();
    }

    /**
     * Фактите, с които да се смята — {@link #facts}, а при непропорциониращ вид пълен месец.
     *
     * <p>⚠️ НЕ Е ДОПУСКАНЕ. При {@code proratesWithWorkTime = false} наборът факти НЕ СЕ ЧЕТЕ от
     * нито един ред: {@code BgInsurableIncomeService.applyFloor} връща месечния праг цял, преди да
     * погледне фактите, а таванът не се пропорционира никога. Стойността тук е несчупваема замяна
     * на {@code null} при отказ, не прочит на липсващо работно време — затова и не е обявена като
     * допускане в {@link #describe}.
     */
    public BgWorkTimeFacts factsFor(boolean proratesWithWorkTime) {
      if (!proratesWithWorkTime) {
        return BgWorkTimeFacts.fullMonth();
      }
      return facts;
    }
  }

  /**
   * Кой ред по НЕВД чл. 1 важи, и с какви числа.
   *
   * <p>Редът на въпросите е по НОРМАТА, не по наличността на данни:
   *
   * <ol>
   *   <li><b>Режимът</b> — свойство на ДОГОВОРА. Не се знае → ОТКАЗ. Пита се първо, защото решава
   *       кой ред важи, а двата реда дават различно число за един и същ месец.
   *   <li><b>Знаменателят</b> — работните дни в периода. Липсва → БЕЗ пропорция, с обявена причина
   *       (непокрита календарна година). Тук не се отказва: без знаменател нито един от двата реда
   *       не е приложим, тоест въпросът вече не е „кой ред“, а „изобщо няма аритметика“. Заварената
   *       проверка {@code BgPaySlipService.calendarRefusal} отказва точно този случай при
   *       потвърждаване на фиша.
   *   <li><b>НЕПЪЛНО</b> → ал. 4, по ОТРАБОТЕНИ ЧАСОВЕ. Липсват → ОТКАЗ, а не падане към ал. 3:
   *       последното изречение на ал. 4 казва, че часовият ред важи и при неотработени дни.
   *   <li><b>ПЪЛНО</b> → ал. 3, по ОТРАБОТЕНИ ДНИ. Липсват → БЕЗ пропорция. Това НЕ е подразбиране,
   *       а прочит на нормата: ал. 3 се прилага „за лицата, които НЕ СА отработили всичките дни“,
   *       тоест щом неотработване не се твърди, прагът важи цял.
   * </ol>
   *
   * <p><b>Числата, заради които редът има значение.</b> Пълно работно време, 176 отчетени часа при
   * 168 законоустановени и 10 отработени от 21 работни дни: по ал. 3 коефициентът е 10/21 = 0,4762
   * и прагът 550,66 става 262,22. Първата версия избираше часовия ред, защото часови данни ИМАШЕ:
   * 176/168 = 1,0476, ограничено до 1, тоест праг 550,66 — цял, при десет отработени дни от двайсет
   * и един. Завишение от 288,44 евро, и то без нито един червен ред.
   */
  public static Decision decide(BgPayrollInput input) {
    return decide(input, null);
  }

  /**
   * Същото решение, но С ДНИТЕ ПО ЧЛ. 40 АЛ. 5 КСО В ЧИСЛИТЕЛЯ — вратата на ФИША.
   *
   * <p><b>⚠️ ЗАЩО ВТОРА ВРАТА, А НЕ РАЗШИРЕН ПОДПИС.</b> Едноарговият {@link
   * #decide(BgPayrollInput)} остава непокътнат и продължава да е верният вход за {@code
   * BgContributionPreviewController} — диагностичният екран сглобява вход за ПРОИЗВОЛЕН договор и
   * фиш не вижда, тоест няма откъде да знае разделението. Разширен на място, подписът щеше да
   * поиска промяна на всеки заварен повикващ и на всеки тест, който го вика, за факт, който
   * половината от тях не притежават.
   *
   * <p><b>⚠️ ЧИСЛОТО СЕ ПОДАВА, А НЕ СЕ ИЗВЕЖДА — и това е същият довод, по който го чете и {@code
   * BgD1DaySource}.</b> Разделянето на епизодите на „за сметка на осигурителя“ и „за сметка на ДОО“
   * е правило на {@code BgSickLeaveResolver#split}: то иска осигурителен стаж, производствен
   * календар и правото по вида отсъствие, и вече е СМЕТНАТО и ЗАМРАЗЕНО на фиша като {@code
   * BgPaySlip.bgSickDaysEmployer}. Изведено втори път тук от {@code
   * BgPayrollInput.sickLeaveEpisodes}, то щеше да е втора сметка на едно число — и коригиращият фиш
   * за минал месец щеше да го сметне по ДНЕШНИТЕ правила.
   *
   * <p><b>⚠️ РЕДЪТ Е ЧАСТ ОТ ДОГОВОРА НА ТАЗИ ВРАТА.</b> Числото е налично само СЛЕД {@code
   * BgPaySlipService#generateSickLeave}, който го записва на фиша, и точно затова {@code
   * generateContributions} се вика след него. Извикана по-рано, вратата щеше да получи нулата на
   * непопълнено поле и да се държи точно като едноарговата — тихо.
   *
   * <p><b>Числата, заради които числителят има значение.</b> Пълно работно време, 21 работни дни, 9
   * отработени и болничен с 2 дни за сметка на осигурителя: без числителя коефициентът е 9/21 =
   * 0,4285714286, с него — 11/21 = 0,5238095238. При МОД 1077,00 прагът е 461,57 срещу 564,14,
   * тоест 102,57 евро по-нисък праг, по-ниска осигурителна база и по-ниски вноски. Занижаването е
   * тихо: и двете числа изглеждат пресметнати. Заковано е в {@code BgArt40Par5NumeratorTest}.
   *
   * @param art40Par5Days РАБОТНИ ДНИ за сметка на осигурителя по чл. 40 ал. 5 КСО, паднали в
   *     периода — тоест {@code BgPaySlip.bgSickDaysEmployer}. ⚠️ Нула и {@code null} се четат
   *     ЕДНАКВО и нарочно: генерираният getter за {@code Integer} връща 0 за непопълнена колона
   *     ({@code BgDefaultedGetterTest}), тоест „няма болничен“ и „не е пипано“ са неразличими на
   *     ЗАПИС. И двете дават обявена липса, тоест фиш БЕЗ болничен минава през този вход с изход,
   *     идентичен на едноарговия — включително диагностичното изречение.
   */
  public static Decision decide(BgPayrollInput input, Integer art40Par5Days) {
    if (input == null) {
      return refused(refuse("noInput"), Regime.UNKNOWN, null);
    }

    RegimeReading reading = readRegime(input);
    Regime regime = reading.regime;
    String assumption = reading.assumption;
    if (regime == Regime.UNKNOWN) {
      return refused(refuse("unknownRegime"), regime, assumption);
    }

    if (input.workingDaysInPeriod == null) {
      // Обявена липса, не подразбиране: причината се изписва от describe(...).
      return of(BgWorkTimeFacts.fullMonth(), regime, assumption);
    }
    BigDecimal workingDays = new BigDecimal(input.workingDaysInPeriod);

    if (regime == Regime.PART) {
      if (input.workedHours == null) {
        return refused(refuse("partTimeWithoutHours"), regime, assumption);
      }
      return of(
          BgWorkTimeFacts.byHours(
              STATUTORY_DAILY_HOURS.multiply(workingDays),
              input.workedHours,
              notSupplied("art40Par5Hours")),
          regime,
          assumption);
    }

    if (input.workedDays == null) {
      return of(BgWorkTimeFacts.fullMonth(), regime, assumption);
    }
    return of(
        BgWorkTimeFacts.byDays(
            workingDays, new BigDecimal(input.workedDays), art40Par5DaysOf(art40Par5Days)),
        regime,
        assumption);
  }

  /**
   * Дните по чл. 40 ал. 5 КСО за числителя — числото, или ОБЯВЕНА ЛИПСА.
   *
   * <p>⚠️ Прагът е {@code > 0}, а не {@code != null}: нулата на непопълнено {@code Integer} поле не
   * е твърдение (виж {@code BgDefaultedGetterTest}), а подадена като {@code ZERO} тя щеше да смени
   * диагностичното изречение на всеки фиш БЕЗ болничен, без да смени нито едно число. Тоест гейтът
   * пази точно изискването „нормален фиш — идентичен изход“, и го пази ВИДИМО, а не по случайност:
   * {@code nz(...)} в {@code BgInsurableIncomeService.prorate} и без това чете нулата и {@code
   * null} еднакво.
   */
  private static BigDecimal art40Par5DaysOf(Integer days) {
    if (days == null || days <= 0) {
      return notSupplied("art40Par5Days");
    }
    return new BigDecimal(days);
  }

  // ═══ ИЗРЕЧЕНИЕТО ЗА ЧОВЕК ════════════════════════════════════════════════

  /**
   * Кое правило се е приложило, с какви числа — или защо е отказано.
   *
   * <p>Диагностичната форма показва входовете, които сама е избрала, за да може странно число да се
   * проследи до грешен вход, а не до грешна сметка. Пропорцията е точно такъв вход: без този ред
   * „осигурителна база 262,22“ не се различава от „осигурителна база 550,66“ по нищо видимо.
   */
  /**
   * Пропорцията, ОБЯСНЕНА СПРЯМО ВИДА ОСИГУРЕН — за екрана, който показва и двете страни.
   *
   * <p>⚠️ Отказът НЕ СЕ КРИЕ, когато не блокира. При {@code bgZeroWorkTime} диагностиката пак
   * трябва да каже, че режимът е неразпознат (тоест {@code bgHoursPerDay} стои непопълнено по
   * договора) — само че вече като БЕЛЕЖКА, а не като спряла сметка. Замяна на текста с „няма
   * пропорция“ би скрила една истинска липса в данните зад един верен резултат.
   */
  public static String describe(Decision decision, boolean proratesWithWorkTime) {
    if (proratesWithWorkTime) {
      return describe(decision);
    }
    String note =
        decision != null && decision.isRefused()
            ? " ⚠️ Режимът остава неразпознат и това е записано, а не скрито: " + decision.refusal
            : "";
    return "НЕПРИЛОЖИМА — видът осигурен е с bgZeroWorkTime, тоест правоотношението няма работно"
        + " време, на което прагът да е част: дължи се ЦЯЛ и НЕВД чл. 1 не се прилага с нито едно"
        + " число."
        + note;
  }

  public static String describe(Decision decision) {
    if (decision == null) {
      return "няма решение за работното време — без пропорция";
    }
    // ⚠️ Допускането се показва ПРЕДИ резултата и при отказ, и при факти: то е част от начина, по
    // който се е стигнало до тях, а не бележка под линия.
    String assumed = decision.isAssumed() ? "⚠️ ДОПУСКАНЕ: " + decision.assumption + "\n" : "";
    if (decision.isRefused()) {
      return assumed + "ОТКАЗ: " + decision.refusal;
    }
    BgWorkTimeFacts facts = decision.facts;
    if (facts.hasHourData()) {
      return assumed
          + "НЕВД чл. 1 ал. 4 (ЧАСОВЕ, непълно работно време): отработени "
          + text(facts.getWorkedHours())
          + " от законоустановени "
          + text(facts.getStatutoryMonthlyHours())
          + " за месеца";
    }
    if (facts.hasDayData()) {
      // ⚠️ ЧИСЛИТЕЛЯТ СЕ ИЗПИСВА ЦЯЛ, КОГАТО НЕ Е САМО ОТРАБОТЕНОТО. „Отработени 9 от 21“ при
      // коефициент 11/21 би лъгало за собствения си вход точно на болничния месец, и то по начин,
      // който изглежда като грешна СМЕТКА, а не като недоизписан числител. Виж довода в описанието
      // на BgWorkTimeFacts: странно число трябва да се проследява до входа си.
      // ⚠️ Клаузата се появява само при подадени дни, тоест фиш БЕЗ болничен получава текста без
      // нея, буква по буква.
      BigDecimal art40 = facts.getArt40Par5Days();
      String art40Clause =
          art40 == null || art40.signum() <= 0
              ? ""
              : " + " + text(art40) + " дни по чл. 40 ал. 5 КСО за сметка на осигурителя";
      return assumed
          + "НЕВД чл. 1 ал. 3 (ДНИ, пълно работно време): отработени "
          + text(facts.getWorkedDays())
          + art40Clause
          + " от "
          + text(facts.getWorkingDaysInMonth())
          + " работни дни в периода";
    }
    return assumed
        + "БЕЗ пропорция — прагът важи за цял месец. Режим: "
        + decision.regime
        + ". ⚠️ Причината е обявена, не подразбиране: или липсва знаменател (непокрита календарна"
        + " година, тоест работните дни в периода не са надеждни), или при ПЪЛНО работно време няма"
        + " отчет за отработени дни — а ал. 3 се прилага само при НЕотработени всички дни, тоест"
        + " цял праг е отговорът по норма.";
  }

  private static String text(BigDecimal value) {
    return value != null ? value.toPlainString() : "(няма)";
  }

  private static Decision of(BgWorkTimeFacts facts, Regime regime, String assumption) {
    return new Decision(facts, null, regime, assumption);
  }

  private static Decision refused(String reason, Regime regime, String assumption) {
    return new Decision(null, reason, regime, assumption);
  }

  // ═══ ОБЯВЯВАНЕТО НА ЛИПСА ════════════════════════════════════════════════

  /**
   * НЕ СЕ ПОДАВА, с обявена причина — връща {@code null} и пада, ако причината не е записана.
   *
   * <p>Същият механизъм като {@code BgPayrollInputBuilder.absent}: носачът на твърдението е поле, а
   * не изречение, и премълчаването е невъзможно, защото {@code null} тук минава само през този
   * метод.
   */
  static BigDecimal notSupplied(String argument) {
    if (!NOT_SUPPLIED.containsKey(argument)) {
      throw new IllegalStateException(
          "аргументът „"
              + argument
              + "“ се обявява за неподаден, но не е в BgPayrollWorkTime.NOT_SUPPLIED. Обявена липса"
              + " без ПРИЧИНА е криене на грешка.");
    }
    return null;
  }

  /**
   * ОТКАЗ с обявена причина — същият механизъм, върху {@link #REFUSALS}.
   *
   * <p>Текстът на отказа е ПРИЧИНАТА от списъка, а не свободно изречение на мястото на извикването:
   * така един отказ има един текст и той се сверява в двете посоки от тест, вместо да се преписва.
   */
  /**
   * ОБЯВЕНО ДОПУСКАНЕ — връща ПРИЧИНАТА от {@link #ASSUMPTIONS} и пада, ако не е записана.
   *
   * <p>Същият механизъм като {@link #refuse} и {@link #notSupplied}: причината живее на едно място
   * и се сверява в двете посоки, вместо да се преписва на мястото на употребата.
   */
  static String assume(String field) {
    String reason = ASSUMPTIONS.get(field);
    if (reason == null) {
      throw new IllegalStateException(
          "допускането за „"
              + field
              + "“ не е в BgPayrollWorkTime.ASSUMPTIONS. Допускане без ПРИЧИНА е точно мълчаливото"
              + " подразбиране, което списъкът съществува да замени.");
    }
    return reason;
  }

  static String refuse(String code) {
    String reason = REFUSALS.get(code);
    if (reason == null) {
      throw new IllegalStateException(
          "отказът „"
              + code
              + "“ не е в BgPayrollWorkTime.REFUSALS. Отказ без ПРИЧИНА е точно толкова тих, колкото"
              + " и мълчаливото подразбиране, което той съществува да замени.");
    }
    return reason;
  }
