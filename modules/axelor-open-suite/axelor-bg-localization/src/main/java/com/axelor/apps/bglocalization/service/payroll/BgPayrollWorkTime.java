  /** Режимът на работното време по КТ — и трите състояния, включително „не знам“. */
  public enum Regime {
    /** Пълно работно време: договорената дневна продължителност е законоустановената. */
    FULL,
    /** Непълно работно време по чл. 138 КТ: договорената дневна продължителност е под нормата. */
    PART,
    /** Не се знае. НЕ е нито едно от горните и не се свежда до тях. */
    UNKNOWN
  }

  /**
   * Режимът, прочетен от УСЛОВИЕТО НА ТРУДОВИЯ ДОГОВОР за работно време.
   *
   * <p>Ал. 4 казва „съгласно условията на трудовия договор или чл. 138, ал. 2 от Кодекса на труда
   * лицето е работило при непълно работно време“. Условието на трудовия договор за работно време е
   * договорената дневна продължителност, тоест {@link BgPayrollInput#contractHoursPerDay}. Тя е и в
   * СЪЩАТА единица като {@link #STATUTORY_DAILY_HOURS}, тоест сравнението е едно и без
   * преобразувания.
   *
   * <p><b>⚠️ ЗАЩО НЕ {@code workTimeMode} — И ТОВА НЕ Е ПРЕДПОЧИТАНИЕ, А ПРОЧЕТЕНО ОТ ДОМЕЙНА.</b>
   * Селекцията {@code bg.work.time.mode.select} носи точно две стойности: {@code 1} „Подневно
   * отчитане“ и {@code 2} „Сумирано изчисляване (СИРВ)“. Това е чл. 142 КТ — режимът на ОТЧИТАНЕ, —
   * а ал. 4 пита за чл. 138 ал. 2 КТ, тоест за НЕПЪЛНО РАБОТНО ВРЕМЕ. Двете са ортогонални: договор
   * на непълно работно време може да е и подневен, и сумиран. Нито една от двете стойности не се
   * съпоставя с „пълно“ или „непълно“, тоест полето не може да бъде дискриминаторът — то би
   * отговаряло на друг въпрос и щеше да го прави правдоподобно.
   *
   * <p>Това не е проза: {@code BgWorkTimeRegimeTest} чете селекцията ОТ ДОМЕЙНА и заковава, че нито
   * една от стойностите ѝ не носи признака. Добави ли някой стойност „непълно работно време“ в тази
   * селекция, тестът става червен и авторът трябва да реши дали полето вече е дискриминатор.
   *
   * <p><b>⚠️ И НАМАЛЕНИЯТ БРОЙ ДНИ (чл. 138 ал. 1 КТ) СЕ РАЗПОЗНАВА.</b> Непълното работно време
   * може да е с намален брой часове ИЛИ с намален брой дни, тоест договор от 8 часа на ден и 3 дни
   * на седмица е непълно работно време, макар часовете на ден да са пълните. Оттам и {@link
   * BgPayrollInput#contractDaysPerWeek} влезе в контракта: без него този режим НЕ Е ИЗРАЗИМ.
   *
   * <p><b>⚠️ И РАЗЛИКАТА НЕ Е В ЧИСЛОТО, А В ПЪТЯ НА „НЕ ЗНАМ“ — заради това не беше безобидно.</b>
   * При 8 часа на ден отработените часове са точно 8 × отработените дни, а делителят е 8 ×
   * работните дни, тоест часовият и дневният коефициент са ЕДНО И СЪЩО число: СЪС отчет поправката
   * не мени нито едно число, и това е заковано с тест. БЕЗ отчет обаче двата режима се разминават —
   * пълното работно време получава цял праг (ал. 3 важи само при неотработени всички дни), а
   * непълното ОТКАЗ (ал. 4 иска часове винаги). Тоест без дните на седмица договор 8 × 3 без отчет
   * би получил цял праг там, където нормата иска отказ.
   *
   * <p>Липсващите дни на седмица НЕ водят до отказ: прилага се ОБЯВЕНО ДОПУСКАНЕ за пълна седмица
   * от {@link #ASSUMPTIONS}, и то се вижда в {@link #describe}. Причината е в самия запис — почти
   * всеки договор е пететдневен и отказ при всяко непопълнено поле щеше да е червено, което стои.
   *
   * <p>Над нормата ({@code > 8}) НЕ е незнание и НЕ е непълно работно време: при сумирано
   * изчисляване дневната продължителност законно стига до 12 часа (чл. 136а КТ). Такъв договор е
   * ПЪЛЕН.
   */
  public static Regime regimeOf(BgPayrollInput input) {
    return readRegime(input).regime;
  }

  /** Режимът ЗАЕДНО с допускането, което е трябвало да се приложи, за да се стигне до него. */
  private static final class RegimeReading {

    final Regime regime;

    /** Ключът от {@link #ASSUMPTIONS}, или {@code null} ако нищо не е допускано. */
    final String assumption;

    RegimeReading(Regime regime, String assumption) {
      this.regime = regime;
      this.assumption = assumption;
    }
  }

  private static RegimeReading readRegime(BgPayrollInput input) {
    if (input == null || input.contractHoursPerDay == null) {
      return new RegimeReading(Regime.UNKNOWN, null);
    }
    // ⚠️ Нулата вече идва като null от сглобителя (генерираният getter връща ZERO за непопълнено
    // поле). Отрицателното е данна грешка и също е незнание, а не „много непълно“.
    if (input.contractHoursPerDay.signum() <= 0) {
      return new RegimeReading(Regime.UNKNOWN, null);
    }
    // Намален брой ЧАСОВЕ — чл. 138 КТ. Стига сам по себе си.
    if (input.contractHoursPerDay.compareTo(STATUTORY_DAILY_HOURS) < 0) {
      return new RegimeReading(Regime.PART, null);
    }
    // Пълна дневна продължителност. Остава вторият път към непълното работно време: намален брой
    // ДНИ по чл. 138 ал. 1 КТ.
    BigDecimal daysPerWeek = input.contractDaysPerWeek;
    if (daysPerWeek == null || daysPerWeek.signum() <= 0) {
      // ⚠️ ОБЯВЕНО ДОПУСКАНЕ, не подразбиране: липсата се чете като пълна седмица И СЕ КАЗВА.
      return new RegimeReading(Regime.FULL, assume("contractDaysPerWeek"));
    }
    return new RegimeReading(
        daysPerWeek.compareTo(STATUTORY_WEEKLY_DAYS) < 0 ? Regime.PART : Regime.FULL, null);
  }

