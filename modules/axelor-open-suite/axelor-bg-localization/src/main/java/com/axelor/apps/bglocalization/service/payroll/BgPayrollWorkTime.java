/**
 * ОТ КОНТРАКТА КЪМ ПРОПОРЦИЯТА: {@link BgPayrollInput} → {@link BgWorkTimeFacts}.
 *
 * <p><b>Защо е отделен клас.</b> {@link BgPayrollInput} е СТРУКТУРА и не бива да получи поведение —
 * контрактът сам го обявява и {@code BgPayrollInputContractTest.theContractCarriesNoLogic()} го
 * пази. Изборът между НЕВД чл. 1 ал. 4 и ал. 3 обаче е точно поведение. Затова живее тук, до
 * сглобителя, а не в контракта и не в {@code BgInsurableIncomeService}: там влиза вече готовият
 * набор факти.
 *
 * <p><b>⚠️ КРИТЕРИЙ, А НЕ НАЛИЧНОСТ НА ДАННИ.</b> Първата версия избираше часовия ред, „когато има
 * часови данни“, и дневния — „когато часовете са неизползваеми“. Това е избор по това какво е
 * попълнено, а нормата дава КРИТЕРИЙ: ал. 4 се прилага заради РЕЖИМА на работното време. Разликата
 * не е педантизъм и се мери в пари — виж {@link #decide}.
 *
 * <p><b>НЕВД чл. 1, дословно</b> (обн. ДВ бр. 263/1999, ред. 2024 — цитат от акта, не извод от
 * справка):
 *
 * <blockquote>
 *
 * <p><b>ал. 3:</b> „Минималният месечен осигурителен доход … за лицата, които не са отработили
 * всичките дни през месеца или са се намирали в отпуски, извън посочените в ал. 2, се определя
 * пропорционално на отработените дни и дните по чл. 40, ал. 5 от Кодекса за социално осигуряване
 * през месеца. В тези случаи … се раздели на броя на РАБОТНИТЕ ДНИ през месеца и получената сума се
 * умножи по броя на отработените дни и дните на отпуските, посочени в ал. 2 …“
 *
 * <p><b>ал. 4:</b> „Минималният месечен осигурителен доход …, КОГАТО СЪГЛАСНО УСЛОВИЯТА НА ТРУДОВИЯ
 * ДОГОВОР ИЛИ ЧЛ. 138, АЛ. 2 ОТ КОДЕКСА НА ТРУДА ЛИЦЕТО Е РАБОТИЛО ПРИ НЕПЪЛНО РАБОТНО ВРЕМЕ, се
 * определя пропорционално на отработените часове и часовете, съответстващи на дните по чл. 40, ал.
 * 5 … се раздели на броя на ЗАКОНОУСТАНОВЕНИТЕ РАБОТНИ ЧАСОВЕ ЗА МЕСЕЦА и получената сума се умножи
 * по броя на отработените часове за месеца … По този ред се определя и минималният месечен
 * осигурителен доход, когато лицето се е намирало в отпуски извън посочените в ал. 2 ИЛИ НЕ Е
 * ОТРАБОТИЛО ВСИЧКИ РАБОТНИ ДНИ ПРЕЗ МЕСЕЦА.“
 *
 * </blockquote>
 *
 * <p>Оттам следват три неща, и всяко от тях е закован тест:
 *
 * <ol>
 *   <li>ал. 4 се прилага заради РЕЖИМА, не заради наличието на часови данни;
 *   <li>при непълно работно време часовият ред важи ДОРИ при неотработени дни — последното
 *       изречение на ал. 4 го казва изрично, тоест неотработените дни НЕ прехвърлят случая към ал.
 *       3;
 *   <li>ал. 3 остава за ПЪЛНОТО работно време, и то само при неотработени всички дни.
 * </ol>
 *
 * <p><b>Двата пътя към непълното работно време.</b> Чл. 138 КТ допуска намален брой ЧАСОВЕ и
 * намален брой ДНИ, тоест договор от 8 часа на ден и 3 дни на седмица е непълно работно време.
 * Затова контрактът носи {@link BgPayrollInput#contractDaysPerWeek} — без него този режим не е
 * изразим. ⚠️ Аритметиката при 8 часа на ден е една и съща по двата реда; различава се само пътят
 * на „не знам“, и точно там е рискът. Виж {@link #regimeOf}.
 *
 * <p><b>Нищо не се пропорционира при непълни данни, и нищо не пада по подразбиране.</b> Три изхода:
 * набор факти, набор БЕЗ пропорция с обявена причина, или ОТКАЗ, който казва какво липсва — плюс
 * ОБЯВЕНО ДОПУСКАНЕ, което се носи през решението и се вижда в изхода ({@link #ASSUMPTIONS}). Вижте
 * {@link Decision}. Мълчаливото подразбиране е точно това, което прагът не бива да прави: и „не
 * знам“, и „цял месец“ дават един и същ резултат днес и различен утре.
 */
