package com.axelor.apps.bglocalization.service.art49;

import com.axelor.apps.bglocalization.service.BgPaySlipResolver;
import java.math.BigDecimal;
import java.time.LocalDate;
import java.time.Month;

/**
 * КОГА И В КОЯ ПОСОКА ЛЯГА ИЗРАВНЯВАНЕТО ПО ЧЛ. 49 — правилото на перото, без база и без Guice.
 *
 * <p>Сметката вече е направена и ЗАПИСАНА ({@link BgArt49Recalculation} → {@code
 * BgArt73Para6Annual}). Тук не се смята нищо: отговаря се на трите въпроса, които стоят между
 * готовото число и реда на фиша — НА КОЙ ФИШ, В КОЯ ПОСОКА и С КАКВО ИМЕ.
 *
 * <p><b>═══ ⚠️ ЗАЩО ЯНУАРИ, А НЕ ДЕКЕМВРИ ═══</b>
 *
 * <p>Чл. 49 ал. 5 и ал. 6 дават СРОК („до 31 януари на следващата година“), не период — а перото
 * иска период. Периодът се доказва от ДРУГ член: чл. 65 ал. 11, изр. 2, дословно — „Работодателят
 * по основното трудово правоотношение внася данъка по чл. 49, ал. 5 в срок до <b>25 февруари</b> на
 * следващата година.“ Общото правило в същата алинея е „до 25-о число на месеца, СЛЕДВАЩ месеца,
 * през който данъкът е удържан“. Тоест 25 февруари ⇔ удържан през ЯНУАРИ. Декемврийско удържане би
 * искало внасяне до 25 януари и би противоречало на изричното изр. 2.
 *
 * <p><b>⚠️ И ДАННИТЕ НАЛАГАТ СЪЩОТО, НЕЗАВИСИМО ОТ НОРМАТА.</b> Справката по чл. 73 ал. 6 чете само
 * фишове в състояние ПОТВЪРДЕН или ПЛАТЕН ({@code BgArt73Para6ReportService#slipsByEmployee}),
 * тоест декемврийският фиш трябва да е ПОТВЪРДЕН, преди годишният данък изобщо да съществува. Перо
 * върху него би искало сметката да се направи наново, върху фиш в чернова — тоест да се дублира.
 * Двата независими довода сочат един и същ месец и точно това ги прави проверими.
 *
 * <p><b>⚠️ ЕДИН ЛИПСВАЩ НОСИТЕЛ, ОБЯВЕН, А НЕ ПОКРИТ.</b> Лице с договор, свършващ ТОЧНО на 31
 * декември, е работодател по основно ТПО към 31 декември ({@link BgArt49MainEmployer#contractAt}
 * пуска {@code end == 31.12}) и получава ред в справката — но НЯМА януарски фиш, върху който
 * изравняването да легне. Тук това не се лекува: генераторът се вика ОТ фиш, а фиш няма. Дупката е
 * закована със свидетел ({@code BgArt49SettlementGeneratorTest}) и остава въпрос към възложителя —
 * решението ѝ е от страната на СПРАВКАТА (тя знае за лицето), не от страната на фиша.
 */
public final class BgArt49Settlement {

  private BgArt49Settlement() {}

  /**
   * МЕСЕЦЪТ НА ИЗРАВНЯВАНЕТО — януари. Виж класовия javadoc за двата независими довода.
   *
   * <p>⚠️ Назован, а не написан като {@code == 1} на място: числото 1 в сравнение с месец се чете
   * еднакво добре като „януари“ и като „първи период на годината“, а второто е ДРУГО правило (фирма
   * със заплатна година, започваща през юли, има първи период юли). Периодът тук е КАЛЕНДАРЕН,
   * защото такива са и 31 декември на чл. 49 ал. 1, и 25 февруари на чл. 65 ал. 11.
   */
  public static final Month SETTLEMENT_MONTH = Month.JANUARY;

  /**
   * Този период ли носи изравняването — януари по КАЛЕНДАРНОТО начало на периода.
   *
   * @param periodStart началната дата на периода на фиша; {@code null} се чете като „не“
   */
  public static boolean isSettlementPeriod(LocalDate periodStart) {
    return periodStart != null && periodStart.getMonth() == SETTLEMENT_MONTH;
  }

  /**
   * ДАНЪЧНАТА ГОДИНА, КОЯТО СЕ ИЗРАВНЯВА — предходната спрямо периода.
   *
   * <p>⚠️ Не се пита фишът за „неговата“ година: изравняването НИКОГА не е за годината на фиша.
   * Януари 2027 изравнява 2026 — и точно затова справката, която се търси, е за 2026.
   *
   * @return годината, или {@code null}, когато периодът не е януарски
   */
  public static Integer settledTaxYear(LocalDate periodStart) {
    return isSettlementPeriod(periodStart) ? periodStart.getYear() - 1 : null;
  }

  /**
   * ПОСОКАТА НА ПЕРОТО ПО ЗНАКА НА КОЛОНА 19.
   *
   * <p>Положителна колона 19 значи ДОВНАСЯНЕ — годишният данък е по-висок от авансово удържания, —
   * тоест разликата се УДЪРЖА от лицето (чл. 49 ал. 5) и перото е DEBIT: нетото пада. Отрицателна
   * значи ВЪЗСТАНОВЯВАНЕ по ал. 6 и перото е CREDIT: нетото расте.
   *
   * <p><b>⚠️ ТОВА Е ОБРАТНОТО НА {@code BgPaySlipResolver#deltaSign}, И РАЗЛИКАТА НЕ Е ГРЕШКА.</b>
   * Двете функции изглеждат като едно и също правило („знак по знака на числото“) и връщат ПРОТИВНИ
   * отговори за едно и също число. Причината е, че двете числа мерят различни неща: ретро-делтата е
   * ПАРИ КЪМ ЛИЦЕТО (положителна = получава, тоест CREDIT), а колона 19 е ДАНЪК ОТ ЛИЦЕТО
   * (положителна = дължи, тоест DEBIT). Преизползвана, {@code deltaSign} щеше да върне пари на
   * всеки, който дължи, и да удържи от всеки, на когото се възстановява — при това мълчаливо, с
   * вярна абсолютна стойност на фиша.
   */
  public static String sign(BigDecimal settlement) {
    return settlement != null && settlement.signum() > 0
        ? BgPaySlipResolver.DEBIT
        : BgPaySlipResolver.CREDIT;
  }

  /** Довнасяне ли е — за текстовете, които различават двете посоки с ДУМА, а не със знак. */
  public static boolean isWithholding(BigDecimal settlement) {
    return settlement != null && settlement.signum() > 0;
  }

  /**
   * ИМЕТО НА РЕДА, КАКТО ГО ЧЕТЕ ЧОВЕК НА ФИША — с ГОДИНАТА и с ПОСОКАТА.
   *
   * <p>⚠️ Годината влиза в името, не само в бележката. Фишът се подписва, а ред „Годишно
   * изравняване по чл. 49 ЗДДФЛ“ върху януарски фиш не казва КОЯ година се изравнява — а точно това
   * е първият въпрос на всеки, който го гледа. Същият довод като при {@code
   * BgPaySlipResolver#deltaLineName}.
   *
   * <p>⚠️ И посоката се пише с ДУМА, защото знакът на перото не се вижда на хартията: колоната
   * показва число, а дали то е удържано или върнато решава DEBIT/CREDIT — величина, която печатът
   * подрежда, но не назовава.
   */
  public static String lineName(int taxYear, BigDecimal settlement) {
    return "Годишно изравняване по чл. 49 ЗДДФЛ за "
        + taxYear
        + (isWithholding(settlement) ? " (доплащане)" : " (възстановяване)");
  }
}
