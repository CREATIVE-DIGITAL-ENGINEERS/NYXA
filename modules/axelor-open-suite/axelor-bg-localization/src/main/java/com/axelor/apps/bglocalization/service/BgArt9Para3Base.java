package com.axelor.apps.bglocalization.service;

import java.math.BigDecimal;
import java.math.RoundingMode;
import java.util.Collections;
import java.util.LinkedHashMap;
import java.util.Map;

/**
 * ОСИГУРИТЕЛНАТА БАЗА ЗА ПЕРИОДА ПО КСО ЧЛ. 9 АЛ. 3 Т. 1 И Т. 2 — чиста, без база и без Guice.
 *
 * <p><b>Какъв въпрос отговаря този клас и защо е ОТДЕЛЕН от сумата на обезщетението.</b> При чл.
 * 213, чл. 214 и чл. 225 ал. 1 КТ има ДВЕ различни числа за едни и същи месеци, и те съвпадат само
 * по случайност:
 *
 * <ol>
 *   <li>КОЛКО СЕ ПЛАЩА на лицето — брутното трудово възнаграждение за времето без работа. Това е
 *       {@code BgCompensation.bgFinalAmount} и се смята от {@link BgCompensationResolver#compute}.
 *   <li>ВЪРХУ КАКВО СЕ ОСИГУРЯВА за същия период — ПОСЛЕДНОТО БРУТНО ВЪЗНАГРАЖДЕНИЕ, на месец. Това
 *       е числото тук.
 * </ol>
 *
 * <p><b>⚠️ И ДВЕТЕ НОРМИ СОЧАТ В ЕДНА ПОСОКА, ТОЕСТ ТОВА НЕ Е ПРОЧИТ ПО ПРЕЦЕНКА.</b>
 *
 * <p>НЕВД чл. 1 ал. 8 т. 7, дословно: „Не се изчисляват и внасят осигурителни вноски върху: … 7.
 * обезщетенията по чл. 200, <b>213, 214</b>, чл. 216, ал. 1, т. 1 и 2, ал. 2 и 3, чл. 220, 221, чл.
 * 222, ал. 2, 3 и 4, чл. 224, <b>225</b>, 226, чл. 232, ал. 2 и чл. 331 от Кодекса на труда“. Тоест
 * САМАТА ИЗПЛАТЕНА СУМА не е осигурителен доход.
 *
 * <p>КСО чл. 9 ал. 3 т. 1, дословно: „през което лицата … <b>не са работили поради незаконно
 * недопускане или отстраняване от работа</b> … за този период се внасят осигурителни вноски за
 * сметка на осигурителя … <b>върху последното брутно възнаграждение, ако лицето не е било
 * осигурявано; ако лицето е било осигурявано на друго основание, осигурителните вноски се внасят
 * върху РАЗЛИКАТА между последното брутно възнаграждение и осигурителния доход за периода, ако този
 * доход е по-малък</b>“. Т. 2 казва същото със същите думи за <b>уволнение, признато за
 * незаконно</b>; единствената разлика в текста е „осигурявано НА ДРУГО ОСНОВАНИЕ“ в т. 1 срещу
 * „осигурявано“ в т. 2.
 *
 * <p><b>⚠️ ЗАЩО ЧЛ. 217 И ЧЛ. 222 АЛ. 1 НЕ СА ТУК, макар и трите да са „не работи по вина на
 * работодателя“.</b> Те са по ДРУГИ точки на същата алинея и точките казват друго: т. 4 (чл. 217)
 * внася „за сметка на осигурителя <b>върху полагащото се обезщетение</b>“, а т. 5 (чл. 222 ал. 1,
 * чл. 106 ал. 2 ЗДСл, чл. 58 ал. 3 ЗВО) — „<b>върху получаваното обезщетение</b>“. За тях базата Е
 * сумата на перото и днешното ѝ държане е вярно. Списъкът тук е нарочно ЗАТВОРЕН и поименен:
 * правило „всяко обезщетение по чл. 9 ал. 3“ би вкарало и тези две точки и би сменило вярна база с
 * невярна.
 *
 * <p><b>⚠️ КАКВО ТОЗИ КЛАС НЕ ПРАВИ.</b> Не решава НАБОРА ФОНДОВЕ и не смята вноски. КСО чл. 9 ал.
 * 5 ограничава дължимото по цялата ал. 3 до фонд „Пенсии“ (съотв. фонда по чл. 69), ДЗПО и
 * Учителския пенсионен фонд — тоест БЕЗ ОЗМ, безработица, ТЗПБ и ЗОВ, и изцяло за сметка на
 * осигурителя. Тези ставки вече ги ИМА в {@code bg_insurance_contribution} под вид осигурен 18
 * (редове IC-112 … IC-126) и се четат от {@link BgInsuranceCalculationService#calculate} по {@code
 * bgCompensationTypeCode}. Какво липсва, за да се навържат, е записано в {@link
 * #refuseUnmodelledRegime}.
 */
public final class BgArt9Para3Base {

  private BgArt9Para3Base() {}

  /** Незаконно НЕДОПУСКАНЕ или ОТСТРАНЯВАНЕ от работа — чл. 213 ал. 1 и ал. 2, чл. 214 КТ. */
  public static final String POINT_1 = "КСО чл. 9 ал. 3 т. 1";

  /** Уволнение, признато за НЕЗАКОННО — чл. 225 ал. 1 КТ. */
  public static final String POINT_2 = "КСО чл. 9 ал. 3 т. 2";

  /**
   * ВИДОВЕТЕ, ЧИЯТО ОСИГУРИТЕЛНА БАЗА Е ПОСЛЕДНОТО БРУТНО, а не изплатената сума — по код и по
   * точка.
   *
   * <p>⚠️ Кодовете са ключът, не {@code legalBasis}: основанието е свободен текст на екрана, а
   * кодът е това, по което {@code bg_insurance_contribution.bgCompensationTypeCode} вече свързва
   * редовете със ставки. Едни и същи четири низа на двете места значат, че данните и правилото не
   * могат да се разминат по правопис.
   *
   * <p>⚠️ Разделянето на чл. 213 на ДВА кода е на каталога, не тук: ал. 1 плаща БТВ „за съответната
   * длъжност“ (лицето още не е работило), ал. 2 — собственото БТВ на лицето. Разликата е в това КОЕ
   * БТВ се взема, не в това ДАЛИ то е базата, затова и двата стоят под една точка.
   */
  private static final Map<String, String> POINT_BY_CODE;

  static {
    Map<String, String> byCode = new LinkedHashMap<>();
    byCode.put("comp_kt_213_1", POINT_1); // чл. 213 ал. 1 КТ — недопускане преди постъпване
    byCode.put("comp_kt_213_2", POINT_1); // чл. 213 ал. 2 КТ — недопускане по време на ТПО
    byCode.put("comp_kt_214", POINT_1); // чл. 214 КТ — незаконно отстраняване
    byCode.put("comp_kt_225_1", POINT_2); // чл. 225 ал. 1 КТ — незаконно уволнение
    POINT_BY_CODE = Collections.unmodifiableMap(byCode);
  }

  /**
   * Точката на КСО чл. 9 ал. 3 за този вид обезщетение, или {@code null}, ако не е по т. 1/т. 2.
   */
  public static String pointFor(String compensationTypeCode) {
    return compensationTypeCode == null ? null : POINT_BY_CODE.get(compensationTypeCode.trim());
  }

  /**
   * ОСИГУРЯВА ЛИ СЕ ТОЗИ ВИД ВЪРХУ ПОСЛЕДНОТО БРУТНО, вместо върху изплатената сума.
   *
   * <p>⚠️ {@code false} тук НЕ значи „не се осигурява“. Значи само „не по т. 1 и не по т. 2“ — чл.
   * 217 и чл. 222 ал. 1 се осигуряват, но върху себе си.
   */
  public static boolean basedOnLastGross(String compensationTypeCode) {
    return pointFor(compensationTypeCode) != null;
  }

  /**
   * БАЗАТА ЗА ЕДИН МЕСЕЦ ОТ ПРИЗНАТИЯ ПЕРИОД. {@code null} значи „не може да се определи“, НЕ нула.
   *
   * <p>Двете хипотези на нормата, в реда, в който тя ги казва:
   *
   * <ul>
   *   <li>лицето НЕ е било осигурявано ({@code insuredIncomeForTheMonth == null}) → цялото последно
   *       брутно възнаграждение;
   *   <li>лицето Е било осигурявано → РАЗЛИКАТА, и то само „ако този доход е по-малък“. Доход,
   *       равен на последното брутно или по-голям от него, не отговаря на условието — тогава по
   *       тази алинея не се дължи нищо и базата е НУЛА, а не отрицателно число.
   * </ul>
   *
   * <p>⚠️ Нулата тук е ЗАКОННА нула и се различава от {@code null}: първата значи „условието на
   * нормата не е изпълнено, вноска не се дължи“, втората — „последното брутно не е известно“.
   * Слети, непопълнена база би минала за месец без задължение.
   *
   * @param lastMonthlyGross последното брутно месечно възнаграждение по чл. 228 ал. 1 КТ — същото
   *     число, което документът пази в {@code bgBaseMonthGross}
   * @param insuredIncomeForTheMonth осигурителният доход на лицето за месеца на ДРУГО основание,
   *     или {@code null}, когато лицето не е било осигурявано
   */
  public static BigDecimal monthlyBase(
      BigDecimal lastMonthlyGross, BigDecimal insuredIncomeForTheMonth) {
    if (lastMonthlyGross == null || lastMonthlyGross.signum() < 0) {
      return null;
    }
    BigDecimal base = lastMonthlyGross;
    if (insuredIncomeForTheMonth != null) {
      base =
          insuredIncomeForTheMonth.compareTo(lastMonthlyGross) < 0
              ? lastMonthlyGross.subtract(insuredIncomeForTheMonth)
              : BigDecimal.ZERO;
    }
    return base.setScale(2, RoundingMode.HALF_UP);
  }

  /**
   * БАЗАТА ЗА ЦЕЛИЯ ПРИЗНАТ ПЕРИОД — месечната база, умножена по броя месеци.
   *
   * <p><b>⚠️ СБОРЪТ НЕ Е ЕДНА МЕСЕЧНА БАЗА, И НЕ Е ЕДНО ЧИСЛО ЗА ДЕКЛАРАЦИЯТА.</b> Периодът по чл.
   * 9 ал. 3 обхваща МИНАЛИ месеци и всеки от тях иска СВОЙ запис в Декларация обр. 1 с вид осигурен
   * 18. Този метод дава сбора, за да може той да се СРАВНИ с изплатената сума — не за да се
   * декларира наведнъж в месеца на плащането. Разписването по месеци е отделна работа и е назовано
   * в {@link #refuseUnmodelledRegime}.
   *
   * @param months броят месеци от признатия период; {@code null} или неположително → {@code null}
   */
  public static BigDecimal periodBase(
      BigDecimal lastMonthlyGross, BigDecimal months, BigDecimal insuredIncomeForTheMonth) {
    BigDecimal monthly = monthlyBase(lastMonthlyGross, insuredIncomeForTheMonth);
    if (monthly == null || months == null || months.signum() <= 0) {
      return null;
    }
    return monthly.multiply(months).setScale(2, RoundingMode.HALF_UP);
  }

  /**
   * ОТКАЗЪТ, КОГАТО ФИШ НОСИ ТАКОВА ОБЕЗЩЕТЕНИЕ. Връща причината, или {@code null}, ако видът не е
   * по т. 1/т. 2.
   *
   * <p><b>⚠️ ЗАЩО ОТКАЗ, А НЕ ТИХА ПОПРАВКА НА БАЗАТА.</b> Днес перото на обезщетението носи {@code
   * bgIsInsuranceIncome = true} (речникът, редове 907, 911, 912 и 913) и затова цялата му сума
   * влиза в {@code BgPaySlipResolver#insuranceIncomeBase} — тоест в базата, върху която се смятат
   * ОБИКНОВЕНИТЕ вноски по вид осигурен 01 и която пълни т. 21 на Д1. И двете са невярни: сумата не
   * е осигурителен доход (НЕВД чл. 1 ал. 8 т. 7), наборът фондове е друг (КСО чл. 9 ал. 5) и
   * платецът е само осигурителят.
   *
   * <p>Да се извади само перото от базата би заменило ЗАВИШЕНА вноска с НУЛЕВА — и то мълчаливо,
   * защото задължението по чл. 9 ал. 3 никъде другаде не се поражда. Затова тук се отказва:
   * числото, което Е дължимо, се назовава в самото съобщение, а какво липсва, за да се сметне само,
   * е изброено поименно.
   *
   * @param reference номерът на документа — фишът може да носи няколко обезщетения
   * @param compensationTypeCode кодът от каталога
   * @param legalBasis основанието за човека („чл. 225 ал. 1 КТ“)
   * @param paidAmount замразената сума на документа — това, което днес влиза в базата
   * @param lastMonthlyGross {@code bgBaseMonthGross} на документа, или {@code null}
   * @param months {@code bgQuantity} на документа в месеци, или {@code null}
   */
  public static String refuseUnmodelledRegime(
      String reference,
      String compensationTypeCode,
      String legalBasis,
      BigDecimal paidAmount,
      BigDecimal lastMonthlyGross,
      BigDecimal months) {

    String point = pointFor(compensationTypeCode);
    if (point == null) {
      return null;
    }
    BigDecimal owed = periodBase(lastMonthlyGross, months, null);
    return "обезщетението „"
        + reference
        + "“ ("
        + legalBasis
        + ") се осигурява по "
        + point
        + " — ВЪРХУ ПОСЛЕДНОТО БРУТНО ВЪЗНАГРАЖДЕНИЕ за всеки месец от признатия период, а НЕ върху"
        + " изплатената сума. Върху самото обезщетение вноски не се дължат (НЕВД чл. 1 ал. 8 т. 7),"
        + " а перото на фиша днес влиза в осигурителния доход с цялата си сума "
        + money(paidAmount)
        + " — тоест вноските излизат по вид осигурен 01, с целия пакет ДОО и с част за лицето."
        + " Дължимото е друго: "
        + (owed == null
            ? "база по последното брутно, която НЕ може да се сметне от този документ"
            : "база "
                + money(owed)
                + " ("
                + money(lastMonthlyGross)
                + " × "
                + count(months)
                + " месеца)")
        + ", само за фонд „Пенсии“ и ДЗПО (КСО чл. 9 ал. 5), ИЗЦЯЛО за сметка на осигурителя, по вид"
        + " осигурен 18. Ставките ги има в bg_insurance_contribution, но НЕ СА НАВЪРЗАНИ:"
        + " BgPaySlipService подава STANDARD за целия фиш, липсват и признатият период по месеци, и"
        + " осигурителният доход на лицето на друго основание за същите месеци, и отделен запис в Д1"
        + " за всеки минал месец. Фишът се отказва, вместо да начисли завишена вноска по грешния"
        + " набор фондове или пък мълчаливо нула. Изплатете обезщетението извън този фиш, докато"
        + " режимът по чл. 9 ал. 3 не бъде построен.";
  }

  /** Сума за съобщението — ВИНАГИ с два знака, защото е пари. {@code null} → „неизвестно“. */
  private static String money(BigDecimal value) {
    return value == null ? "неизвестно" : value.setScale(2, RoundingMode.HALF_UP).toPlainString();
  }

  /** Брой месеци за съобщението — без опашка от нули, защото не е сума. */
  private static String count(BigDecimal value) {
    return value == null ? "неизвестно" : value.stripTrailingZeros().toPlainString();
  }
}
