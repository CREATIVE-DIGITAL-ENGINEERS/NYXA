package com.axelor.apps.bglocalization.report;

/** Logical names of the Bulgarian VAT/NAP BIRT reports (files under src/main/resources/reports). */
public interface IReport {

  String BG_VAT_SALES_DIARY = "BgVatSalesDiary.rptdesign";
  String BG_VAT_PURCHASE_DIARY = "BgVatPurchaseDiary.rptdesign";
  // СД (справка-декларация) 1:1 layout — deferred until the official НАП образец is available.
  String BG_VAT_DECLARATION = "BgVatDeclaration.rptdesign";

  /**
   * Декларация обр. № 1 по Наредба Н-13 — ПЕЧАТНИЯТ образец.
   *
   * <p>⚠️ Той не е „докато чакаме файла“. Чл. 8 ал. 1 т. 1 разрешава подаване на ХАРТИЕН носител,
   * тоест печатът е уреден път сам по себе си. Файлът за електронно подаване чака ЗАПОВЕД по чл. 8
   * ал. 5 и затова го няма — виж BgD1RecordAdapter.
   */
  String BG_D1_DECLARATION = "BgD1Declaration.rptdesign";

  /**
   * Декларация обр. № 6 по Наредба Н-13 — ПЕЧАТНИЯТ образец.
   *
   * <p>⚠️ ФОРМУЛЯР, А НЕ ТАБЛИЦА, и това не е оформление. Д6 е агрегат на ДРУЖЕСТВОТО — един ред за
   * месеца, а не по един на лице. Отчет, построен по образеца на Д1 (таблица с детайлен ред), би
   * поискал дъщерни записи, които не съществуват, и щеше да излезе с една безименна редица числа.
   */
  String BG_D6_DECLARATION = "BgD6Declaration.rptdesign";

  /**
   * ФИШЪТ ЗА ЗАПЛАТА — печатният образец на ЕДИН разчетен лист.
   *
   * <p>⚠️ ЕДИН ФИШ, А НЕ ВЕДОМОСТ. Двете не са едно нещо с различна ширина: фишът е документът НА
   * ЛИЦЕТО (КТ чл. 128 т. 3 — работодателят е длъжен да издава извлечение за платеното) и носи
   * перата му поотделно; ведомостта е документ на предприятието и сумира по колони. Отчет, който се
   * опитва и двете, дава лист, на който нито едното не се чете.
   *
   * <p>⚠️ И ЗАКОНЕН ОБРАЗЕЦ НЯМА. За Д1/Д6 съществува приложение към Наредба Н-13 и оформлението се
   * сверява точка по точка срещу него; за фиша нормата казва КАКВО се дължи на лицето, а не как
   * изглежда листът. Затова редът тук следва въпроса, който човек задава на фиша си: какво ми е
   * начислено, какво ми е удържано, колко получавам.
   */
  String BG_PAY_SLIP = "BgPaySlip.rptdesign";

  /**
   * РАЗЧЕТНО-ПЛАТЕЖНАТА ВЕДОМОСТ — печатният регистър на ЦЕЛИЯ период.
   *
   * <p>⚠️ ДРУГИЯТ ДОКУМЕНТ, А НЕ ФИШЪТ В ШИРОК ФОРМАТ — точно разграничението, което {@link
   * #BG_PAY_SLIP} по-горе вече прави, погледнато от другата страна. Фишът е документът НА ЛИЦЕТО и
   * носи перата му поотделно; ведомостта е документът НА ПРЕДПРИЯТИЕТО: по един ред на лице и по
   * една колона на въпрос (начислено, удържано от лицето, за сметка на работодателя, данък, нето),
   * плюс ред „общо“, който се сверява със счетоводната статия и с платежния файл.
   *
   * <p>⚠️ И ТУК ЗАКОНЕН ОБРАЗЕЦ НЯМА, както го няма и за фиша. Колоните следват образеца на
   * Микроинвест, защото той е онова, което българското ТРЗ разпознава — а не защото някаква норма
   * ги изброява. Единственото, което нормата дава, е СЪДЪРЖАНИЕТО на дължимото; какво стои в коя
   * графа е избор на продукта и се сверява с очи, не с член.
   *
   * <p>⚠️ ПЕТТЕ РАЗРЕЗА НА ОБРАЗЕЦА СА ЕДИН ФАЙЛ С ПАРАМЕТЪР, А НЕ ПЕТ ФАЙЛА. Колоните им са едни и
   * същи; различава се само кои редове влизат — а това се решава в Java (виж {@code
   * BgPayrollLedgerSelection}) и се подава като списък от номера на фишове. Пет копия на един
   * образец биха се разминали при първата промяна на колона, и то само в четири от петте.
   */
  String BG_PAYROLL_LEDGER = "BgPayrollLedger.rptdesign";

  /**
   * ПРОТОКОЛЪТ ПО ЧЛ. 117 ЗДДС — печатният лист на ЕДИН протокол (ВОП, услуга по чл. 82, чл. 163а,
   * внос по чл. 167а).
   *
   * <p>⚠️ ЗАКОНЕН ОБРАЗЕЦ НЯМА — законът изброява реквизитите (чл. 117 ал. 2 т. 1–10), не вида на
   * листа. Затова всеки ред на образеца носи номера на точката, която покрива: проверката е „има ли
   * т. N и стойност до нея“, а не сверка с бланка.
   *
   * <p>⚠️ БЕЗ НАБОР ДАННИ ОТ БАЗАТА. Стойностите идват като параметри от {@code
   * BgVatProtocolPrint#params()} — числата на реда в дневниците, вече закръглени и форматирани.
   */
  String BG_VAT_PROTOCOL = "BgVatProtocol.rptdesign";
}
